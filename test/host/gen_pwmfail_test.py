#!/usr/bin/env python3
"""Builds a host test for a PWM update the LEDC timer refuses (aux_io.c).

pwm_set(), pwm_put_duty() and duty_ticks() are cut out of aux_io.c verbatim;
the LEDC driver is a stub that keeps the channel's state and can be told to
refuse a timer configuration.

What it pins down, found by a review: a change of frequency that needs a new
resolution stops the channel (held low) before reconfiguring the timer, and
when the timer refused, the function returned with the channel still
stopped -- while s_freq/s_duty, and so status, Modbus and MQTT, said the
old PWM was running. Now the old timer is put back and the old duty with it.
OLD=1 cuts aux_io.c from git (OLDREV, default HEAD).

  make -C test/host pwmfail
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("components/board/aux_io.c")
hdr  = Source.at("components/board/aux_io.h")
cuts  = hdr.defines("AUX_PWM_DUTY_MAX") + src.defines("PWM_MODE", "PWM_TIMER", "PWM_CHAN", "PWM_SRC_HZ", "PWM_BITS_MAX")
cuts += src.func("static uint32_t duty_ticks(uint16_t duty_pm, uint8_t bits)")
cuts += src.func("static void pwm_put_duty(uint8_t a, uint16_t duty, uint8_t bits)")
cuts += src.func("static esp_err_t pwm_set(uint8_t a, uint32_t freq, uint16_t duty, bool fresh)")

HARNESS = r"""
/* GENERATED by gen_pwmfail_test.py -- do not edit; edit aux_io.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define ESP_ERR_INVALID_ARG 0x102
typedef enum { LEDC_LOW_SPEED_MODE } ledc_mode_t;
typedef enum { LEDC_TIMER_0, LEDC_TIMER_1 } ledc_timer_t;
typedef enum { LEDC_CHANNEL_0, LEDC_CHANNEL_1 } ledc_channel_t;
typedef int ledc_timer_bit_t;
typedef enum { LEDC_USE_APB_CLK } ledc_clk_cfg_t;
typedef struct { ledc_mode_t speed_mode; ledc_timer_t timer_num; ledc_timer_bit_t duty_resolution; uint32_t freq_hz; ledc_clk_cfg_t clk_cfg; } ledc_timer_config_t;
typedef struct { int gpio_num; ledc_mode_t speed_mode; ledc_channel_t channel; ledc_timer_t timer_sel; uint32_t duty; int hpoint; } ledc_channel_config_t;
static int  refuse_timer;
static bool running; static uint32_t run_freq, run_bits, run_duty;
static uint32_t ledc_find_suitable_duty_resolution(uint32_t src, uint32_t f) { uint32_t b = 0; while (b < 20 && (src / f) >> (b + 1)) b++; return b; }
static esp_err_t ledc_timer_config(const ledc_timer_config_t *t) { if (refuse_timer) { refuse_timer--; return ESP_FAIL; } run_freq = t->freq_hz; run_bits = (uint32_t)t->duty_resolution; return ESP_OK; }
static esp_err_t ledc_channel_config(const ledc_channel_config_t *c) { (void)c; return ESP_OK; }
static esp_err_t ledc_stop(ledc_mode_t m, ledc_channel_t c, uint32_t lvl) { (void)m; (void)c; (void)lvl; running = false; return ESP_OK; }
static uint32_t pending;
static esp_err_t ledc_set_duty(ledc_mode_t m, ledc_channel_t c, uint32_t d) { (void)m; (void)c; pending = d; return ESP_OK; }
static esp_err_t ledc_update_duty(ledc_mode_t m, ledc_channel_t c) { (void)m; (void)c; run_duty = pending; running = true; return ESP_OK; }
static int s_gpio[3];
static uint32_t s_freq[3]; static uint16_t s_duty[3]; static uint8_t s_bits[3];

__CUT__

int main(void)
{
    int failures = 0;
    printf("PWM-Aenderung, die der LEDC-Timer ablehnt\n");
    if (pwm_set(0, 1000, 500, true) != ESP_OK || !running) { printf("  FEHLER: Start\n"); return 1; }
    uint32_t f0 = run_freq, d0 = run_duty;
    refuse_timer = 1;                      /* 20 kHz needs another resolution: stop, then refused */
    esp_err_t r = pwm_set(0, 20000, 500, false);
    if (r == ESP_OK) { failures++; printf("  FEHLER: abgelehnte Aenderung als ok gemeldet\n"); }
    if (!running) { failures++; printf("  FEHLER: Kanal bleibt gestoppt (Pin low), Status sagt %u Hz %u Promille\n", s_freq[0], s_duty[0]); }
    else if (run_freq != f0 || run_duty != d0 || s_freq[0] != 1000) { failures++; printf("  FEHLER: laeuft mit %u Hz / Tastung %u statt %u / %u\n", run_freq, run_duty, f0, d0); }
    if (!failures) printf("  abgelehnte Aenderung: alter Timer und alte Tastung laufen weiter, Status stimmt\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_pwmfail.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
