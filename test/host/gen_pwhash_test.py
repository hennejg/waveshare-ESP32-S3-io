#!/usr/bin/env python3
"""Builds a host test for how the web password is stored and checked (auth.c).

The password functions are cut out of auth.c verbatim; NVS is an in-memory
blob, mbedTLS is ESP-IDF's own (MD, SHA-256, PKCS5) built for the host.

What it pins down, found by a review: the password was stored as one round
of SHA-256(salt || password), so a flash dump could be attacked at GPU speed,
and compared with memcmp. Now PBKDF2-HMAC-SHA256 with the iteration count in
the blob; an old blob still logs in and is replaced at that login; a wrong
password never passes the RAM-only fast path.
OLD=1 cuts auth.c from git (OLDREV, default HEAD).

  make -C test/host pwhash
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("components/board/auth.c")
new = "static esp_err_t store_password(const char *pw)" in src.text
a = src.text.index("typedef struct {")
b = src.text.index("/* ---------------------------------------------------------------- token */")
cuts = src.defines("NVS_NS", "K_CRED") + src.text[a:b]

HARNESS = r"""
/* GENERATED by gen_pwhash_test.py -- do not edit; edit auth.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define MBEDTLS_ALLOW_PRIVATE_ACCESS   /* to leave a context as a failed setup does */
#include "mbedtls/md.h"
#include "mbedtls/pkcs5.h"
#include "mbedtls/constant_time.h"

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define ESP_ERR_NVS_NOT_FOUND 0x1102
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGE(...) ((void)0)
static const char *esp_err_to_name(esp_err_t e) { (void)e; return "?"; }
static void esp_fill_random(void *b, size_t n) { for (size_t i = 0; i < n; i++) ((uint8_t *)b)[i] = (uint8_t)rand(); }

/* NVS: one namespace, one blob. */
typedef int nvs_handle_t;
enum { NVS_READONLY, NVS_READWRITE };
static uint8_t blob[128]; static size_t blob_len; static int blob_set;
static esp_err_t nvs_open(const char *ns, int m, nvs_handle_t *h) { (void)ns; (void)m; *h = 1; return (blob_set || m == NVS_READWRITE) ? ESP_OK : ESP_ERR_NVS_NOT_FOUND; }
static esp_err_t nvs_get_blob(nvs_handle_t h, const char *k, void *v, size_t *n)
{ (void)h; (void)k; if (!blob_set) return ESP_ERR_NVS_NOT_FOUND; if (*n < blob_len) return ESP_FAIL; memcpy(v, blob, blob_len); *n = blob_len; return ESP_OK; }
static esp_err_t nvs_set_blob(nvs_handle_t h, const char *k, const void *v, size_t n)
{ (void)h; (void)k; memcpy(blob, v, n); blob_len = n; blob_set = 1; return ESP_OK; }
static esp_err_t nvs_commit(nvs_handle_t h) { (void)h; return ESP_OK; }
static void nvs_close(nvs_handle_t h) { (void)h; }

/* mbedTLS running out of memory, on demand. */
static int pbkdf2_fail;
static int pbkdf2_maybe_fail(mbedtls_md_type_t t, const unsigned char *p, size_t pl, const unsigned char *s,
                             size_t sl, unsigned int it, uint32_t kl, unsigned char *out)
{
    if (pbkdf2_fail) return MBEDTLS_ERR_MD_ALLOC_FAILED;
    return mbedtls_pkcs5_pbkdf2_hmac_ext(t, p, pl, s, sl, it, kl, out);
}
#define mbedtls_pkcs5_pbkdf2_hmac_ext pbkdf2_maybe_fail

/* mbedtls_md_setup() out of memory, as md.c leaves it: the digest set, its
   context NULL -- the next mbedtls_md_starts() dereferences that. Only the
   calls in auth.c are redirected; PBKDF2 inside the library is not. */
static int md_setup_fail;
static int md_setup_maybe_fail(mbedtls_md_context_t *ctx, const mbedtls_md_info_t *info, int hmac)
{
    if (!md_setup_fail) return mbedtls_md_setup(ctx, info, hmac);
    ctx->MBEDTLS_PRIVATE(md_info) = info;
    ctx->MBEDTLS_PRIVATE(md_ctx)  = NULL;
    return MBEDTLS_ERR_MD_ALLOC_FAILED;
}
#define mbedtls_md_setup md_setup_maybe_fail

__CUT__

static esp_err_t token_init(void) { return ESP_OK; }

/* A reboot: everything in RAM gone, the blob read again. */
#define REBOOT() do { memset(&s_pw_set, 0, sizeof s_pw_set); memset(s_pw_salt, 0, 16); memset(s_pw_hash, 0, 32); \
                      __RESET_NEW__ auth_init(); } while (0)

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Gespeichertes Web-Passwort\n");

    /* A blob as the first firmware wrote it: SHA-256(salt || password). */
    uint8_t salt[16]; for (int i = 0; i < 16; i++) salt[i] = (uint8_t)(i * 7);
    uint8_t v1[48]; memcpy(v1, salt, 16);
    mbedtls_md(mbedtls_md_info_from_type(MBEDTLS_MD_SHA256), (const uint8_t *)"\x00", 0, v1 + 16);
    {   mbedtls_md_context_t c; mbedtls_md_init(&c); mbedtls_md_setup(&c, mbedtls_md_info_from_type(MBEDTLS_MD_SHA256), 0);
        mbedtls_md_starts(&c); mbedtls_md_update(&c, salt, 16); mbedtls_md_update(&c, (const uint8_t *)"geheim123", 9);
        mbedtls_md_finish(&c, v1 + 16); mbedtls_md_free(&c); }
    memcpy(blob, v1, 48); blob_len = 48; blob_set = 1;
    REBOOT();
    CHECK(auth_is_password_set(), "alter Eintrag nicht erkannt");
    CHECK(!auth_check_password("falsch"), "falsches Passwort angenommen");
    CHECK(auth_check_password("geheim123"), "alter Eintrag: richtiges Passwort abgelehnt");
    CHECK(blob_len != 48, "alter SHA-256-Eintrag nach dem Login nicht ersetzt");
    REBOOT();
    CHECK(auth_check_password("geheim123"), "nach dem Ersetzen und Neustart: Passwort abgelehnt");
    CHECK(!auth_check_password("geheim124"), "nach Neustart: falsches Passwort angenommen");
    if (!failures) printf("  alter Eintrag: Login klappt, danach als PBKDF2 gespeichert\n");

    /* A new password: what lands in flash must be PBKDF2, not one SHA round. */
    int f0 = failures;
    auth_set_password("NeuesPasswort!");
    uint8_t ref[32], one[32];
    const uint8_t *bs = blob_len == 48 ? blob : blob + 8;           /* salt */
    const uint8_t *bh = blob_len == 48 ? blob + 16 : blob + 24;     /* hash */
    uint32_t iter = blob_len == 56 ? (uint32_t)(blob[4] | blob[5] << 8 | blob[6] << 16 | (uint32_t)blob[7] << 24) : 0;
    {   mbedtls_md_context_t c; mbedtls_md_init(&c); mbedtls_md_setup(&c, mbedtls_md_info_from_type(MBEDTLS_MD_SHA256), 0);
        mbedtls_md_starts(&c); mbedtls_md_update(&c, bs, 16); mbedtls_md_update(&c, (const uint8_t *)"NeuesPasswort!", 14);
        mbedtls_md_finish(&c, one); mbedtls_md_free(&c); }
    CHECK(memcmp(bh, one, 32) != 0, "neues Passwort als einfaches SHA-256 gespeichert");
    if (iter) {
        mbedtls_pkcs5_pbkdf2_hmac_ext(MBEDTLS_MD_SHA256, (const uint8_t *)"NeuesPasswort!", 14, bs, 16, iter, 32, ref);
        CHECK(memcmp(bh, ref, 32) == 0, "gespeicherter Hash ist nicht PBKDF2-HMAC-SHA256 mit %u Iterationen", iter);
        CHECK(iter >= 1000, "nur %u Iterationen", iter);
    } else CHECK(0, "kein PBKDF2-Eintrag (%zu Bytes)", blob_len);
    REBOOT();
    CHECK(auth_check_password("NeuesPasswort!") && !auth_check_password("geheim123"), "neues Passwort nach Neustart nicht gueltig oder altes noch gueltig");
    if (failures == f0) printf("  neues Passwort: PBKDF2-HMAC-SHA256, %u Iterationen, gilt nach Neustart\n", iter);

    /* The derivation fails while a new password is set. */
    f0 = failures;
    pbkdf2_fail = 1;
    int r = auth_set_password("Kaputt#1");
    pbkdf2_fail = 0;
    CHECK(r != ESP_OK, "fehlgeschlagene Ableitung als Erfolg gemeldet");
    CHECK(!auth_check_password("Kaputt#1"), "nicht gespeichertes Passwort gilt (RAM-Cache)");
    REBOOT();
    CHECK(auth_check_password("NeuesPasswort!"), "nach fehlgeschlagener Ableitung und Neustart: bisheriges Passwort abgelehnt");
    CHECK(!auth_check_password("Kaputt#1"), "nach Neustart: nicht gespeichertes Passwort gilt");
    if (failures == f0) printf("  fehlgeschlagene Ableitung: Aenderung abgelehnt, altes Passwort gilt weiter\n");

    /* SHA-256 cannot get its context (fast verifier, old entry). */
    f0 = failures;
    REBOOT();
    CHECK(auth_check_password("NeuesPasswort!"), "Ausgangslage: Passwort abgelehnt");   /* sets the fast verifier */
    md_setup_fail = 1;
    CHECK(auth_check_password("NeuesPasswort!"), "SHA-Kontext fehlt: richtiges Passwort abgelehnt (PBKDF2 muss tragen)");
    CHECK(!auth_check_password("falsch"), "SHA-Kontext fehlt: falsches Passwort angenommen");
    CHECK(!s_fast_ok, "SHA-Kontext fehlt: schneller Pruefwert gilt als berechnet");
    md_setup_fail = 0;
    CHECK(!auth_check_password("falsch") && auth_check_password("NeuesPasswort!"),
          "nach dem Speichermangel: Pruefung falsch");
    CHECK(s_fast_ok, "nach dem Speichermangel: schneller Pruefwert nicht neu berechnet");
    memcpy(blob, v1, 48); blob_len = 48; blob_set = 1;
    REBOOT();
    md_setup_fail = 1;
    CHECK(!auth_check_password("geheim123") && blob_len == 48, "SHA-Kontext fehlt: alter Eintrag ohne Hash angenommen oder ersetzt");
    md_setup_fail = 0;
    CHECK(auth_check_password("geheim123"), "alter Eintrag nach dem Speichermangel abgelehnt");
    if (failures == f0) printf("  SHA-256 ohne Speicher: kein Absturz, Pruefwert ungueltig, PBKDF2 traegt\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
reset_new = "s_pw_v1 = false; s_pw_iter = 0; s_fast_ok = false;" if new else ""
out = pathlib.Path(__file__).with_name("test_pwhash.c")
out.write_text(HARNESS.replace("__CUT__", cuts).replace("__RESET_NEW__", reset_new))
print("erzeugt:", out.name)
