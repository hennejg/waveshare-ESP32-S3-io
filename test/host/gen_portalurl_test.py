#!/usr/bin/env python3
"""Builds a host test for how the setup portal routes a request
(wifi_config.c).

wifi_config_server_on_url() is cut out of wifi_config.c verbatim, with the
endpoint list; the parser is a struct with a method.

What it pins down, found by a review: the path was compared with strncmp()
bounded by the request's own length, so any start of a known path matched
it -- "POST /" was a settings update and "POST /e" switched WiFi off and
rebooted into Ethernet-only mode. Now only the whole path matches.
OLD=1 cuts wifi_config.c from git (OLDREV, default HEAD).

  make -C test/host portalurl
"""
import pathlib
from cutter import Source

src = Source.at("components/esp32-wifi-bootstrap/src/wifi_config.c")
c0 = src.type("} endpoint_t;")
c1 = (src.func("static bool url_is(const char *data, size_t length, const char *path)")
      if "static bool url_is(" in src.text else "")
c1 += src.func("static int wifi_config_server_on_url(http_parser *parser, const char *data, size_t length)")

HARNESS = r"""
/* GENERATED by gen_portalurl_test.py -- do not edit; edit wifi_config.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define DEBUG(...) ((void)0)
enum { HTTP_GET = 1, HTTP_POST = 3 };
typedef struct { int method; void *data; } http_parser;
static const char *http_method_str(int m) { return m == HTTP_GET ? "GET" : "POST"; }
__CUT0__
typedef struct { endpoint_t endpoint; } client_t;
__CUT1__

static endpoint_t route(int method, const char *url)
{
    client_t c = { .endpoint = ENDPOINT_UNKNOWN };
    http_parser p = { .method = method, .data = &c };
    wifi_config_server_on_url(&p, url, strlen(url));
    return c.endpoint;
}

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Routing im Einrichtungsportal\n");

    CHECK(route(HTTP_POST, "/settings") == ENDPOINT_SETTINGS_UPDATE, "POST /settings");
    CHECK(route(HTTP_POST, "/eth-only") == ENDPOINT_ETH_ONLY, "POST /eth-only");
    CHECK(route(HTTP_GET,  "/settings") == ENDPOINT_SETTINGS, "GET /settings");
    CHECK(route(HTTP_GET,  "/") == ENDPOINT_INDEX, "GET /");

    CHECK(route(HTTP_POST, "/") == ENDPOINT_UNKNOWN, "POST / gilt als Einstellungen speichern");
    CHECK(route(HTTP_POST, "/e") == ENDPOINT_UNKNOWN, "POST /e schaltet WLAN ab");
    CHECK(route(HTTP_POST, "/s") == ENDPOINT_UNKNOWN, "POST /s gilt als Einstellungen speichern");
    CHECK(route(HTTP_GET,  "/se") == ENDPOINT_UNKNOWN, "GET /se gilt als Einstellungsseite");
    CHECK(route(HTTP_POST, "/settingsX") == ENDPOINT_UNKNOWN, "POST /settingsX");
    if (!failures) printf("  nur der ganze Pfad zaehlt\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_portalurl.c")
out.write_text(HARNESS.replace("__CUT0__", c0).replace("__CUT1__", c1))
print("erzeugt:", out.name)
