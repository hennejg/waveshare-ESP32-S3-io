#!/usr/bin/env python3
"""Builds a host test for the physical-button token flow (components/board/auth.c).

Cut out of auth.c verbatim: the whole token section -- state, timers,
on_timeout(), on_blink(), begin, button press, status, consume, cancel. The
esp_timer API is a fake with a hand-driven clock whose callbacks run on
whichever thread the test fires them from; the FreeRTOS mutex is a pthread
mutex, so the HTTP handler and the esp_timer task really run side by side.

What it pins down, found by an outside review: the timeout callback (esp_timer
task) and the HTTP handlers shared the flow's state and timers without a
lock. A new /api/auth/begin that ran on the other core right after the
timeout had set TIMEOUT got its button handler and both timers torn down by
the old callback's cleanup: the new flow stayed WAITING, every further begin
answered "already pending", the button did nothing, until a reboot.
OLD=1 cuts the code from git (OLDREV, default HEAD) as it was before.

  make -C test/host auth
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/board/auth.c")
old  = os.environ.get("OLD") == "1"
if old:
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/board/auth.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

cuts  = src.func("static void to_hex(const uint8_t *b, size_t n, char *out)")
cuts += src.span("/* ---------------------------------------------------------------- token */",
                 "void auth_token_cancel(void)")
cuts += src.func("void auth_token_cancel(void)")[len("void auth_token_cancel(void)"):]

HARNESS = r"""
/* GENERATED by gen_auth_test.py -- do not edit; edit auth.c. */
#include <pthread.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include "auth.h"

#define TAG "auth"
#define ESP_LOGI(t, ...) ((void)(t))
#define ESP_LOGW(t, ...) ((void)(t))
#define ESP_LOGE(t, ...) ((void)(t))
static void esp_fill_random(void *b, size_t n) { for (size_t i = 0; i < n; i++) ((uint8_t *)b)[i] = (uint8_t)rand(); }

/* FreeRTOS: a mutex is a pthread mutex. */
typedef pthread_mutex_t  StaticSemaphore_t;
typedef pthread_mutex_t *SemaphoreHandle_t;
#define portMAX_DELAY 0
__attribute__((unused)) static SemaphoreHandle_t xSemaphoreCreateMutexStatic(StaticSemaphore_t *b) { pthread_mutex_init(b, NULL); return b; }
#define xSemaphoreTake(l, t) pthread_mutex_lock(l)
#define xSemaphoreGive(l)    pthread_mutex_unlock(l)

/* esp_timer: a hand-driven clock. */
typedef void (*esp_timer_cb_t)(void *);
typedef struct { esp_timer_cb_t callback; void *arg; const char *name; } esp_timer_create_args_t;
typedef struct esp_timer { esp_timer_cb_t cb; void *arg; bool armed, periodic, deleted; int64_t due, period; } *esp_timer_handle_t;
static pthread_mutex_t tm = PTHREAD_MUTEX_INITIALIZER;
static int64_t now_us;
static int created, deleted_n;
__attribute__((unused)) static int64_t esp_timer_get_time(void) { pthread_mutex_lock(&tm); int64_t t = now_us; pthread_mutex_unlock(&tm); return t; }
static esp_err_t esp_timer_create(const esp_timer_create_args_t *a, esp_timer_handle_t *h)
{ *h = calloc(1, sizeof(**h)); (*h)->cb = a->callback; (*h)->arg = a->arg; created++; return ESP_OK; }
static esp_err_t esp_timer_start_once(esp_timer_handle_t h, uint64_t us)
{ pthread_mutex_lock(&tm); esp_err_t r = h->armed ? ESP_ERR_INVALID_STATE : ESP_OK;
  if (!h->armed) { h->armed = true; h->periodic = false; h->due = now_us + (int64_t)us; } pthread_mutex_unlock(&tm); return r; }
static esp_err_t esp_timer_start_periodic(esp_timer_handle_t h, uint64_t us)
{ pthread_mutex_lock(&tm); esp_err_t r = h->armed ? ESP_ERR_INVALID_STATE : ESP_OK;
  if (!h->armed) { h->armed = true; h->periodic = true; h->period = (int64_t)us; h->due = now_us + (int64_t)us; } pthread_mutex_unlock(&tm); return r; }
static esp_err_t esp_timer_stop(esp_timer_handle_t h)
{ pthread_mutex_lock(&tm); esp_err_t r = h->armed ? ESP_OK : ESP_ERR_INVALID_STATE; h->armed = false; pthread_mutex_unlock(&tm); return r; }
/* Deleting only marks: a fake that freed would turn the old code's
   use-after-delete into a crash before the check could say what broke. */
__attribute__((unused)) static esp_err_t esp_timer_delete(esp_timer_handle_t h)
{ pthread_mutex_lock(&tm); h->armed = false; h->deleted = true; deleted_n++; pthread_mutex_unlock(&tm); return ESP_OK; }

/* The esp_timer task taking a due timer off its list: the callback is then
   on its way, whatever happens to the timer afterwards. */
static bool take_due(esp_timer_handle_t h)
{
    pthread_mutex_lock(&tm);
    bool due = h && h->armed && !h->deleted && now_us >= h->due;
    if (due) { if (h->periodic) h->due += h->period; else h->armed = false; }
    pthread_mutex_unlock(&tm);
    return due;
}
static void advance(int64_t us) { pthread_mutex_lock(&tm); now_us += us; pthread_mutex_unlock(&tm); }

/* button.c and led.c */
static void (*volatile button_cb)(void);
static void (*race_hook)(void);
static void button_on_short_press(void (*cb)(void))
{
    button_cb = cb;
    if (!cb && race_hook) { void (*h)(void) = race_hook; race_hook = NULL; h(); }
}
static int led_r;
static void led_force_set(uint8_t r, uint8_t g, uint8_t b) { (void)g; (void)b; led_r = r; }

__CUT__

/* --- the test ------------------------------------------------------------ */
static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static esp_timer_handle_t timer_of(esp_timer_handle_t *slot) { return *slot; }

/* The HTTP handler on the other core. */
static char            session2[9];
static esp_err_t       begin2_ret = -1;
static volatile bool   begin2_done;
static void *http_begin(void *a) { (void)a; begin2_ret = auth_token_begin(session2); begin2_done = true; return NULL; }
static pthread_t http;
/* Called from inside the old flow's timeout, right after it set TIMEOUT:
   the new begin starts and is given time to finish if nothing holds it. */
static void start_begin_on_other_core(void)
{
    pthread_create(&http, NULL, http_begin, NULL);
    for (int i = 0; i < 200 && !begin2_done; i++) usleep(1000);
}
static void *timer_task(void *a) { esp_timer_handle_t h = a; h->cb(h->arg); return NULL; }

static void reset(void)
{
    auth_token_cancel();
    advance(1000000000LL);
}

int main(void)
{
    printf("Token-Ablauf mit BOOT-Taste\n");
#ifndef OLD_CODE
    CHECK(token_init() == ESP_OK, "token_init");
#endif
    char s[9], tok[33];

    /* 1. The normal flow. */
    CHECK(auth_token_begin(s) == ESP_OK, "begin");
    CHECK(auth_token_status(s, tok) == AUTH_TOK_WAITING, "nicht WAITING");
    CHECK(button_cb == auth_on_button_press, "Tastenhandler nicht gesetzt");
    void (*cb)(void) = button_cb; button_cb = NULL; cb();          /* one-shot, as in button.c */
    memset(tok, 0, sizeof(tok));
    CHECK(auth_token_status(s, tok) == AUTH_TOK_READY && strlen(tok) == 32, "nicht READY");
    CHECK(auth_token_consume(tok), "consume");
    CHECK(auth_token_status(s, NULL) == AUTH_TOK_IDLE, "nicht IDLE");
    printf("  Normalfall: begin, Taste, Token, consume\n");

    /* 2. A READY token nobody collects expires; a new begin works after it. */
    CHECK(auth_token_begin(s) == ESP_OK, "begin");
    cb = button_cb; button_cb = NULL; cb();
    advance(121000000LL);
    esp_timer_handle_t to = timer_of(&s_timeout_timer);
    CHECK(take_due(to), "READY-Timeout nicht faellig");
    to->cb(to->arg);
    CHECK(auth_token_status(s, NULL) == AUTH_TOK_TIMEOUT, "READY nicht abgelaufen");
    CHECK(auth_token_begin(s) == ESP_OK, "begin nach Timeout abgewiesen");
    reset();
    printf("  ein nicht abgeholter Token laeuft ab, danach geht begin wieder\n");

    /* 3. The reported race: the timeout fires, sets TIMEOUT, and before it
          has cleaned up, a new begin runs on the other core. */
    char s1[9];
    CHECK(auth_token_begin(s1) == ESP_OK, "begin");
    advance(31000000LL);
    to = timer_of(&s_timeout_timer);
    CHECK(take_due(to), "Timeout nicht faellig");
    race_hook = start_begin_on_other_core;
    pthread_t tt; pthread_create(&tt, NULL, timer_task, to);
    pthread_join(tt, NULL);
    pthread_join(http, NULL);
    CHECK(begin2_ret == ESP_OK, "neues begin abgewiesen (%d)", (int)begin2_ret);
    CHECK(auth_token_status(session2, NULL) == AUTH_TOK_WAITING, "neuer Vorgang nicht WAITING");
    CHECK(button_cb == auth_on_button_press, "Tastenhandler des neuen Vorgangs geloescht");
    esp_timer_handle_t nto = timer_of(&s_timeout_timer), nbl = timer_of(&s_blink_timer);
    CHECK(nto && nto->armed && !nto->deleted, "Timeout des neuen Vorgangs geloescht");
    CHECK(nbl && nbl->armed && !nbl->deleted, "Blinken des neuen Vorgangs geloescht");
    if (button_cb) { cb = button_cb; button_cb = NULL; cb(); }
    CHECK(auth_token_status(session2, NULL) == AUTH_TOK_READY, "Taste schaltet den neuen Token nicht frei");
    /* And it is not stuck: it still ends by itself. */
    advance(121000000LL);
    nto = timer_of(&s_timeout_timer);
    if (take_due(nto)) nto->cb(nto->arg);
    CHECK(auth_token_status(session2, NULL) == AUTH_TOK_TIMEOUT, "neuer Vorgang laeuft nie ab");
    CHECK(auth_token_begin(s) == ESP_OK, "haengt: begin meldet already pending");
    reset();
    printf("  Timeout und begin gleichzeitig: der neue Vorgang bleibt intakt\n");

    /* 4. A timeout on its way when the button re-armed it for the READY
          window must not end the READY token it no longer belongs to. */
    CHECK(auth_token_begin(s) == ESP_OK, "begin");
    advance(30000000LL);
    to = timer_of(&s_timeout_timer);
    CHECK(take_due(to), "Timeout nicht faellig");          /* on its way ...      */
    cb = button_cb; button_cb = NULL; cb();                 /* ... the press wins  */
    to->cb(to->arg);                                        /* ... then it arrives */
    CHECK(auth_token_status(s, NULL) == AUTH_TOK_READY, "verspaeteter WAITING-Timeout beendet READY");
    reset();
    printf("  ein verspaeteter Timeout beendet keinen neu gestellten Vorgang\n");

    /* 5. A blink tick on its way after the LED was put out leaves it out. */
    CHECK(auth_token_begin(s) == ESP_OK, "begin");
    advance(150000);
    esp_timer_handle_t bl = timer_of(&s_blink_timer);
    CHECK(take_due(bl), "Blinken nicht faellig");
    cb = button_cb; button_cb = NULL; cb();                 /* stop_blink(): LED off */
    if (led_r) { advance(150000); take_due(bl); }
    bl->cb(bl->arg);
    CHECK(led_r == 0, "LED nach dem Tastendruck wieder an");
    reset();
    printf("  ein verspaeteter Blink-Tick schaltet die LED nicht wieder an\n");

    CHECK(deleted_n == 0, "%d Timer geloescht, waehrend Callbacks unterwegs sein koennen", deleted_n);
    printf("  Timer nur einmal angelegt (%d), nie geloescht\n", created);

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_auth.c")
h = HARNESS.replace("__CUT__", cuts)
if old:
    h = "#define OLD_CODE 1\n" + h
out.write_text(h)
print("erzeugt:", out.name)
