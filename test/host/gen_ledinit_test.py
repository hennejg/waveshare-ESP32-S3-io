#!/usr/bin/env python3
"""Builds a host test for the RGB LED driver (components/board/led.c).

led.c is taken whole from its #defines on, verbatim; the LED strip, the
timers, MQTT and FreeRTOS are recorders. cJSON is ESP-IDF's own.

What it pins down, found by a review:
  - led_init() started the LED task on a queue it never checked -- NULL on
    out of memory, and the task's first receive stopped the device -- and a
    task that could not be created still gave ESP_OK. Now each step is
    checked, what was made is freed, and ESP_ERR_NO_MEM is returned, in
    both LED modes;
  - an instant colour ("#000000" on led/set, or led_set_rgb() from Modbus,
    CAN, rules or the web page) during a sequence was overwritten by the
    sequence's next step. Now it ends the sequence, also one queued before
    it and not started yet;
  - a colour is exactly "#RRGGBB": "#ff0000xyz" was red, "#zzzzzz" black.
OLD=1 cuts led.c from git (OLDREV, default HEAD); before the fix
run_sequence() did not exist, so the generator stops there.

  make -C test/host ledinit
"""
import pathlib, sys
from cutter import Source

led = Source.at("components/board/led.c")
if "static void run_sequence(const led_seq_t *seq)" not in led.text:
    sys.exit("FEHLER: run_sequence() fehlt -- eine Sofortfarbe beendet keine Sequenz")
jx = Source.at("components/board/json_exact.c")
body = led.text[led.text.index('#define TAG'):]

HARNESS = r"""
/* GENERATED by gen_ledinit_test.py -- do not edit; edit led.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cJSON.h"

#define CONFIG_APP_MQTT_ENABLE 1
typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define ESP_ERR_NO_MEM 0x101
#define ESP_ERR_INVALID_STATE 0x103
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGW(...) ((void)0)
#define ESP_LOGE(...) ((void)0)
#define ESP_RETURN_ON_ERROR(x, tag, ...) do { esp_err_t _r = (x); if (_r != ESP_OK) return _r; } while (0)
#define GPIO_NUM_38 38
#define LED_MODE_IO 0
#define LED_MODE_STATUS 1
typedef struct { uint8_t led_mode; } app_config_t;
static app_config_t cfg;
static const app_config_t *app_config_get(void) { return &cfg; }

/* FreeRTOS */
typedef uint32_t TickType_t;
#define portMAX_DELAY 0xFFFFFFFFu
#define pdTRUE 1
#define pdPASS 1
#define pdMS_TO_TICKS(ms) ((TickType_t)(ms))
typedef struct { int dummy; } obj_t;
typedef obj_t *QueueHandle_t; typedef obj_t *SemaphoreHandle_t; typedef obj_t *TaskHandle_t;
static int fail_queue, fail_task, fail_mutex, live_queues, live_mutexes, tasks;
static obj_t objs[16]; static int nobj;
static QueueHandle_t xQueueCreate(int n, size_t sz) { (void)n; (void)sz; if (fail_queue) return NULL; live_queues++; return &objs[nobj++ % 16]; }
static void vQueueDelete(QueueHandle_t q) { (void)q; live_queues--; }
static SemaphoreHandle_t xSemaphoreCreateMutex(void) { if (fail_mutex) return NULL; live_mutexes++; return &objs[nobj++ % 16]; }
static void vSemaphoreDelete(SemaphoreHandle_t m) { (void)m; live_mutexes--; }
static int xSemaphoreTake(SemaphoreHandle_t m, TickType_t t) { (void)m; (void)t; return pdTRUE; }
static int xSemaphoreGive(SemaphoreHandle_t m) { (void)m; return pdTRUE; }
static int xTaskCreate(void (*fn)(void *), const char *n, int st, void *a, int pr, TaskHandle_t *h)
{ (void)fn; (void)n; (void)st; (void)a; (void)pr; if (fail_task) return 0; tasks++; if (h) *h = &objs[nobj++ % 16]; return pdPASS; }
static uint32_t notifications, waited_ms;
static void xTaskNotifyGive(TaskHandle_t t) { (void)t; notifications++; }
/* A step waiting out its time: the test can let something happen meanwhile. */
static void (*during_wait)(void);
static uint32_t ulTaskNotifyTake(int clear, TickType_t t) {
    if (!notifications && t) {
        if (during_wait) { void (*f)(void) = during_wait; during_wait = NULL; f(); }
        else waited_ms += t;
    }
    uint32_t n = notifications;
    if (clear) notifications = 0; else if (notifications) notifications--;
    return n;
}
static void vTaskDelay(TickType_t t) { (void)t; }
static int queued;
static int xQueueReceive(QueueHandle_t q, void *p, TickType_t t) { (void)q; (void)p; (void)t; return 0; }
static int xQueueOverwrite(QueueHandle_t q, const void *p) { (void)q; (void)p; queued++; return pdTRUE; }
static int uxQueueMessagesWaiting(QueueHandle_t q) { (void)q; return 0; }
typedef int portMUX_TYPE;
#define portMUX_INITIALIZER_UNLOCKED 0
#define taskENTER_CRITICAL(m) ((void)(m))
#define taskEXIT_CRITICAL(m)  ((void)(m))

/* esp_timer */
typedef void *esp_timer_handle_t;
typedef struct { void (*callback)(void *); const char *name; } esp_timer_create_args_t;
static esp_err_t esp_timer_create(const esp_timer_create_args_t *a, esp_timer_handle_t *h) { (void)a; *h = &objs[0]; return ESP_OK; }
static esp_err_t esp_timer_start_periodic(esp_timer_handle_t h, uint64_t us) { (void)h; (void)us; return ESP_OK; }
static esp_err_t esp_timer_stop(esp_timer_handle_t h) { (void)h; return ESP_OK; }

/* Record the existing RGB wire bytes. Match the
   SDK's RGB API and its default GRB format, rather than hiding an R/G swap. */
typedef obj_t *led_strip_handle_t;
#define LED_STRIP_COLOR_COMPONENT_FMT_RGB 1
typedef struct { int strip_gpio_num; int max_leds; int color_component_format; } led_strip_config_t;
typedef struct { uint32_t resolution_hz; struct { int with_dma; } flags; } led_strip_rmt_config_t;
static int strips, strip_format;
static esp_err_t led_strip_new_rmt_device(const led_strip_config_t *c, const led_strip_rmt_config_t *r, led_strip_handle_t *h)
{ strip_format = c->color_component_format; (void)r; strips++; *h = &objs[nobj++ % 16]; return ESP_OK; }
static esp_err_t led_strip_del(led_strip_handle_t h) { (void)h; strips--; return ESP_OK; }
static uint32_t written[32]; static int nwritten; static uint8_t px[3];
static esp_err_t led_strip_set_pixel(led_strip_handle_t h, int i, uint8_t r, uint8_t g, uint8_t b) { (void)h; (void)i; px[0] = strip_format == LED_STRIP_COLOR_COMPONENT_FMT_RGB ? r : g; px[1] = strip_format == LED_STRIP_COLOR_COMPONENT_FMT_RGB ? g : r; px[2] = b; return ESP_OK; }
static esp_err_t led_strip_refresh(led_strip_handle_t h) { (void)h; if (nwritten < 32) written[nwritten++] = (uint32_t)px[0] << 16 | px[1] << 8 | px[2]; return ESP_OK; }
static esp_err_t led_strip_clear(led_strip_handle_t h) { (void)h; return ESP_OK; }

static int app_mqtt_publish(const char *t, const char *p, int l, int q, bool r) { (void)t; (void)p; (void)l; (void)q; (void)r; return 0; }
static int app_mqtt_subscribe(const char *t, int q) { (void)t; (void)q; return 0; }
static bool app_mqtt_is_connected(void) { return false; }

__JX__
__LED__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static void reset_init(void)
{
    s_strip = NULL; s_queue = NULL; s_io_lock = NULL; s_led_task = NULL; s_flash_q = NULL;
    fail_queue = fail_task = fail_mutex = 0; live_queues = live_mutexes = tasks = strips = 0;
    notifications = waited_ms = 0;
}
static void instant_black(void) { led_set_rgb(0, 0, 0); }
static void mqtt_black(void)    { led_on_mqtt_message("led/set", 7, "#000000", 7); }

int main(void)
{
    printf("RGB-LED: Start, Sofortfarbe, Farbformat\n");
    for (int mode = 0; mode < 2; mode++) {
        cfg.led_mode = mode ? LED_MODE_STATUS : LED_MODE_IO;
        const char *m = mode ? "Statusmodus" : "IO-Modus";
        for (int what = 0; what < (mode ? 2 : 3); what++) {
            reset_init();
            if (what == 0) fail_queue = 1; else if (what == 1) fail_task = 1; else fail_mutex = 1;
            esp_err_t r = led_init();
            CHECK(r == ESP_ERR_NO_MEM, "%s, %s scheitert: led_init() meldet %d", m, what == 0 ? "Queue" : what == 1 ? "Task" : "Mutex", r);
            CHECK(tasks == 0 || what == 2, "%s: Task trotz fehlender Queue gestartet", m);
            CHECK(live_queues == 0 && live_mutexes == 0 && strips == 0, "%s: nach dem Fehler bleibt etwas belegt (%d Queues, %d Mutexe, %d LED)", m, live_queues, live_mutexes, strips);
        }
        reset_init();
        CHECK(led_init() == ESP_OK && tasks == 1, "%s: ordentlicher Start", m);
    }
    reset_init(); cfg.led_mode = LED_MODE_IO; led_init();
    if (!failures) printf("  led_init: Queue, Mutex und Task geprueft, bei Fehler freigegeben, ESP_ERR_NO_MEM\n");

    nwritten = 0;
    led_set_rgb(255, 0, 0); led_set_rgb(0, 255, 0); led_set_rgb(0, 0, 255);
    CHECK(nwritten == 3 && written[0] == 0xFF0000 && written[1] == 0x00FF00 && written[2] == 0x0000FF,
          "RGB-Drahtreihenfolge: primaere Farben vertauscht");

    int f0 = failures;
    led_seq_t seq = { .count = 2, .gen = s_gen,
                      .steps = { { 255, 0, 0, 0, 1000 }, { 0, 255, 0, 0, 1000 } } };
    for (int k = 0; k < 2; k++) {
        nwritten = 0; seq.gen = s_gen;
        during_wait = k ? mqtt_black : instant_black;     /* during the red step */
        run_sequence(&seq);
        CHECK(nwritten == 2 && written[0] == 0xFF0000 && written[1] == 0x000000,
              "%s waehrend Rot: %d Farben, zuletzt #%06X (Gruen darf nicht folgen)",
              k ? "MQTT #000000" : "led_set_rgb(0,0,0)", nwritten, nwritten ? (unsigned)written[nwritten - 1] : 0u);
    }
    seq.gen = s_gen; led_set_rgb(0, 0, 255); nwritten = 0;   /* queued before the instant colour */
    run_sequence(&seq);
    CHECK(nwritten == 0, "Sequenz von vor der Sofortfarbe noch gelaufen (%d Farben)", nwritten);
    seq.gen = s_gen; nwritten = 0; run_sequence(&seq);
    CHECK(nwritten == 2 && written[1] == 0x00FF00, "Sequenz nach der Sofortfarbe laeuft nicht durch");
    /* A command wakes the task even when it was waiting for a queue item,
       rather than a step's timeout. That old notification must not shorten
       the first step of the sequence it has just received. */
    static const char timed[] = "[{\"color\":\"#ff0000\",\"duration\":1000},{\"color\":\"#00ff00\",\"duration\":1000}]";
    led_on_mqtt_message("led/set", 7, timed, sizeof timed - 1);
    seq.gen = s_gen; waited_ms = 0; nwritten = 0;
    run_sequence(&seq);
    CHECK(waited_ms == 2000 && nwritten == 2,
          "neue Sequenz: %u ms statt 2000 ms (Startbenachrichtigung verkuerzt ersten Schritt)", (unsigned)waited_ms);
    if (failures == f0) printf("  Sofortfarbe beendet eine laufende oder wartende Sequenz\n");

    f0 = failures;
    uint8_t r, g, b;
    CHECK(parse_hex("#ff8000", &r, &g, &b) && r == 0xFF && g == 0x80 && b == 0, "#ff8000 nicht gelesen");
    CHECK(!parse_hex("#ff0000xyz", &r, &g, &b), "#ff0000xyz angenommen");
    CHECK(!parse_hex("#zzzzzz", &r, &g, &b), "#zzzzzz angenommen");
    nwritten = 0; led_on_mqtt_message("led/set", 7, "#ff0000x", 8);
    CHECK(nwritten == 0, "led/set #ff0000x gesetzt");
    static const char bad_step[] = "{\"color\":\"#00ff00junk\",\"duration\":100}";
    queued = 0; led_on_mqtt_message("led/set", 7, bad_step, sizeof bad_step - 1);
    CHECK(queued == 0, "Sequenzschritt mit ungueltiger Farbe eingereiht");
    if (failures == f0) printf("  Farbe nur genau #RRGGBB\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_ledinit.c")
jx_body = jx.text[jx.text.index("static bool escapes_nul"):] if "static bool escapes_nul" in jx.text \
          else jx.text[jx.text.index("cJSON *json_parse_exact"):]
out.write_text(HARNESS.replace("__JX__", jx_body).replace("__LED__", body))
print("erzeugt:", out.name)
