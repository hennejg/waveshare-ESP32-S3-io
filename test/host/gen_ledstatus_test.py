#!/usr/bin/env python3
"""Builds a host test for what the status LED shows (led.c, auth.c).

The status-mode functions, hw_apply() and led_force_set() are cut out of
led.c verbatim, stop_blink() out of auth.c; the LED strip is a recorder.

What it pins down, found by a review:
  - "network up" came once per address an interface got -- two with
    Ethernet and WiFi, another with a DHCP renewal -- but "down" only once,
    when the last one was gone. The LED counted them, never came back to
    zero, and stayed green with no network at all.
  - the end of the password-setup blinking (and of a Matter identify) put
    the LED out instead of back to what it showed before: the status colour,
    or the colour set in IO mode.
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host ledstatus
"""
import pathlib
from cutter import Source

led  = Source.at("components/board/led.c")
auth = Source.at("components/board/auth.c")

cuts  = led.span("static led_strip_handle_t s_strip;", "static bool               s_status_mode;")
if "static void hw_write(" in led.text:
    cuts += led.func("static void hw_write(uint8_t r, uint8_t g, uint8_t b)")
cuts += led.func("static void hw_apply(uint8_t r, uint8_t g, uint8_t b)")
cuts += led.span("/* Colours (50%", "typedef struct { uint8_t r, g, b; } flash_t;")
cuts += led.span("static uint8_t            s_bg_r", "portMUX_INITIALIZER_UNLOCKED;")
for sig in ("static void set_background(uint8_t r, uint8_t g, uint8_t b)",
            "static void refresh_status(void)",
            "static void ap_blink_cb(void *arg)",
            "void led_status_set_ap_mode(bool up)",
            "void led_status_set_network(bool up)",
            "void led_status_set_mqtt(bool up)",
            "esp_err_t led_set_rgb(uint8_t r, uint8_t g, uint8_t b)",
            "void led_force_set(uint8_t r, uint8_t g, uint8_t b)"):
    cuts += led.func(sig)
if "void led_force_release(void)" in led.text:
    cuts += led.func("void led_force_release(void)")
cuts += auth.func("static void stop_blink(void)")

HARNESS = r"""
/* GENERATED by gen_ledstatus_test.py -- do not edit; edit led.c / auth.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

typedef int esp_err_t;
#define ESP_OK 0
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
typedef void *QueueHandle_t;
typedef int portMUX_TYPE;
#define portMUX_INITIALIZER_UNLOCKED 0
#define taskENTER_CRITICAL(m) ((void)(m))
#define taskEXIT_CRITICAL(m)  ((void)(m))
typedef void *esp_timer_handle_t;
typedef struct { void (*callback)(void *); const char *name; } esp_timer_create_args_t;
static int dummy_timer;
static esp_err_t esp_timer_create(const esp_timer_create_args_t *a, esp_timer_handle_t *h) { (void)a; *h = &dummy_timer; return 0; }
static esp_err_t esp_timer_start_periodic(esp_timer_handle_t t, unsigned long long us) { (void)t; (void)us; return 0; }
static esp_err_t esp_timer_stop(esp_timer_handle_t t) { (void)t; return 0; }

typedef void *led_strip_handle_t;
static uint8_t px_r, px_g, px_b;
static void led_strip_set_pixel(led_strip_handle_t s, int i, uint8_t g, uint8_t r, uint8_t b) { (void)s; (void)i; px_r = r; px_g = g; px_b = b; }
static void led_strip_refresh(led_strip_handle_t s) { (void)s; }
static void led_force_set(uint8_t r, uint8_t g, uint8_t b);
#ifndef HAVE_RELEASE
void led_force_release(void);
#endif

static esp_timer_handle_t s_blink_timer;
static bool               s_blink_on;

__CUT__

#ifndef HAVE_RELEASE
void led_force_release(void) {}
#endif

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
#define IS(r, g, b) (px_r == (r) && px_g == (g) && px_b == (b))

int main(void)
{
    static int strip;
    s_strip = &strip;
    printf("Status-LED\n");

    s_status_mode = true;
    refresh_status();
    CHECK(IS(STA_BOOT_R, STA_BOOT_G, STA_BOOT_B), "Start nicht gelb");

    /* Ethernet and WiFi both get an address; both lose it. main.c reports
       the loss once, when no interface is left. */
    led_status_set_network(true);
    led_status_set_network(true);
    CHECK(IS(STA_NET_R, STA_NET_G, STA_NET_B), "Netz da, nicht gruen");
    led_status_set_network(false);
    CHECK(IS(STA_BOOT_R, STA_BOOT_G, STA_BOOT_B), "zwei Schnittstellen weg: LED %u/%u/%u statt gelb", px_r, px_g, px_b);

    /* A DHCP renewal reports the same interface up again. */
    led_status_set_network(true);
    led_status_set_network(true);
    led_status_set_network(false);
    CHECK(IS(STA_BOOT_R, STA_BOOT_G, STA_BOOT_B), "nach DHCP-Erneuerung und Netzverlust: LED %u/%u/%u statt gelb", px_r, px_g, px_b);

    /* Broker up and down keeps the network level. */
    led_status_set_network(true);
    led_status_set_mqtt(true);
    CHECK(IS(STA_MQTT_R, STA_MQTT_G, STA_MQTT_B), "Broker da, nicht lila");
    led_status_set_mqtt(false);
    CHECK(IS(STA_NET_R, STA_NET_G, STA_NET_B), "Broker weg, Netz da: nicht gruen");
    led_status_set_network(false);
    led_status_set_mqtt(false);
    CHECK(IS(STA_BOOT_R, STA_BOOT_G, STA_BOOT_B), "Broker weg ohne Netz: nicht gelb");

    /* Password-setup blink ends: back to the status colour. */
    led_status_set_network(true);
    led_force_set(100, 100, 0);
    stop_blink();
    CHECK(IS(STA_NET_R, STA_NET_G, STA_NET_B), "Statusmodus nach Blinken: LED %u/%u/%u statt gruen", px_r, px_g, px_b);

    /* IO mode: back to the colour the user set. */
    s_status_mode = false;
    led_set_rgb(10, 20, 30);
    led_force_set(100, 100, 0);
    stop_blink();
    CHECK(IS(10, 20, 30), "IO-Modus nach Blinken: LED %u/%u/%u statt 10/20/30", px_r, px_g, px_b);

    if (!failures) printf("  Netzverlust setzt die LED zurueck; nach dem Blinken stimmt die Farbe wieder\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
have = "void led_force_release(void)" in led.text
out = pathlib.Path(__file__).with_name("test_ledstatus.c")
out.write_text(("#define HAVE_RELEASE 1\n" if have else "") + HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
