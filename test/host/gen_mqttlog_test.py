#!/usr/bin/env python3
"""Builds a host test for the MQTT broker URL as it is logged (app_mqtt.c).

url_for_log() is cut out of app_mqtt.c verbatim. What it pins down, found by
a review: "Connecting to %s" logged the configured URL as it was, and a URL
of the form mqtt://user:password@host put the broker password on the console.
OLD=1 has no url_for_log(); the test then says so.

  make -C test/host mqttlog
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("apps/full/main/app_mqtt.c")
have = "static const char *url_for_log(" in src.text
cut  = src.func("static const char *url_for_log(const char *url, char *out, size_t cap)") if have else \
       "static const char *url_for_log(const char *url, char *out, size_t cap) { snprintf(out, cap, \"%s\", url); return out; }\n"

HARNESS = r"""
/* GENERATED by gen_mqttlog_test.py -- do not edit; edit app_mqtt.c. */
#include <stdio.h>
#include <string.h>

__CUT__

int main(void)
{
    static const struct { const char *in, *out; } c[] = {
        { "mqtt://192.168.1.10:1883",                   "mqtt://192.168.1.10:1883" },
        { "mqtts://user:secret@broker.example:8883",     "mqtts://broker.example:8883" },
        { "mqtt://user:p@ss@broker.example",             "mqtt://broker.example" },
        { "mqtt://broker.example/path@x",                "mqtt://broker.example/path@x" },
        { "ws://u:pw@host:8080/mqtt",                    "ws://host:8080/mqtt" },
        { "broker.example",                              "broker.example" },
    };
    int failures = 0;
    char buf[128];
    printf("MQTT-URL im Log\n");
    for (size_t i = 0; i < sizeof c / sizeof c[0]; i++) {
        const char *got = url_for_log(c[i].in, buf, sizeof buf);
        if (strcmp(got, c[i].out)) { failures++; printf("  FEHLER: %s -> %s (erwartet %s)\n", c[i].in, got, c[i].out); }
    }
    char small[12];
    url_for_log("mqtts://user:secret@broker.example:8883", small, sizeof small);
    if (strstr(small, "secret")) { failures++; printf("  FEHLER: gekuerzt steht das Passwort drin: %s\n", small); }
    if (!failures) printf("  Zugangsdaten nie im Log, Rest der URL unveraendert (%zu Faelle)\n", sizeof c / sizeof c[0]);
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqttlog.c")
out.write_text(HARNESS.replace("__CUT__", cut))
print("erzeugt:", out.name)
