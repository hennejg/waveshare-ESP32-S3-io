#!/usr/bin/env python3
"""Builds a host test for NUL bytes and trailing data in commands
(components/board/dout.c, json_exact.c, components/scripting/scripting.c).

Cut out verbatim: dout_parse_state(), dout_parse_toggle(),
json_parse_exact() and scripting_on_mqtt_message(). cJSON is ESP-IDF's own;
QuickJS turns the payload into the string a rule sees.

What it pins down, found by a review: a payload was copied and compared as
a C string, so it ended at its first NUL byte -- "on\\0off" switched an
output on, a rule saw "ON" of "ON\\0OFF". cJSON stopped after the first
value as well: "50 off" or an object with bytes appended were taken as the
value in front. Now a command is the whole payload or nothing, and a rule
gets every byte.
OLD=1 cuts the files from git (OLDREV, default HEAD); before the fix
json_exact.c did not exist, so the generator stops there.

  make -C test/host nulbytes
"""
import pathlib, sys
from cutter import Source

dout = Source.at("components/board/dout.c")
scr  = Source.at("components/scripting/scripting.c")
try:
    jx = Source.at("components/board/json_exact.c")
except Exception:
    sys.exit("FEHLER: json_exact.c fehlt -- cJSON nimmt Nutzlasten mit Anhang an")
types = (scr.defines("MAX_TOPIC_LEN", "MAX_PAYLOAD_LEN")
         + scr.span("typedef enum { EVT_MQTT, EVT_INPUT_CHANGE,", "} evt_type_t;")
         + scr.span("typedef struct {\n    evt_type_t type;", "} scripting_evt_t;"))
body = (dout.func("bool dout_parse_state(const char *data, size_t len, bool *out)")
        + dout.func("bool dout_parse_toggle(const char *data, size_t len)")
        + jx.func("cJSON *json_parse_exact(const char *data, size_t n)")
        + scr.func("void scripting_on_mqtt_message(const char *topic, size_t tlen,"))

HARNESS = r"""
/* GENERATED by gen_nulbytes_test.py -- do not edit; edit the firmware. */
#include <ctype.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cJSON.h"
#include "quickjs.h"

#define TAG "t"
#define ESP_LOGW(...) ((void)0)
typedef int BaseType_t;
#define pdTRUE 1
typedef int esp_err_t;
typedef esp_err_t (*scripting_store_fn_t)(const char *);
static int queue_obj; static void *s_queue = &queue_obj;

__TYPES__

static scripting_evt_t sent; static int nsent;
static BaseType_t evt_send(scripting_evt_t *ev) { sent = *ev; nsent++; return pdTRUE; }

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    printf("Nullbytes und Anhaengsel in Befehlen\n");
    bool v = false;
    CHECK(dout_parse_state("on", 2, &v) && v, "\"on\" nicht erkannt");
    CHECK(dout_parse_state("OFF", 3, &v) && !v, "\"OFF\" nicht erkannt");
    CHECK(!dout_parse_state("on\0off", 6, &v), "\"on\\0off\" (6 Bytes) als Befehl angenommen");
    CHECK(!dout_parse_state("1\0", 2, &v), "\"1\\0\" als Befehl angenommen");
    CHECK(dout_parse_toggle("toggle", 6) && !dout_parse_toggle("toggle\0x", 8), "toggle mit Nullbyte angenommen");

    static const struct { const char *d; size_t n; bool ok; const char *what; } js[] = {
        { "50", 2, true, "Zahl" },               { " {\"duty\":5}\n", 12, true, "Objekt mit Leerraum" },
        { "50\0xyz", 6, false, "Zahl+Nullbyte" }, { "50 off", 6, false, "Zahl+Text" },
        { "{\"duty\":5}garbage", 17, false, "Objekt+Anhang" }, { "", 0, false, "leer" },
        { "[1,2] [3]", 9, false, "zwei Werte" },
    };
    for (unsigned i = 0; i < sizeof js / sizeof js[0]; i++) {
        cJSON *j = json_parse_exact(js[i].d, js[i].n);
        CHECK((j != NULL) == js[i].ok, "JSON %s: %s", js[i].what, j ? "angenommen" : "abgelehnt");
        cJSON_Delete(j);
    }

    scripting_on_mqtt_message("rules/cmd", 9, "ON\0OFF", 6);
    CHECK(nsent == 1 && sent.mqtt.plen == 6, "Nutzlast-Laenge nicht erhalten (%u)", (unsigned)sent.mqtt.plen);
    JSRuntime *rt = JS_NewRuntime(); JSContext *ctx = JS_NewContext(rt);
    JSValue s = JS_NewStringLen(ctx, sent.mqtt.payload, sent.mqtt.plen);
    JSValue l = JS_GetPropertyStr(ctx, s, "length"); int32_t len = 0; JS_ToInt32(ctx, &len, l);
    CHECK(len == 6, "Regel sieht %d Zeichen statt 6 (\"ON\\0OFF\")", len);
    JS_FreeValue(ctx, l); JS_FreeValue(ctx, s); JS_FreeContext(ctx); JS_FreeRuntime(rt);
    scripting_on_mqtt_message("rules/cmd\0x", 11, "ON", 2);
    CHECK(nsent == 1, "Topic mit Nullbyte an die Regeln gegeben");

    if (!failures) printf("  Befehle nur als ganze Nutzlast; Regeln erhalten jedes Byte\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_nulbytes.c")
out.write_text(HARNESS.replace("__TYPES__", types).replace("__CUT__", body))
print("erzeugt:", out.name)
