#!/usr/bin/env python3
"""Builds a host test for MQTT messages larger than the client's buffer
(apps/full/main/app_mqtt.c).

data_whole() is cut out verbatim; the event is a stand-in with the fields
esp-mqtt fills, split the way esp-mqtt splits a payload larger than
CONFIG_MQTT_BUFFER_SIZE (1024): the first event carries the topic and the
first piece, the continuations no topic.

What it pins down, found on the bench board: the continuations were dropped,
but the first piece went to the handlers as if it were the whole message.
1100 bytes of "#aaaa..." on led/set set the LED to #aaaaaa, and no handler's
own length limit ever saw the real length. Now the message is dropped whole.
OLD=1 cuts app_mqtt.c from git (OLDREV, default HEAD); before the fix the
function did not exist, so the generator stops there.

  make -C test/host mqttfrag
"""
import pathlib, sys
from cutter import Source

src = Source.at("apps/full/main/app_mqtt.c")
if "static bool data_whole(const esp_mqtt_event_t *e)" not in src.text:
    sys.exit("FEHLER: data_whole() fehlt -- das erste Stueck einer grossen Nachricht geht als ganze Nachricht weiter")
cut = src.func("static bool data_whole(const esp_mqtt_event_t *e)")

HARNESS = r"""
/* GENERATED by gen_mqttfrag_test.py -- do not edit; edit app_mqtt.c. */
#include <stdbool.h>
#include <stdio.h>
#include <string.h>

#define TAG "mqtt"
static int warnings;
#define ESP_LOGW(tag, ...) (warnings++, snprintf(NULL, 0, __VA_ARGS__))
typedef struct {
    const char *topic; int topic_len;
    const char *data;  int data_len;
    int total_data_len, current_data_offset;
} esp_mqtt_event_t;

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

#define BUF 1024
/* Events as esp-mqtt raises them for one message; returns how many were passed on. */
static int deliver(const char *topic, int total)
{
    static char payload[4096];
    memset(payload, 'a', sizeof payload);
    int passed = 0;
    for (int off = 0; off < total || (total == 0 && off == 0); off += BUF) {
        esp_mqtt_event_t e = {
            .topic = off ? NULL : topic, .topic_len = off ? 0 : (int)strlen(topic),
            .data = payload + off, .data_len = total - off < BUF ? total - off : BUF,
            .total_data_len = total, .current_data_offset = off,
        };
        if (data_whole(&e)) passed++;
        if (total == 0) break;
    }
    return passed;
}

int main(void)
{
    printf("MQTT-Nachrichten groesser als der Puffer\n");
    CHECK(deliver("led/set", 7) == 1, "kleine Nachricht nicht weitergegeben");
    CHECK(deliver("led/set", 0) == 1, "leere Nachricht nicht weitergegeben");
    CHECK(deliver("led/set", BUF) == 1, "Nachricht von genau %d Byte nicht weitergegeben", BUF);
    warnings = 0;
    CHECK(deliver("led/set", 1100) == 0, "erstes Stueck einer 1100-Byte-Nachricht als ganze weitergegeben");
    CHECK(warnings == 1, "%d Warnungen fuer eine Nachricht", warnings);
    warnings = 0;
    CHECK(deliver("rules/x", 3000) == 0, "Stuecke einer 3000-Byte-Nachricht weitergegeben");
    CHECK(warnings == 1, "%d Warnungen fuer eine Nachricht", warnings);
    if (!failures) printf("  eine zu grosse Nachricht wird ganz verworfen, mit einer Warnung\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqttfrag.c")
out.write_text(HARNESS.replace("__CUT__", cut))
print("erzeugt:", out.name)
