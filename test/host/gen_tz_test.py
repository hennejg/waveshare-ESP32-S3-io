#!/usr/bin/env python3
"""Builds a host test for QuickJS's getTimezoneOffset() as the firmware runs it.

The function is cut out of components/quickjs/extern/quickjs/quickjs.c -- with
patches/0001 applied, which the firmware build does -- and its newlib branch is
forced, whatever the host's libc: that branch is the one the ESP32 runs, and
the one that used to put every local-time cron rule an hour late in summer.
It is checked against tm_gmtoff for zones with and without daylight saving
time, across a year boundary and a half-hour zone.

  make -C test/host tz
"""
import pathlib, re
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/quickjs/extern/quickjs/quickjs.c")
fn   = src.func("static int getTimezoneOffset(int64_t time)")
if "#elif !defined(__GLIBC__)" not in fn:
    raise SystemExit("quickjs.c has no newlib branch -- is patches/0001 applied? "
                     "Build the firmware once, or: git -C components/quickjs/extern/quickjs "
                     "apply ../../patches/0001-getTimezoneOffset-portable.patch")
fn = fn.replace("#if defined(_WIN32)", "#if 0", 1).replace("#elif !defined(__GLIBC__)", "#elif 1", 1)

HARNESS = r"""
/* GENERATED by gen_tz_test.py -- do not edit; edit quickjs.c via its patch. */
#define _DEFAULT_SOURCE
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

__CUT__

int main(void)
{
    static const char *const zones[] = {
        "CET-1CEST,M3.5.0,M10.5.0/3", "UTC0", "EST5EDT,M3.2.0,M11.1.0",
        "IST-5:30", "NZST-12NZDT,M9.5.0,M4.1.0/3",
    };
    static const int64_t times[] = {
        1783555200, /* 2026-07-09, summer in the north         */
        1768003200, /* 2026-01-10, winter in the north         */
        1798761300, /* 2026-12-31 23:55 UTC, local date ahead  */
        1774746000, /* 2026-03-29 01:00 UTC, CEST just begun   */
    };
    int failures = 0;
    printf("Zeitzonenversatz von QuickJS (newlib-Zweig)\n");
    for (size_t z = 0; z < sizeof zones / sizeof zones[0]; z++) {
        setenv("TZ", zones[z], 1);
        tzset();
        for (size_t t = 0; t < sizeof times / sizeof times[0]; t++) {
            time_t ti = (time_t)times[t];
            struct tm l;
            localtime_r(&ti, &l);
            int want = (int)(-l.tm_gmtoff / 60);
            int got  = getTimezoneOffset(times[t] * 1000);
            if (got != want) {
                failures++;
                printf("  FEHLER %s bei %lld: %d statt %d Minuten\n",
                       zones[z], (long long)times[t], got, want);
            }
        }
    }
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_tz.c")
out.write_text(HARNESS.replace("__CUT__", fn))
print("erzeugt:", out.name)
