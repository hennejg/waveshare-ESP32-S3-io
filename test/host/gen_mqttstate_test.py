#!/usr/bin/env python3
"""Builds a host test for how the rule engine learns the broker state
(components/scripting/scripting.c).

scripting_on_mqtt_state() and deliver_pending() are cut out verbatim; the
JS side is a recorder.

What it pins down, found by a review: "$sys/mqtt" up/down went through the
event queue and was dropped when it was full -- mqttDown() then never
matched and the local fallback stayed off until the next transition. Now it
is a latch: never lost, and what arrives is the latest state, so a burst of
up/down/up cannot end on the wrong one.
OLD=1 cuts scripting.c from git (OLDREV, default HEAD); before the fix the
function did not exist, so the generator stops there.

  make -C test/host mqttstate
"""
import pathlib, sys
from cutter import Source

src = Source.at("components/scripting/scripting.c")
if "void scripting_on_mqtt_state(bool up)" not in src.text:
    sys.exit("FEHLER: scripting_on_mqtt_state() fehlt -- der Zustand geht nur ueber die Warteschlange")
cuts = (src.span("static volatile uint8_t s_pending;", "static volatile bool s_mqtt_known;      /* a state was ever reported */")
        + src.func("static void deliver_pending(JSContext *ctx, JSValue on_time_sync, JSValue on_mqtt)")
        + src.func("void scripting_on_mqtt_state(bool up)"))

HARNESS = r"""
/* GENERATED by gen_mqttstate_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
typedef int JSContext; typedef const char *JSValue;
static JSValue JS_NewString(JSContext *c, const char *s) { (void)c; return s; }
static void budget_start(void) {}
static int syncs;
static void handle_time_sync(JSContext *c, JSValue f, bool s) { (void)c; (void)f; (void)s; syncs++; }
static char got[8][16]; static int ngot;
static void call2(JSContext *c, JSValue fn, JSValue a, JSValue b)
{ (void)c; (void)fn; if (!strcmp(a, "$sys/mqtt") && ngot < 8) snprintf(got[ngot++], 16, "%s", b); }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Broker-Zustand fuer die Regeln\n");
    JSContext ctx = 0;
    scripting_on_mqtt_state(false);                 /* engine busy, nothing delivered yet */
    scripting_on_mqtt_state(true);
    scripting_on_mqtt_state(false);
    deliver_pending(&ctx, "ts", "mq");
    CHECK(ngot == 1 && !strcmp(got[0], "down"), "nach up/down/up/down: %d Zustellung(en), letzte '%s'", ngot, ngot ? got[ngot - 1] : "-");
    deliver_pending(&ctx, "ts", "mq");
    CHECK(ngot == 1, "Zustand doppelt zugestellt");
    scripting_on_mqtt_state(true);
    deliver_pending(&ctx, "ts", "mq");
    CHECK(ngot == 2 && !strcmp(got[1], "up"), "Wechsel auf up nicht zugestellt");
    CHECK(syncs == 0, "Zeit-Sync ohne Anlass");
    if (!failures) printf("  Zustand geht nie verloren, zugestellt wird der letzte\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqttstate.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
