#!/usr/bin/env python3
"""Builds a host test for rule timer ids past 2^31 (scripting.c).

Cut out of scripting.c verbatim: the timer table, timer_find(), js_set_timer()
and js_clear_timer(); esp_timer stubbed. Real QuickJS and the real dsl.js.

What it pins down, found by a review: ids were handed out as uint32 and
returned to JS as int32, and dsl.js reads a negative id as "refused". From
2^31 on every timer was armed in C but recorded as never scheduled, so nothing
cancelled it: a watchdog fed on time kept the timer of every feed, and the
first one expired it. Here the counter starts just below 2^31 and a watchdog
is fed ten times. OLD=1 cuts scripting.c from git (OLDREV, default HEAD).

  make -C test/host timerid
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/scripting.c")
if os.environ.get("OLD") == "1":
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/scripting/scripting.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

cuts  = src.span("#define MAX_TIMERS", "static uint32_t     s_next_timer_id = 1;")
cuts += "static uint32_t s_timer_full_count;\n"
cuts += src.func("static timer_slot_t *timer_find(uint32_t id)")
cuts += src.defines("TIMER_MAX_MS")
cuts += src.func("static JSValue js_set_timer(JSContext *ctx, JSValue this_val, int argc, JSValue *argv)")
cuts += src.func("static JSValue js_clear_timer(JSContext *ctx, JSValue this_val, int argc, JSValue *argv)")

HARNESS = r"""
/* GENERATED by gen_timerid_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "quickjs.h"

#define TAG "t"
#define ESP_LOGW(tag, ...) do { (void)(tag); } while (0)
typedef int esp_err_t;
#define ESP_OK 0
typedef void *esp_timer_handle_t;
typedef enum { ESP_TIMER_TASK } esp_timer_dispatch_t;
typedef struct { void (*callback)(void *); void *arg; esp_timer_dispatch_t dispatch_method; const char *name; } esp_timer_create_args_t;
static int armed;
static esp_err_t esp_timer_create(const esp_timer_create_args_t *a, esp_timer_handle_t *h) { (void)a; *h = (void *)1; return ESP_OK; }
static esp_err_t esp_timer_start_once(esp_timer_handle_t h, uint64_t us) { (void)h; (void)us; armed++; return ESP_OK; }
static esp_err_t esp_timer_stop(esp_timer_handle_t h) { (void)h; armed--; return ESP_OK; }
static esp_err_t esp_timer_delete(esp_timer_handle_t h) { (void)h; return ESP_OK; }
static void timer_fired_cb(void *arg) { (void)arg; }

__CUT__

static JSValue js_nop(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_UNDEFINED; }
static JSValue js_false(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_FALSE; }
static char *slurp(const char *path)
{
    FILE *f = fopen(path, "rb"); if (!f) { perror(path); exit(2); }
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    char *b = malloc((size_t)n + 1); if (fread(b, 1, (size_t)n, f) != (size_t)n) exit(2); b[n] = 0; fclose(f);
    return b;
}
static int run(JSContext *ctx, const char *s)
{
    JSValue r = JS_Eval(ctx, s, strlen(s), "<t>", JS_EVAL_TYPE_GLOBAL);
    int32_t n = -999;
    if (JS_IsException(r)) { JSValue e = JS_GetException(ctx); const char *m = JS_ToCString(ctx, e); printf("  JS: %s\n", m); JS_FreeCString(ctx, m); JS_FreeValue(ctx, e); }
    else JS_ToInt32(ctx, &n, r);
    JS_FreeValue(ctx, r);
    return n;
}

int main(void)
{
    char *dsl = slurp("../../components/scripting/dsl.js");
    JSRuntime *rt = JS_NewRuntime();
    JSContext *ctx = JS_NewContext(rt);
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "print",        JS_NewCFunction(ctx, js_nop, "print", 1));
    JS_SetPropertyStr(ctx, g, "_di_get",      JS_NewCFunction(ctx, js_false, "_di_get", 1));
    JS_SetPropertyStr(ctx, g, "_set_timer",   JS_NewCFunction(ctx, js_set_timer, "_set_timer", 2));
    JS_SetPropertyStr(ctx, g, "_clear_timer", JS_NewCFunction(ctx, js_clear_timer, "_clear_timer", 1));
    JS_FreeValue(ctx, g);
    run(ctx, dsl);
    int failures = 0;
    printf("Timer-IDs ueber 2^31\n");

    s_next_timer_id = 0x7FFFFFFDu;
    run(ctx, "var wd = watchdog(1000);"
             "rule('feed').when(input(0).isOn()).then(function(){ wd.feed(); });"
             "rule('fb').when(wd.isExpired()).then(function(){});");
    for (int i = 0; i < 10; i++) { run(ctx, "_on_input(0, true)"); run(ctx, "_on_input(0, false)"); }
    int used = 0; for (int i = 0; i < MAX_TIMERS; i++) used += s_timers[i].used;
    int pend = run(ctx, "_pending.length");
    if (used != 1) { failures++; printf("  FEHLER: nach 10 Fuetterungen %d Timer belegt statt 1 -- jede Fuetterung laesst ihren alten stehen\n", used); }
    if (pend != 1) { failures++; printf("  FEHLER: dsl.js fuehrt %d Timer statt 1\n", pend); }
    if (armed != 1) { failures++; printf("  FEHLER: %d esp_timer laufen statt 1\n", armed); }
    int neg = run(ctx, "(function(){ var n = 0; for (var i = 0; i < 20; i++) { var id = _set_timer(10, function(){}); if (id < 0) n++; else _clear_timer(id); } return n; })()");
    if (neg) { failures++; printf("  FEHLER: %d von 20 IDs negativ\n", neg); }
    if (!failures) printf("  Watchdog ueber die Grenze gefuettert: ein Timer, alle IDs positiv\n");

    /* An id still in use is skipped when the counter wraps. */
    for (int i = 0; i < MAX_TIMERS; i++) if (s_timers[i].used) { s_next_timer_id = s_timers[i].id; break; }
    int clash = run(ctx, "(function(){ var id = _set_timer(10, function(){}); var c = _pending.indexOf(id) >= 0 ? 1 : 0; _clear_timer(id); return c; })()");
    used = 0; for (int i = 0; i < MAX_TIMERS; i++) used += s_timers[i].used;
    if (used != 1 || clash) { failures++; printf("  FEHLER: belegte ID neu vergeben (%d belegt)\n", used); }
    else printf("  eine noch belegte ID wird uebersprungen\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_timerid.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
