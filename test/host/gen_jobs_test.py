#!/usr/bin/env python3
"""Builds a host test for the rule engine's promise-job drain (scripting.c).

Cut out of scripting.c verbatim: the time budget (deadline, js_interrupt,
budget_start) and drain_jobs(). Real QuickJS with the firmware's patches.

What it pins down, found by a review: QuickJS turns the budget's interrupt
inside a promise job into an ordinary rejection, so the job "succeeds" and a
.catch() can queue the next one. drain_jobs() ran until the queue was empty
and never got there:

    function again(){ Promise.resolve().then(function(){ for(;;){} }).catch(again); }

held the rule engine until a reboot, and an endless chain of short jobs did
the same. Now the drain has a budget of its own and stops when it is spent.
OLD=1 cuts scripting.c from git (OLDREV, default HEAD); the old drain never
returns, which a 5 s alarm reports.

  make -C test/host jobs
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/scripting.c")
if os.environ.get("OLD") == "1":
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/scripting/scripting.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

new  = "static bool drain_jobs(JSRuntime *rt)" in src.text
cuts  = src.span("static int64_t s_deadline_us;", "static int64_t s_deadline_us;")
cuts += src.span("static bool    s_interrupted;", "static bool    s_interrupted;")
cuts += src.func("static int js_interrupt(JSRuntime *rt, void *opaque)")
cuts += src.func("static inline void budget_start(void)")
cuts += src.func("static bool drain_jobs(JSRuntime *rt)" if new else "static void drain_jobs(JSRuntime *rt)")

HARNESS = r"""
/* GENERATED by gen_jobs_test.py -- do not edit; edit scripting.c. */
#include <signal.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <unistd.h>
#include "quickjs.h"

#define TAG "t"
static int logs;
#define ESP_LOGW(tag, ...) do { logs++; printf("    log: "); printf(__VA_ARGS__); printf("\n"); } while (0)
#define ESP_LOGE ESP_LOGW
#define TIME_BUDGET_US ((int64_t)50 * 1000)   /* 50 ms instead of 2 s */
static int64_t esp_timer_get_time(void)
{
    struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
    return (int64_t)ts.tv_sec * 1000000 + ts.tv_nsec / 1000;
}

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static const char *what = "";
static void on_alarm(int sig)
{
    (void)sig;
    printf("  FEHLER: %s: drain_jobs() kehrt nach 5 s nicht zurueck -- die Regel-Engine haengt\nFEHLER\n", what);
    fflush(stdout);
    _exit(1);
}

static JSRuntime *rt;
static JSContext *ctx;

static void run(const char *code)
{
    budget_start();
    JSValue r = JS_Eval(ctx, code, strlen(code), "<t>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(r)) { JSValue e = JS_GetException(ctx); JS_FreeValue(ctx, e); }
    JS_FreeValue(ctx, r);
}
static int32_t num(const char *name)
{
    JSValue g = JS_GetGlobalObject(ctx), v = JS_GetPropertyStr(ctx, g, name);
    int32_t n = 0; JS_ToInt32(ctx, &n, v);
    JS_FreeValue(ctx, v); JS_FreeValue(ctx, g);
    return n;
}
static double drain_ms(void)
{
    int64_t t0 = esp_timer_get_time();
    alarm(5);
    drain_jobs(rt);
    alarm(0);
    return (esp_timer_get_time() - t0) / 1000.0;
}

int main(void)
{
    signal(SIGALRM, on_alarm);
    rt  = JS_NewRuntime();
    JS_SetInterruptHandler(rt, js_interrupt, NULL);
    ctx = JS_NewContext(rt);
    printf("Promise-Jobs unter dem Zeitbudget\n");

    what = "gewoehnliche Promises";
    run("var done = 0; Promise.resolve(1).then(function (v) { return v + 1; }).then(function (v) { done = v; });");
    drain_ms();
    CHECK(num("done") == 2, "gewoehnliche Promise-Kette nicht zu Ende gelaufen (done=%d)", num("done"));
    CHECK(!s_interrupted, "gewoehnliche Promises als Budgetueberschreitung gemeldet");
    printf("  gewoehnliche Promises laufen vollstaendig\n");

    what = "1000 kurze Jobs";
    run("var n = 0; function f() { if (++n < 1000) Promise.resolve().then(f); } f();");
    drain_ms();
    CHECK(num("n") == 1000, "Kette von 1000 kurzen Jobs abgebrochen bei %d", num("n"));
    CHECK(!s_interrupted, "1000 kurze Jobs als Budgetueberschreitung gemeldet");
    printf("  1000 kurze Jobs in einem Durchgang\n");

    what = "endlose Kette kurzer Jobs";
    run("var k = 0; function g() { k++; Promise.resolve().then(g); } g();");
    double ms = drain_ms();
    CHECK(s_interrupted, "endlose Kette: kein Abbruch gemeldet");
    CHECK(ms < 500, "endlose Kette: %.0f ms statt etwa eines Budgets", ms);
    printf("  endlose Kette kurzer Jobs: nach %.0f ms beendet\n", ms);
    s_interrupted = false;
    int before = num("k");
    drain_ms();
    CHECK(num("k") > before, "Rest der Kette laeuft im naechsten Durchgang nicht weiter");
    printf("  der Rest laeuft im naechsten Durchgang weiter\n");
    run("g = function () {};");   /* end it */
    s_interrupted = false; drain_ms(); s_interrupted = false;

    what = "der gemeldete Fall (.catch(again))";
    run("var c = 0; function again() { c++; Promise.resolve().then(function () { for (;;) {} }).catch(again); } again();");
    ms = drain_ms();
    CHECK(s_interrupted, "catch-Kette: kein Abbruch gemeldet");
    CHECK(ms < 500, "catch-Kette: %.0f ms statt etwa eines Budgets", ms);
    printf("  for(;;) mit .catch(again): nach %.0f ms beendet, %d Runde(n)\n", ms, num("c"));

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    JS_FreeContext(ctx);
    JS_FreeRuntime(rt);
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_jobs.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
