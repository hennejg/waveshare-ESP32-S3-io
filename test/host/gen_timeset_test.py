#!/usr/bin/env python3
"""Builds a host test for setting the clock from the web UI (web_server.c).

POST /api/time is cut out verbatim (web_common.c, before that web_server.c); the HTTP server, the RTC and the rule
engine's hook are recorded.

What it pins down, found by a review: the handler stepped the clock and the
RTC but never told the rule engine, as an SNTP sync does. On a board with no
SNTP and no valid RTC -- where setting the time by hand is the only way --
cron rules were never armed until the next reboot; on a running clock they
stayed armed for the old time.
OLD=1 cuts web_server.c from git (OLDREV, default HEAD).

  make -C test/host timeset
"""
import pathlib
from cutter import Source, json_exact_if_used

src  = Source.at("apps/full/main/web_server.c")
if "static esp_err_t api_time_post(httpd_req_t *req)" in src.text:
    cuts = src.defines("BODY_MAX") + src.func("static esp_err_t api_time_post(httpd_req_t *req)")
else:
    # Since both firmwares have it: components/board/web_common.c, where the
    # rule engine's hook is behind CONFIG_APP_SCRIPTING_ENABLE.
    common = Source.at("components/board/web_common.c")
    cuts = ("#define CONFIG_APP_SCRIPTING_ENABLE 1\n" + common.defines("TIME_BODY_MAX")
            + common.func("esp_err_t web_api_time_post(httpd_req_t *req)")
            + "#define api_time_post web_api_time_post\n")

HARNESS = r"""
/* GENERATED by gen_timeset_test.py -- do not edit; edit web_server.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <sys/time.h>
#include "cJSON.h"
typedef int esp_err_t;
#define ESP_OK 0
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
typedef struct { size_t content_len; } httpd_req_t;
enum { HTTPD_400_BAD_REQUEST = 400, HTTPD_500_INTERNAL_SERVER_ERROR = 500 };
static int last_status; static const char *req_body;
static bool check_auth(httpd_req_t *r) { (void)r; return true; }
static esp_err_t send_denied(httpd_req_t *r) { (void)r; last_status = 401; return ESP_OK; }
static esp_err_t httpd_resp_send_err(httpd_req_t *r, int code, const char *m) { (void)r; (void)m; last_status = code; return ESP_OK; }
static esp_err_t httpd_resp_set_type(httpd_req_t *r, const char *t) { (void)r; (void)t; return ESP_OK; }
static esp_err_t httpd_resp_sendstr(httpd_req_t *r, const char *s) { (void)r; (void)s; last_status = 200; return ESP_OK; }
static int recv_body(httpd_req_t *r, char *buf, size_t cap) { (void)r; snprintf(buf, cap + 1, "%s", req_body); return (int)strlen(buf); }
/* Since web_common.c the helpers carry a web_ prefix; the stubs serve both. */
#define web_check_auth check_auth
#define web_send_denied send_denied
#define web_send_json send_json
#define web_recv_body recv_body
static time_t clock_set;
static int test_settimeofday(const struct timeval *tv, const void *tz) { (void)tz; clock_set = tv->tv_sec; return 0; }
#define settimeofday test_settimeofday
static esp_err_t rtc_dev_set(const struct tm *t) { (void)t; return ESP_OK; }
static void iso8601_utc(time_t t, char *b, size_t n) { (void)t; snprintf(b, n, "x"); }
static int time_syncs;
void scripting_on_time_sync(void) { time_syncs++; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Uhr von Hand stellen\n");
    httpd_req_t rq = { 30 };
    req_body = "{\"epoch\":1791612000}";
    api_time_post(&rq);
    CHECK(last_status == 200 && clock_set == 1791612000, "Uhr nicht gestellt (Status %d)", last_status);
    CHECK(time_syncs == 1, "Regel-Engine nicht benachrichtigt (%d)", time_syncs);
    req_body = "{\"epoch\":5}"; time_syncs = 0;
    api_time_post(&rq);
    CHECK(last_status == 400 && time_syncs == 0, "ungueltige Zeit: Status %d, %d Benachrichtigung(en)", last_status, time_syncs);
    if (!failures) printf("  gestellte Uhr: Regel-Engine benachrichtigt wie nach SNTP; ungueltige Zeit nicht\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_timeset.c")
out.write_text(HARNESS.replace("__CUT__", json_exact_if_used(cuts) + cuts))
print("erzeugt:", out.name)
