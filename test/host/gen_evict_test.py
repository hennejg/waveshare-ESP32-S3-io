#!/usr/bin/env python3
"""Builds a host test for the Modbus TCP server at its connection limit
(mb_tcp_server.c).

accept_one(), close_slot() and oldest_idle() are cut out of mb_tcp_server.c
verbatim, with conn_t and the #defines; the socket calls are stubs.

What it pins down, found by a review: with all eight slots taken a new
connection was closed at once, and nothing ever freed a slot whose client
stayed connected and silent -- keepalive only finds dead peers. Any host on
the network could open eight connections, send nothing, and lock every SCADA
client out. Now the slot idle longest (at least EVICT_IDLE_MS) is closed for
the newcomer; an active one, one with a frame half received or an answer
still going out, or one a worker holds, never is.
OLD=1 cuts mb_tcp_server.c from git (OLDREV, default HEAD).

  make -C test/host evict
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("apps/full/main/mb_tcp_server.c")
bud  = Source.at("apps/full/main/net_budget.h")
new = "static int oldest_idle(int64_t now)" in src.text

defines = bud.defines("NET_SOCK_MB_CONN") + src.defines("MBAP_HDR", "FRAME_MAX", "MB_TCP_MAX_CONN", "KEEPALIVE_IDLE_S", "KEEPALIVE_INTVL_S", "KEEPALIVE_COUNT") + \
          (src.defines("EVICT_IDLE_MS") if new else "#define EVICT_IDLE_MS 2000\n")
types = src.type("SLOT_BUSY };") + src.type("} conn_t;")
cuts  = (src.func("static inline uint8_t slot_state(int i)") if "slot_state(int i)" in src.text else "")
cuts += src.func("static void close_slot(int i)")
if new: cuts += src.func("static int oldest_idle(int64_t now)")
cuts += src.func("static bool accept_one(void)")

HARNESS = r"""
/* GENERATED by gen_evict_test.py -- do not edit; edit mb_tcp_server.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <sys/socket.h>
#include <netinet/in.h>
#include <netinet/tcp.h>
#include "mb_pdu.h"
#ifndef TCP_KEEPIDLE
#define TCP_KEEPIDLE 0x10
#endif
#define TAG "t"
#define ESP_LOGW(...) ((void)0)
#define ESP_LOGD(...) ((void)0)
__DEFINES__
__TYPES__
static conn_t s_conn[MB_TCP_MAX_CONN];
static struct { unsigned accepted, refused, evicted; } s_stats;
static int s_listen_fd = 3;
static int64_t clock_us;
static int next_fd = 100, closed[1024];
static int64_t esp_timer_get_time(void) { return clock_us; }
#define accept      stub_accept
#define close       stub_close
#define setsockopt  stub_setsockopt
#define getsockname stub_getsockname
static int stub_accept(int s, struct sockaddr *a, socklen_t *l) { (void)s; (void)a; (void)l; return next_fd++; }
static int stub_close(int fd) { if (fd >= 0 && fd < 1024) closed[fd] = 1; return 0; }
static int stub_setsockopt(int s, int l, int o, const void *v, socklen_t n) { (void)s; (void)l; (void)o; (void)v; (void)n; return 0; }
static int stub_getsockname(int s, struct sockaddr *a, socklen_t *l) { (void)s; (void)a; (void)l; return -1; }

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
static void reset(void)
{
    memset(s_conn, 0, sizeof s_conn); memset(&s_stats, 0, sizeof s_stats); memset(closed, 0, sizeof closed);
    for (int i = 0; i < MB_TCP_MAX_CONN; i++) s_conn[i].fd = -1;
    clock_us = 0; next_fd = 100;
}
static int slot_of(int fd) { for (int i = 0; i < MB_TCP_MAX_CONN; i++) if (s_conn[i].fd == fd && s_conn[i].state != SLOT_FREE) return i; return -1; }

int main(void)
{
    printf("Modbus TCP am Verbindungslimit\n");

    /* 1. Eight connections, opened one second apart, then silent. */
    reset();
    for (int i = 0; i < MB_TCP_MAX_CONN; i++) { clock_us = (int64_t)i * 1000000; accept_one(); }
    clock_us += 5 * 1000000;
    int fd9 = next_fd; accept_one();
    CHECK(slot_of(fd9) >= 0, "8 stille Verbindungen: die neunte wird abgewiesen (%u abgewiesen)", s_stats.refused);
    CHECK(closed[100] && slot_of(100) < 0, "nicht die am laengsten stille Verbindung geschlossen");
    for (int f = 101; f < 100 + MB_TCP_MAX_CONN; f++) CHECK(slot_of(f) >= 0, "Verbindung %d unnoetig geschlossen", f);
    if (!failures) printf("  8 stille Verbindungen: die neunte uebernimmt den Platz der aeltesten\n");

    /* 2. Eight connections all used within EVICT_IDLE_MS: the newcomer goes. */
    int f0 = failures;
    reset();
    for (int i = 0; i < MB_TCP_MAX_CONN; i++) accept_one();
    clock_us = (int64_t)EVICT_IDLE_MS * 1000 - 1;
    fd9 = next_fd; accept_one();
    CHECK(slot_of(fd9) < 0 && s_stats.refused == 1, "aktive Verbindung verdraengt");
    if (failures == f0) printf("  8 aktive Verbindungen: die neunte wird abgewiesen, keine verdraengt\n");

    /* 3. Never a slot with a frame half in, an answer half out, or a worker's. */
    f0 = failures;
    reset();
    for (int i = 0; i < MB_TCP_MAX_CONN; i++) accept_one();
    for (int i = 0; i < MB_TCP_MAX_CONN; i++) {
        if (i % 3 == 0) s_conn[i].got = 3;
        else if (i % 3 == 1) s_conn[i].out_len = 9;
        else s_conn[i].state = SLOT_BUSY;
    }
    clock_us = 60LL * 1000000;
    fd9 = next_fd; accept_one();
    CHECK(slot_of(fd9) < 0, "Verbindung mitten in einem Rahmen oder mit offener Antwort verdraengt");
    if (failures == f0) printf("  halbe Rahmen, offene Antworten, Worker-Slots bleiben unangetastet\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_evict.c")
out.write_text(HARNESS.replace("__DEFINES__", defines).replace("__TYPES__", types).replace("__CUT__", cuts))
print("erzeugt:", out.name)
