#!/usr/bin/env python3
"""Builds a host test for the rule engine's start
(components/scripting/scripting.c).

Cut out verbatim: scripting_init(), engine_context_new() and the start of
scripting_task() up to its first binding, with the engine's sizes. FreeRTOS
and QuickJS are recorders that fail a chosen allocation.

What it pins down, found by a review: a failed allocation in
scripting_init() returned with the locks and the store task left behind and,
after a failed task, the queue deleted but its handle kept -- producers then
wrote to a freed queue. A second call created everything once more over the
running engine. In the task, a runtime or context QuickJS could not allocate
was used as it was. Now every failure frees what was made and clears the
handles, a second start is ESP_ERR_INVALID_STATE, and the task tries again
every second until QuickJS has its memory.
OLD=1 cuts scripting.c from git (OLDREV, default HEAD); before the fix the
failures left resources and handles behind.

  make -C test/host scriptinit
"""
import pathlib
from cutter import Source

src = Source.at("components/scripting/scripting.c")
sizes = src.defines("TASK_STACK_BYTES", "TASK_PRIORITY", "QUEUE_DEPTH", "JS_HEAP_LIMIT", "JS_STACK_LIMIT")
helper = (src.func("static JSContext *engine_context_new(JSRuntime **runtime)")
          if "static JSContext *engine_context_new(" in src.text else "")
# The task up to its first binding, closed off: everything after needs a
# working engine, which the recorders are not.
first = "    scripting_register_bindings(ctx);"
startup = (src.span("static void scripting_task(void *arg)", first)[:-len(first) - 1]
           .replace("scripting_task(", "startup_probe(", 1)
           + "    probe_ok = ctx && rt;\n    if (ctx) JS_FreeContext(ctx);\n    if (rt) JS_FreeRuntime(rt);\n}\n")
init = src.func("esp_err_t scripting_init(const char *user_script, const scripting_io_t *io)")

HARNESS = r"""
/* GENERATED by gen_scriptinit_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_ERR_NO_MEM 1
#define ESP_ERR_INVALID_ARG 2
#define ESP_ERR_INVALID_STATE 3
#define ESP_LOGE(...) ((void)0)
#define TAG "t"
#define MALLOC_CAP_SPIRAM 1
#define MALLOC_CAP_8BIT 2
#define pdPASS 1
#define pdMS_TO_TICKS(n) (n)
typedef int BaseType_t;
typedef uint32_t StackType_t;
typedef void *SemaphoreHandle_t;
typedef void *QueueHandle_t;
typedef void *TaskHandle_t;
typedef struct { int unused; } scripting_io_t;
typedef struct { int unused; } scripting_evt_t;

__SIZES__

static const scripting_io_t *g_scripting_io;
static const char *s_user_script;
static SemaphoreHandle_t s_subs_mux, s_reload_lock, s_send_lock;
static QueueHandle_t s_queue;
static TaskHandle_t s_store_task, s_engine_task;

/* FreeRTOS: every lock, queue and task is one allocation; fail_at fails the
   n-th, live counts what is still held. */
static int alloc_call, fail_at = -1, live;
static void *resource(void)
{
    if (alloc_call++ == fail_at) return NULL;
    void *p = malloc(1); if (p) live++; return p;
}
static void release(void *p) { if (p) { free(p); live--; } }
static SemaphoreHandle_t xSemaphoreCreateMutex(void) { return resource(); }
static void vSemaphoreDelete(SemaphoreHandle_t h) { release(h); }
static QueueHandle_t xQueueCreate(int n, size_t size) { (void)n; (void)size; return resource(); }
static void vQueueDelete(QueueHandle_t h) { release(h); }
static void vTaskDelete(TaskHandle_t h) { release(h); }
static int xTaskCreate(void (*f)(void *), const char *name, unsigned stack, void *arg, int prio, TaskHandle_t *h)
{ (void)f; (void)name; (void)stack; (void)arg; (void)prio; *h = resource(); return *h ? pdPASS : 0; }
static int xTaskCreateWithCaps(void (*f)(void *), const char *name, unsigned stack, void *arg, int prio, TaskHandle_t *h, int caps)
{ (void)caps; return xTaskCreate(f, name, stack, arg, prio, h); }
static void store_task(void *arg) { (void)arg; }
static void scripting_task(void *arg) { (void)arg; }

/* QuickJS: a runtime or context that fails on request; a call with NULL is
   counted as a use of a failed allocation. */
typedef struct { int unused; } JSRuntime;
typedef struct { int unused; } JSContext;
typedef struct { int unused; } JSMallocFunctions;
static const JSMallocFunctions s_psram_alloc = {0};
static int fail_runtime, fail_context, runtimes, contexts, null_uses, delays;
static bool probe_ok;
static JSRuntime *JS_NewRuntime2(const JSMallocFunctions *a, void *opaque)
{ (void)a; (void)opaque; if (fail_runtime) { fail_runtime--; return NULL; } runtimes++; return malloc(sizeof(JSRuntime)); }
static void JS_FreeRuntime(JSRuntime *rt) { if (rt) { free(rt); runtimes--; } }
static JSContext *JS_NewContext(JSRuntime *rt)
{
    if (!rt) { null_uses++; return NULL; }
    if (fail_context) { fail_context--; return NULL; }
    contexts++; return malloc(sizeof(JSContext));
}
static void JS_FreeContext(JSContext *ctx) { free(ctx); contexts--; }
static void JS_SetMemoryLimit(JSRuntime *rt, size_t n) { (void)n; if (!rt) null_uses++; }
static void JS_SetMaxStackSize(JSRuntime *rt, size_t n) { (void)n; if (!rt) null_uses++; }
static void JS_SetGCThreshold(JSRuntime *rt, size_t n) { (void)n; if (!rt) null_uses++; }
static int js_interrupt(JSRuntime *rt, void *opaque) { (void)rt; (void)opaque; return 0; }
static void JS_SetInterruptHandler(JSRuntime *rt, int (*f)(JSRuntime *, void *), void *opaque)
{ (void)f; (void)opaque; if (!rt) null_uses++; }
static void vTaskDelay(unsigned ticks)
{
    if (ticks != 1000 || ++delays > 3) { printf("  FEHLER: Startwiederholung nicht im Sekundentakt oder ohne Ende\n"); exit(2); }
}

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

/* The old code leaves freed handles behind: forget them, never free twice. */
static void forget(void)
{
    s_subs_mux = s_reload_lock = s_send_lock = s_queue = s_store_task = s_engine_task = NULL;
    alloc_call = live = 0;
}

int main(void)
{
    printf("Regel-Engine: Start bei Speichermangel\n");
    static scripting_io_t io;
    static const char *const what[] = { "Abo-Sperre", "Lade-Sperre", "Ereignis-Sperre", "Queue", "Store-Task", "Engine-Task" };
    for (int stage = 0; stage < 6; stage++) {
        forget(); fail_at = stage;
        esp_err_t e = scripting_init("", &io);
        bool clean = live == 0 && !s_queue && !s_store_task && !s_engine_task &&
                     !s_send_lock && !s_reload_lock && !s_subs_mux;
        CHECK(e == ESP_ERR_NO_MEM && clean, "%s fehlgeschlagen: Ergebnis %d, %d Ressourcen oder Handles bleiben", what[stage], e, live);
        if (!clean) continue;
        fail_at = -1;
        CHECK(scripting_init("", &io) == ESP_OK && live == 6, "%s: zweiter Versuch startet nicht", what[stage]);
        int before = live;
        CHECK(scripting_init("", &io) == ESP_ERR_INVALID_STATE && live == before,
              "zweiter Start ueber laufender Engine: %d statt %d Ressourcen", live, before);
        release(s_engine_task); release(s_store_task); release(s_queue);
        release(s_send_lock); release(s_reload_lock); release(s_subs_mux);
    }
    if (!failures) printf("  scripting_init: jede der sechs Allokationen gibt bei Fehler alles frei; zweiter Start abgelehnt\n");

    int f0 = failures;
    for (int stage = 0; stage < 2; stage++) {
        fail_runtime = stage == 0; fail_context = stage == 1;
        delays = null_uses = 0; probe_ok = false;
        startup_probe(NULL);
        CHECK(probe_ok && delays == 1 && null_uses == 0, "%s fehlgeschlagen: %d NULL-Zugriffe, %d Wiederholungen",
              stage ? "JS_NewContext" : "JS_NewRuntime2", null_uses, delays);
        CHECK(runtimes == 0 && contexts == 0, "%s fehlgeschlagen: %d Runtimes, %d Kontexte nicht freigegeben",
              stage ? "JS_NewContext" : "JS_NewRuntime2", runtimes, contexts);
    }
    if (failures == f0) printf("  Engine-Task: fehlende QuickJS-Runtime oder -Kontext nicht benutzt, nach 1 s erneut versucht\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_scriptinit.c")
out.write_text(HARNESS.replace("__SIZES__", sizes).replace("__CUT__", helper + startup + init))
print("erzeugt:", out.name)
