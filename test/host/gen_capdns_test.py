#!/usr/bin/env python3
"""Builds a host test for the setup AP's DNS server (wifi_config.c).

The reply builder is cut out of wifi_config.c verbatim (with OLD=1, the
per-datagram block of the old dns_task, run on the same 512-byte buffer).

What it pins down, found by a review: the QNAME was measured with strlen()
on a receive buffer that is not terminated and keeps the bytes of earlier,
longer datagrams. Anyone on the open setup AP could send 512 non-zero bytes
and then a short query: the reply was written past the buffer and sent with
stack contents. Now every read stays within the datagram, compression
pointers and responses are dropped, and the reply must fit the buffer.
OLD=1 cuts wifi_config.c from git (OLDREV, default HEAD).

  make -C test/host capdns
"""
import pathlib
from cutter import Source

src = Source.at("components/esp32-wifi-bootstrap/src/wifi_config.c")
new = "static size_t dns_build_reply(" in src.text
if new:
    cut = src.func("static size_t dns_build_reply(uint8_t *buf, size_t len, size_t cap, const uint8_t ip[4]) {")
    runner = """
static size_t reply(size_t count)
{
    static const uint8_t ip[4] = { 192, 168, 4, 1 };
    size_t n = dns_build_reply(rxbuf, count, sizeof rxbuf, ip);
    if (n) { memcpy(sent, rxbuf, n); sent_len = n; } else sent_len = 0;
    return sent_len;
}
"""
else:
    block = src.span("/* Drop messages that are too small or too large to build a valid response */",
                     "sendto(fd, buffer, reply_len, 0, &src_addr, src_addr_len);\n                }")
    cut = ""
    runner = ("""
static size_t reply(size_t count)
{
    ip4_addr_t server_addr = { { 192, 168, 4, 1 } };
    struct sockaddr src_addr = { .sa_family = AF_INET }; socklen_t src_addr_len = 0; int fd = 0;
    sent_len = 0;
    char *buffer = (char *)::buffer;
    """ + block + """
    return sent_len;
}
""").replace("char *buffer = (char *)::buffer;", "char buffer[512]; memcpy(buffer, rxbuf, 512);")

HARNESS = r"""
/* GENERATED by gen_capdns_test.py -- do not edit; edit wifi_config.c. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>
#include <unistd.h>

#define INFO(...) ((void)0)
#define DEBUG(...) ((void)0)
#define AF_INET 2
struct sockaddr { int sa_family; };
typedef int socklen_t;
typedef struct { uint8_t b[4]; } ip4_addr_t;
#define ip4_addr1(a) ((a)->b[0])
#define ip4_addr2(a) ((a)->b[1])
#define ip4_addr3(a) ((a)->b[2])
#define ip4_addr4(a) ((a)->b[3])

static uint8_t rxbuf[512];     /* the task's receive buffer, kept between datagrams */
static uint8_t sent[4096]; static size_t sent_len;
static void sendto(int fd, const void *b, size_t n, int f, const struct sockaddr *a, socklen_t l)
{ (void)fd; (void)f; (void)a; (void)l; if (n > sizeof sent) n = sizeof sent; memcpy(sent, b, n); sent_len = n; }

__CUT__
__RUNNER__

/* What recvfrom() does: the datagram at the start, the rest left as it was. */
static size_t recv_(const uint8_t *d, size_t n) { memcpy(rxbuf, d, n); return n; }

static const uint8_t Q_A[] = { 0x12,0x34, 0x01,0x00, 0,1, 0,0, 0,0, 0,0,
    7,'e','x','a','m','p','l','e', 3,'c','o','m', 0, 0x00,0x01, 0x00,0x01 };

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static int child(void (*fn)(void))
{
    fflush(stdout);
    pid_t p = fork();
    if (p == 0) { fn(); _exit(0); }
    int st = 0; waitpid(p, &st, 0);
    return WIFEXITED(st) && WEXITSTATUS(st) == 0;
}

/* 512 bytes of 'A', dropped, then a 13-byte query whose name has no end
   inside the datagram. */
static void stale_then_short(void)
{
    uint8_t big[512]; memset(big, 'A', sizeof big);
    reply(recv_(big, sizeof big));
    uint8_t q[13] = { 0x55,0x55, 0x01,0x00, 0,1, 0,0, 0,0, 0,0, 'A' };
    size_t n = reply(recv_(q, sizeof q));
    if (n > 13 + 32) _exit(3);          /* answered from beyond the datagram */
}

int main(void)
{
    printf("DNS-Server des Setup-AP\n");

    size_t n = reply(recv_(Q_A, sizeof Q_A));
    CHECK(n == sizeof Q_A + 16, "A-Anfrage: Antwort %zu statt %zu Bytes", n, sizeof Q_A + 16);
    CHECK(n >= sizeof Q_A + 16 && sent[2] & 0x80 && sent[7] == 1 && !memcmp(sent + n - 4, "\xC0\xA8\x04\x01", 4),
          "A-Anfrage: keine Antwort mit 192.168.4.1");
    uint8_t aaaa[sizeof Q_A]; memcpy(aaaa, Q_A, sizeof Q_A); aaaa[sizeof Q_A - 3] = 0x1C;
    n = reply(recv_(aaaa, sizeof aaaa));
    CHECK(n == sizeof Q_A && sent[7] == 0, "AAAA-Anfrage: %zu Bytes, ANCOUNT %u", n, sent[7]);
    if (!failures) printf("  A und AAAA wie bisher beantwortet\n");

    int f0 = failures;
    CHECK(child(stale_then_short), "512 Byte Muell, dann kurze Anfrage: Absturz oder Antwort aus fremdem Speicher");
    uint8_t ptr[sizeof Q_A]; memcpy(ptr, Q_A, sizeof Q_A); ptr[12] = 0xC0; ptr[13] = 0x0C;
    n = reply(recv_(ptr, sizeof ptr));
    CHECK(n == 0, "Kompressionszeiger im QNAME beantwortet (%zu Bytes)", n);
    uint8_t resp[sizeof Q_A]; memcpy(resp, Q_A, sizeof Q_A); resp[2] |= 0x80;
    n = reply(recv_(resp, sizeof resp));
    CHECK(n == 0, "Antwort-Paket (QR=1) beantwortet");
    n = reply(recv_(Q_A, 20));
    CHECK(n == 0, "abgeschnittene Anfrage beantwortet (%zu Bytes)", n);
    if (failures == f0) printf("  Muell, Zeiger, Antworten, abgeschnittene Anfragen: verworfen, kein Lesen ueber das Paket hinaus\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_capdns.c")
out.write_text(HARNESS.replace("__CUT__", cut).replace("__RUNNER__", runner))
print("erzeugt:", out.name)
