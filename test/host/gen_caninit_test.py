#!/usr/bin/env python3
"""Builds a host test for a failed CAN start (can_server.c).

can_server_init() is cut out of can_server.c verbatim; the TWAI driver,
the queue and the task are recorders, and any one step can be made to fail.

What it pins down, found by a review: nothing after twai_new_node_onchip()
was undone on failure, and two results were never looked at. A receive
queue that could not be created was found by the first frame on the bus, in
the ISR; a node whose enable failed was left holding the controller and its
pins; an enabled node whose worker task could not start received into a
queue nobody emptied. Now the queue is checked before the node exists and
every later failure deletes the node again.
OLD=1 cuts can_server.c from git (OLDREV, default HEAD).

  make -C test/host caninit
"""
import pathlib
from cutter import Source

src = Source.at("apps/full/main/can_server.c")
cuts = src.func("esp_err_t can_server_init(void)")

HARNESS = r"""
/* GENERATED by gen_caninit_test.py -- do not edit; edit can_server.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <inttypes.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define ESP_ERR_NO_MEM 0x101
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGE(tag, ...) ((void)snprintf(NULL, 0, __VA_ARGS__))
static const char *esp_err_to_name(esp_err_t e) { (void)e; return "?"; }
#define ESP_RETURN_ON_ERROR(x, tag, ...) do { esp_err_t _r = (x); if (_r != ESP_OK) return _r; } while (0)
#define ESP_RETURN_ON_FALSE(c, err, tag, ...) do { if (!(c)) return (err); } while (0)
#define pdPASS 1
#define GPIO_NUM_NC -1
#define CAN_TX_GPIO 1
#define CAN_RX_GPIO 2
#define TX_QUEUE_DEPTH 8
#define RX_QUEUE_DEPTH 16
#define N2K_MFR_CODE 0x7FF
enum { CAN_MODE_BASIC = 1, CAN_MODE_N2K = 2 };
enum { AC_CLAIMING = 1 };
typedef struct { struct { uint8_t mode; uint32_t bitrate; uint16_t base_id; uint8_t n2k_addr; } can; } app_config_t;
static app_config_t cfg;
static const app_config_t *app_config_get(void) { return &cfg; }
typedef struct { int ide; } rx_msg_t;
typedef void *QueueHandle_t;
typedef uint32_t TickType_t;
static TickType_t xTaskGetTickCount(void) { return 0; }

typedef struct { uint32_t bitrate; } twai_timing_basic_config_t;
typedef struct { struct { int tx, rx, quanta_clk_out, bus_off_indicator; } io_cfg;
                 twai_timing_basic_config_t bit_timing; int tx_queue_depth; int fail_retry_cnt; } twai_onchip_node_config_t;
typedef struct node *twai_node_handle_t;
struct node { bool enabled; };
typedef struct { void *on_rx_done, *on_tx_done; } twai_event_callbacks_t;
static int rx_done_cb, tx_done_cb;
#define rx_done_cb ((void *)&rx_done_cb)
#define tx_done_cb ((void *)&tx_done_cb)
static void can_worker_task(void *a) { (void)a; }

static uint8_t   s_mode;
static twai_node_handle_t s_node;
static QueueHandle_t s_rx_q;
static uint16_t s_base;
static uint8_t  s_addr, s_ac_state, s_name[8];
static TickType_t s_claim_tick;
static void n2k_build_name(uint8_t *n) { (void)n; }
static void n2k_send_address_claim(uint8_t a) { (void)a; }

static bool fail_queue, fail_new, fail_cbs, fail_enable, fail_task;
static int nodes_alive, nodes_enabled, queue_obj;
static struct node the_node;
static QueueHandle_t xQueueCreate(int n, size_t sz) { (void)n; (void)sz; return fail_queue ? NULL : &queue_obj; }
static esp_err_t twai_new_node_onchip(const twai_onchip_node_config_t *c, twai_node_handle_t *h)
{ (void)c; if (fail_new) return ESP_FAIL; *h = &the_node; nodes_alive++; return ESP_OK; }
static esp_err_t twai_node_register_event_callbacks(twai_node_handle_t n, const twai_event_callbacks_t *c, void *u)
{ (void)n; (void)c; (void)u; return fail_cbs ? ESP_FAIL : ESP_OK; }
static esp_err_t twai_node_enable(twai_node_handle_t n) { if (fail_enable) return ESP_FAIL; n->enabled = true; nodes_enabled++; return ESP_OK; }
static esp_err_t twai_node_disable(twai_node_handle_t n) { n->enabled = false; nodes_enabled--; return ESP_OK; }
static esp_err_t twai_node_delete(twai_node_handle_t n) { (void)n; nodes_alive--; return ESP_OK; }
static int xTaskCreate(void (*fn)(void *), const char *nm, int st, void *a, int pr, void *h)
{ (void)fn; (void)nm; (void)st; (void)a; (void)pr; (void)h; return fail_task ? 0 : pdPASS; }

__CUT__

static void reset(void)
{
    fail_queue = fail_new = fail_cbs = fail_enable = fail_task = false;
    nodes_alive = nodes_enabled = 0; s_node = NULL; s_rx_q = NULL; the_node.enabled = false;
}

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("CAN-Start: Fehlerpfade\n");
    cfg.can.mode = CAN_MODE_BASIC; cfg.can.bitrate = 500000;

    reset(); fail_queue = true;
    CHECK(can_server_init() != ESP_OK, "Empfangsqueue fehlt, Start meldet ok");
    CHECK(nodes_alive == 0, "Empfangsqueue fehlt, Knoten trotzdem angelegt");

    const char *what[] = { "Callbacks", "Enable", "Worker-Task" };
    for (int i = 0; i < 3; i++) {
        reset();
        if (i == 0) fail_cbs = true; else if (i == 1) fail_enable = true; else fail_task = true;
        esp_err_t r = can_server_init();
        CHECK(r != ESP_OK, "%s scheitert, Start meldet ok", what[i]);
        CHECK(nodes_alive == 0 && nodes_enabled == 0, "%s scheitert: Knoten bleibt (%d angelegt, %d aktiv)", what[i], nodes_alive, nodes_enabled);
        CHECK(s_node == NULL, "%s scheitert: s_node zeigt auf den Knoten", what[i]);
    }
    reset();
    CHECK(can_server_init() == ESP_OK && nodes_alive == 1 && nodes_enabled == 1 && s_rx_q, "ordentlicher Start");
    if (!failures) printf("  ein gescheiterter Schritt gibt den Knoten wieder frei; keine Queue, kein Knoten\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_caninit.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
