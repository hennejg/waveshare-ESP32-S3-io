#!/usr/bin/env python3
"""Builds a host test for POST /api/io/led in both firmwares
(apps/full/main/web_server.c, apps/matter/main/web_server.c,
components/board/web_common.c).

Cut out verbatim: both api_io_led() handlers, web_led_color_parse(),
web_json_uint() and json_parse_exact(). cJSON is ESP-IDF's own; the HTTP
server and the LED are recorders.

What it pins down, found by a review: the handlers took what they could
get from a request and switched the LED anyway. "#ff0000xyz" was red,
"#zzzzzz" or a colour that was no string black, an r of 256 or 0.5 was
read as 0, and an empty object -- or one with a component missing --
switched the LED off. Now a request is "color" as exactly "#RRGGBB", or
all three of r, g, b as integers 0..255; anything else is a 400 and the
LED is not written.
OLD=1 cuts the files from git (OLDREV, default HEAD); before the fix the
handlers wrote the LED for every one of the bad requests.

  make -C test/host ledapi
"""
import pathlib
from cutter import Source

web = Source.at("components/board/web_common.c")
jx  = Source.at("components/board/json_exact.c")
cuts = web.func("bool web_json_uint(const cJSON *v, uint32_t lo, uint32_t hi, uint32_t *out)")
if "bool web_led_color_parse(" in web.text:
    cuts += web.func("bool web_led_color_parse(const cJSON *root, uint8_t *r, uint8_t *g, uint8_t *b)")
cuts += (jx.func("static bool escapes_nul(const char *d, size_t n)")
         + jx.func("cJSON *json_parse_exact(const char *data, size_t n)"))
for app in ("full", "matter"):
    # Both handlers in one program: each under the name of its firmware.
    cuts += (Source.at("apps/%s/main/web_server.c" % app)
             .func("static esp_err_t api_io_led(httpd_req_t *req)")
             .replace("api_io_led(", "%s_led(" % app, 1))

HARNESS = r"""
/* GENERATED by gen_ledapi_test.py -- do not edit; edit the web servers / web_common.c. */
#include <math.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cJSON.h"

typedef int esp_err_t;
#define ESP_OK 0
#define HTTPD_400_BAD_REQUEST 400
typedef struct { size_t content_len; const char *body; int status; } httpd_req_t;
static bool web_check_auth(httpd_req_t *r) { (void)r; return true; }
static esp_err_t web_send_denied(httpd_req_t *r) { r->status = 401; return ESP_OK; }
static int web_recv_body(httpd_req_t *r, char *b, size_t cap)
{
    if (r->content_len > cap) return -1;
    memcpy(b, r->body, r->content_len); b[r->content_len] = 0;
    return (int)r->content_len;
}
static esp_err_t httpd_resp_send_err(httpd_req_t *r, int status, const char *msg) { (void)msg; r->status = status; return ESP_OK; }
static esp_err_t httpd_resp_set_type(httpd_req_t *r, const char *t) { (void)r; (void)t; return ESP_OK; }
static esp_err_t httpd_resp_sendstr(httpd_req_t *r, const char *s) { (void)s; r->status = 200; return ESP_OK; }

/* The LED: how often written, and the last colour. */
static int writes; static uint32_t color;
static esp_err_t led_set_rgb(uint8_t r, uint8_t g, uint8_t b) { writes++; color = (uint32_t)r << 16 | (uint32_t)g << 8 | b; return ESP_OK; }

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    printf("POST /api/io/led in beiden Firmwares\n");
    static const struct { const char *body; bool ok; uint32_t color; } cases[] = {
        { "{\"color\":\"#fF8000\"}",       true,  0xFF8000 },
        { "{\"r\":16,\"g\":32,\"b\":48}",  true,  0x102030 },
        { "{\"color\":\"#ff0000xyz\"}",    false, 0 },
        { "{\"color\":\"#zzzzzz\"}",       false, 0 },
        { "{\"color\":42}",                false, 0 },
        { "{\"r\":256,\"g\":0,\"b\":0}",   false, 0 },
        { "{\"r\":0.5,\"g\":0,\"b\":0}",   false, 0 },
        { "{\"r\":255}",                   false, 0 },
        { "{}",                            false, 0 },
    };
    static const char *const names[] = { "full", "matter" };
    esp_err_t (*handlers[])(httpd_req_t *) = { full_led, matter_led };
    for (unsigned h = 0; h < 2; h++) {
        for (unsigned i = 0; i < sizeof cases / sizeof cases[0]; i++) {
            httpd_req_t req = { .content_len = strlen(cases[i].body), .body = cases[i].body };
            writes = 0; color = 0;
            handlers[h](&req);
            CHECK(req.status == (cases[i].ok ? 200 : 400) && writes == (cases[i].ok ? 1 : 0) && color == cases[i].color,
                  "%s, %s: Status %d, LED %d Mal geschrieben, Farbe #%06X", names[h], cases[i].body,
                  req.status, writes, (unsigned)color);
        }
    }
    if (!failures) printf("  nur #RRGGBB oder ganzzahlige r, g, b 0..255; alles andere 400, LED unberuehrt\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_ledapi.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
