#!/usr/bin/env python3
"""Builds a host test for the topics the device publishes and subscribes to
(apps/full/main/app_mqtt.c, components/scripting/bindings.c).

make_topic() and app_mqtt_publish/subscribe/unsubscribe() are cut out of
app_mqtt.c, js_mqtt_publish() out of bindings.c, all verbatim; the MQTT
client is a stub that records what it was asked to do. Real QuickJS.

What it pins down, found by a review: a rule could publish to "x/+" or "a/#"
-- a protocol violation a broker answers by closing the connection, and at
QoS 1 the message stayed in the outbox and did it again after every
reconnect. A topic longer than the buffer was cut and published or
subscribed on another topic. Now both are refused, and the rule is told
with a RangeError.
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host mqtttopic
"""
import pathlib
from cutter import Source

mq = Source.at("apps/full/main/app_mqtt.c")
bd = Source.at("components/scripting/bindings.c")
mk = "static bool make_topic(" if "static bool make_topic(" in mq.text else "static void make_topic("
cuts = (mq.defines("TOPIC_MAXLEN")
        + mq.func(mk + "const char *topic, char *buf, size_t buf_len)")
        + mq.func("int app_mqtt_publish(const char *topic, const char *payload, int len,")
        + mq.func("int app_mqtt_subscribe(const char *topic, int qos)")
        + mq.func("int app_mqtt_unsubscribe(const char *topic)")
        + bd.func("static JSValue js_mqtt_publish(JSContext *ctx, JSValue this_val, int argc, JSValue *argv)"))

HARNESS = r"""
/* GENERATED by gen_mqtttopic_test.py -- do not edit; edit app_mqtt.c / bindings.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "quickjs.h"

typedef struct { char mqtt_topic_prefix[64]; } app_config_t;
static app_config_t cfg = { "haus" };
static const app_config_t *app_config_get(void) { return &cfg; }
static int s_client_dummy; static void *s_client = &s_client_dummy;
static void (*s_on_publish_cb)(void);
static char last[512]; static int calls;
static int esp_mqtt_client_publish(void *c, const char *t, const char *p, int l, int q, int r)
{ (void)c; (void)p; (void)l; (void)q; (void)r; calls++; snprintf(last, sizeof last, "%s", t); return 1; }
static int esp_mqtt_client_subscribe(void *c, const char *t, int q) { (void)c; (void)q; calls++; snprintf(last, sizeof last, "%s", t); return 1; }
static int esp_mqtt_client_unsubscribe(void *c, const char *t) { (void)c; calls++; snprintf(last, sizeof last, "%s", t); return 1; }

typedef struct { int (*mqtt_publish)(const char *, const char *, int, int, bool); } scripting_io_t;
int app_mqtt_publish(const char *topic, const char *payload, int len, int qos, bool retain);
static const scripting_io_t s_io = { app_mqtt_publish };
static const scripting_io_t *scripting_io_of(JSContext *ctx) { (void)ctx; return &s_io; }

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    printf("MQTT-Topics\n");
    calls = 0;
    CHECK(app_mqtt_publish("status/do0", "1", 1, 0, false) >= 0 && !strcmp(last, "haus/status/do0"), "normales Topic: %s", last);
    CHECK(app_mqtt_subscribe("cmd/+", 0) >= 0 && !strcmp(last, "haus/cmd/+"), "Abo mit Wildcard abgelehnt");
    int c0 = calls;
    CHECK(app_mqtt_publish("x/+", "1", 1, 1, false) < 0, "PUBLISH auf x/+ angenommen");
    CHECK(app_mqtt_publish("a/#", "1", 1, 1, false) < 0, "PUBLISH auf a/# angenommen");
    CHECK(app_mqtt_publish("", "1", 1, 0, false) < 0, "PUBLISH ohne Topic angenommen");
    char longt[300]; memset(longt, 'x', 299); longt[299] = 0;
    CHECK(app_mqtt_publish(longt, "1", 1, 0, false) < 0, "zu langes Topic gekuerzt veroeffentlicht");
    CHECK(app_mqtt_subscribe(longt, 0) < 0, "zu langes Topic gekuerzt abonniert");
    CHECK(app_mqtt_unsubscribe(longt) < 0, "zu langes Topic gekuerzt abbestellt");
    CHECK(calls == c0, "%d unzulaessige Auftraege an den Client gegangen", calls - c0);
    if (!failures) printf("  Wildcard/leer/zu lang: nicht an den Broker; Abo mit Wildcard weiter erlaubt\n");

    int f0 = failures;
    JSRuntime *rt = JS_NewRuntime(); JSContext *ctx = JS_NewContext(rt);
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "_pub", JS_NewCFunction(ctx, js_mqtt_publish, "_pub", 4));
    JS_FreeValue(ctx, g);
    const char *src = "var r = []; for (var t of ['a/#', 'x/+', '']) { try { _pub(t, '1', 1); r.push('ok'); } "
                      "catch (e) { r.push(e instanceof RangeError ? 'RangeError' : String(e)); } } "
                      "r.push(_pub('ok/topic', '1') >= 0 ? 'ok' : 'fail'); r.join(',')";
    JSValue v = JS_Eval(ctx, src, strlen(src), "<t>", 0);
    const char *s = JS_ToCString(ctx, v);
    CHECK(s && !strcmp(s, "RangeError,RangeError,RangeError,ok"), "Regel: %s statt RangeError,RangeError,RangeError,ok", s ? s : "?");
    JS_FreeCString(ctx, s); JS_FreeValue(ctx, v); JS_FreeContext(ctx); JS_FreeRuntime(rt);
    if (failures == f0) printf("  Regel: Wildcard oder leeres Topic -> RangeError\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqtttopic.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
