#!/usr/bin/env python3
"""Builds a host test for a failed RTU slave start (mb_server.c).

start_rtu_slave() is cut out of mb_server.c verbatim, with what it brings
along; the Modbus controller and the UART driver are recorders, and any one
step can be made to fail.

What it pins down, found by a review: the controller installs the UART
driver when the slave is created, and every later step returned on failure
without deleting it -- the RS-485 port stayed claimed for the rest of the
boot, and s_handle pointed at a slave that never started. Now a failed start
deletes the slave again, as mb_gateway_start() does for the master.
OLD=1 cuts mb_server.c from git (OLDREV, default HEAD).

  make -C test/host rtuunwind
"""
import pathlib
from cutter import Source

src = Source.at("components/modbus/mb_server.c")
cuts = "static void *s_handle = NULL;\n"
if "static void rtu_slave_unwind(void)" in src.text:
    cuts += src.span("static void rtu_slave_unwind(void)", "    } while (0)\n")
cuts += src.func("static esp_err_t start_rtu_slave(const app_config_t *cfg)")

HARNESS = r"""
/* GENERATED by gen_rtuunwind_test.py -- do not edit; edit mb_server.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <inttypes.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGE(...) ((void)0)
static const char *esp_err_to_name(esp_err_t e) { (void)e; return "?"; }
#define ESP_RETURN_ON_ERROR(x, tag, ...) do { esp_err_t _r = (x); if (_r != ESP_OK) return _r; } while (0)

typedef struct { struct { uint8_t address; uint32_t baudrate; } modbus; } app_config_t;
enum { MB_RTU, MB_PARITY_NONE, UART_DATA_8_BITS, UART_STOP_BITS_1, UART_NUM_1 = 1,
       UART_PIN_NO_CHANGE = -1, UART_MODE_RS485_HALF_DUPLEX = 1, MB_FC_DEVICE_ID = 43,
       MB_PARAM_COIL, MB_PARAM_DISCRETE, MB_PARAM_HOLDING, MB_PARAM_INPUT,
       MB_ACCESS_RW, MB_ACCESS_RO };
#define MB_UART UART_NUM_1
#define MB_TX_GPIO 17
#define MB_RX_GPIO 18
#define MB_RTS_GPIO 21
typedef struct { struct { int mode, port; uint8_t uid; uint32_t baudrate; int parity, data_bits, stop_bits; } ser_opts; } mb_communication_info_t;
typedef struct { int type; uint16_t start_offset; void *address; size_t size; int access; } mb_register_area_descriptor_t;
static uint8_t s_coils_unused, s_di_unused, s_hr_unused, s_ir_unused;
static int rtu_device_id_handler;

/* Step n (1-based, in call order) fails when fail_at == n. */
static int step, fail_at, slaves_alive;
static int slave_obj;
static esp_err_t next(void) { return ++step == fail_at ? ESP_FAIL : ESP_OK; }
static esp_err_t mbc_slave_create_serial(const mb_communication_info_t *c, void **h)
{ (void)c; esp_err_t r = next(); if (r == ESP_OK) { *h = &slave_obj; slaves_alive++; } return r; }
static esp_err_t uart_set_pin(int u, int tx, int rx, int rts, int cts) { (void)u; (void)tx; (void)rx; (void)rts; (void)cts; return next(); }
static esp_err_t uart_set_mode(int u, int m) { (void)u; (void)m; return next(); }
static esp_err_t mbc_slave_set_descriptor(void *h, mb_register_area_descriptor_t a) { (void)h; (void)a; return next(); }
static esp_err_t mbc_set_handler(void *h, int fc, void *fn) { (void)h; (void)fc; (void)fn; return next(); }
static esp_err_t mbc_slave_start(void *h) { (void)h; return next(); }
static esp_err_t mbc_slave_delete(void *h) { (void)h; slaves_alive--; return ESP_OK; }
#define rtu_device_id_handler ((void *)&rtu_device_id_handler)

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("RTU-Slave: gescheiterter Start\n");
    app_config_t cfg = { .modbus = { .address = 1, .baudrate = 9600 } };

    /* Steps: create, set_pin, set_mode, 4 descriptors, handler, start. */
    for (fail_at = 2; fail_at <= 9; fail_at++) {
        step = 0; slaves_alive = 0; s_handle = NULL;
        esp_err_t r = start_rtu_slave(&cfg);
        CHECK(r != ESP_OK, "Schritt %d scheitert, Start meldet trotzdem ok", fail_at);
        CHECK(slaves_alive == 0, "Schritt %d scheitert: Slave (und UART) bleibt belegt", fail_at);
        CHECK(s_handle == NULL, "Schritt %d scheitert: s_handle zeigt auf den toten Slave", fail_at);
    }
    fail_at = 0; step = 0; slaves_alive = 0; s_handle = NULL;
    CHECK(start_rtu_slave(&cfg) == ESP_OK && slaves_alive == 1 && s_handle, "ordentlicher Start");
    if (!failures) printf("  jeder gescheiterte Schritt gibt Slave und UART wieder frei\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_rtuunwind.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
