#!/usr/bin/env python3
"""Builds a host test for when a configuration save restarts SNTP (sntp_sync.c).

apply_locked() is cut out of sntp_sync.c verbatim; esp_netif_sntp is
recorded instead of run.

What it pins down, found by a review: every configuration save calls
sntp_sync_apply(), and it tore SNTP down and started it again each time --
renaming an input dropped a sync under way and sent a new request. Now only
a change of server or of enable restarts it; a start that failed is tried
again on the next call.
OLD=1 cuts sntp_sync.c from git (OLDREV, default HEAD).

  make -C test/host sntpapply
"""
import pathlib
from cutter import Source

src = Source.at("components/board/sntp_sync.c")
cuts = ("static bool s_started = false;\n"
        + (src.span("/* The server SNTP runs with", "static char s_server[APP_CFG_SNTP_SERVER_LEN];")
           if "s_server[" in src.text else "")
        + src.func("static void apply_locked(void)"))

HARNESS = r"""
/* GENERATED by gen_sntpapply_test.py -- do not edit; edit sntp_sync.c. */
#include <stdbool.h>
#include <stdio.h>
#include <string.h>
#include <sys/time.h>

#define APP_CFG_SNTP_SERVER_LEN 64
typedef struct { struct { bool enable; char server[APP_CFG_SNTP_SERVER_LEN]; } sntp; } app_config_t;
static app_config_t cfg;
static const app_config_t *app_config_get(void) { return &cfg; }

typedef int esp_err_t;
#define ESP_OK 0
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGE(...) ((void)0)
static const char *esp_err_to_name(esp_err_t e) { (void)e; return "?"; }
typedef struct { const char *server; bool start; void (*sync_cb)(struct timeval *); } esp_sntp_config_t;
#define ESP_NETIF_SNTP_DEFAULT_CONFIG(s) { .server = (s) }
static int inits, deinits, init_fails;
static char running[64];
static esp_err_t esp_netif_sntp_init(const esp_sntp_config_t *c)
{ inits++; if (init_fails) { init_fails--; return -1; } snprintf(running, sizeof running, "%s", c->server); return ESP_OK; }
static void esp_netif_sntp_deinit(void) { deinits++; running[0] = 0; }
static void on_time_synced(struct timeval *tv) { (void)tv; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("SNTP bei Konfigurationsaenderungen\n");

    cfg.sntp.enable = true;
    apply_locked();                                   /* network up */
    CHECK(inits == 1 && !strcmp(running, "pool.ntp.org"), "Start: %d init, Server %s", inits, running);

    apply_locked(); apply_locked();                   /* saves that touch nothing of SNTP */
    CHECK(inits == 1 && deinits == 0, "Speichern ohne SNTP-Aenderung: %d Neustart(s)", deinits);

    snprintf(cfg.sntp.server, sizeof cfg.sntp.server, "ntp.example.org");
    apply_locked();
    CHECK(deinits == 1 && inits == 2 && !strcmp(running, "ntp.example.org"), "Serverwechsel nicht uebernommen (%s)", running);

    cfg.sntp.enable = false;
    apply_locked(); apply_locked();
    CHECK(deinits == 2 && inits == 2 && !running[0], "Abschalten: %d deinit, %d init", deinits, inits);

    cfg.sntp.enable = true; init_fails = 1;
    apply_locked();                                   /* start fails */
    apply_locked();                                   /* tried again */
    CHECK(inits == 4 && !strcmp(running, "ntp.example.org"), "fehlgeschlagener Start nicht wiederholt (%d init)", inits);
    if (!failures) printf("  Neustart nur bei Server- oder Ein/Aus-Aenderung; Fehlstart wird wiederholt\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_sntpapply.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
