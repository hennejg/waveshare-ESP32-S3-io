#!/usr/bin/env python3
"""Builds a host test for the WiFi bootstrap's link monitor (wifi_config.c).

The monitor callback, the legacy event hook and the portal's URL routing are
cut out of wifi_config.c verbatim and compiled with the definitions the
component's CMakeLists.txt gives them -- the bug was in the build file, not in
the C: WIFI_CONFIG_NO_RESTART was only set by the old component.mk, so in the
CMake build every lost WiFi link ended in esp_restart(), Ethernet up or not.

What it pins down:
  - a lost link with credentials stored is retried, not rebooted, and does
    not open the setup AP (jamming the network must not produce an open AP
    that accepts new credentials);
  - without credentials the setup AP still comes up;
  - the switch to Ethernet-only is reachable by POST only;
  - an AP that is up when wifi_config_disable_ap() is called (Matter, once
    commissioned) is taken down by the monitor, not left open.

OLD=1 cuts wifi_config.c and CMakeLists.txt from git (OLDREV, default HEAD).

  make -C test/host wifimon
"""
import pathlib, re
from cutter import Source, show

ROOT = pathlib.Path(__file__).resolve().parents[2]
COMP = "components/esp32-wifi-bootstrap"
src  = Source.at(COMP + "/src/wifi_config.c")
cmk  = show(COMP + "/CMakeLists.txt")

defs = ""
for m in re.finditer(r"target_compile_definitions\([^)]*?PRIVATE\s+([^)]*)\)", cmk):
    for d in m.group(1).split():
        defs += "#define %s\n" % d.replace("=", " ", 1)

hdr  = src.defines("STATION_GOT_IP", "WIFI_CONFIG_CONNECTED_MONITOR_INTERVAL",
                   "WIFI_CONFIG_DISCONNECTED_MONITOR_INTERVAL", "INFO")
cuts = (src.type("} wifi_config_context_t;")
        + src.type("} endpoint_t;")
        + src.type("} client_t;")
        + "static wifi_config_context_t *context = NULL;\n"
        + (src.span("/* Set when the monitor has seen", "static bool s_link_lost;") if "s_link_lost" in src.text else "")
        + src.func("static void wifi_config_monitor_callback(TimerHandle_t xTimer) {")
        + src.func("void wifi_config_legacy_support_on_event(wifi_config_event_t event) {")
        + src.func("static int wifi_config_server_on_url(http_parser *parser, const char *data, size_t length) {"))

HARNESS = r"""
/* GENERATED by gen_wifimon_test.py -- do not edit; edit wifi_config.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stddef.h>
#include <stdlib.h>
#include <string.h>

__DEFS__
__HDR__
#define DEBUG(...)
static const char *http_method_str(int m) { return m == 1 ? "GET" : "POST"; }
typedef void *TimerHandle_t;
typedef void *TaskHandle_t;
#define pdMS_TO_TICKS(x) (x)
typedef enum { WIFI_CONFIG_CONNECTED = 1, WIFI_CONFIG_DISCONNECTED = 2 } wifi_config_event_t;
enum { HTTP_GET = 1, HTTP_POST = 3 };
typedef struct { int method; void *data; } http_parser;
#define STATION_MODE 1

/* The world the monitor sees. */
static int  link_up, opmode = STATION_MODE, configured, s_ap_disabled;
static int  restarts, ap_starts, connects, ready_calls;
static int  sdk_wifi_station_get_connect_status(void) { return link_up ? STATION_GOT_IP : 0; }
static int  sdk_wifi_get_opmode(void) { return opmode; }
static void sdk_wifi_station_set_auto_connect(bool on) { (void)on; }
static void wifi_config_softap_stop(void) { opmode = STATION_MODE; }
static void wifi_config_softap_start(void) { ap_starts++; opmode = 3; }
static int  wifi_config_has_configuration(void) { return configured; }
static int  wifi_config_station_connect(void) { connects++; return configured ? 0 : -1; }
static void xTimerChangePeriod(TimerHandle_t t, int p, int w) { (void)t; (void)p; (void)w; }
static void esp_restart(void) { restarts++; }

__CUT__

static void on_ready(void) { ready_calls++; }

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static endpoint_t route(int method, const char *url)
{
    http_parser p = { .method = method };
    client_t c; memset(&c, 0, sizeof c);
    p.data = &c;
    wifi_config_server_on_url(&p, url, strlen(url));
    return c.endpoint;
}

int main(void)
{
    static wifi_config_context_t ctx;
    context = &ctx;
    ctx.on_wifi_ready = on_ready;
    ctx.on_event = wifi_config_legacy_support_on_event;

    printf("WLAN-Monitor\n");
    /* 1. Credentials stored, the link comes up once, then drops. */
    configured = 1; ctx.first_time = 1;
    link_up = 1; wifi_config_monitor_callback(NULL);
    CHECK(ready_calls == 1, "on_wifi_ready nicht gerufen");
    link_up = 0; connects = 0;
    for (int i = 0; i < 5; i++) wifi_config_monitor_callback(NULL);
    CHECK(restarts == 0, "WLAN-Verlust: %d Neustart(s)", restarts);
    CHECK(connects == 5, "WLAN-Verlust: %d statt 5 Wiederverbindungsversuche", connects);
    CHECK(ap_starts == 0, "WLAN-Verlust mit Zugangsdaten: offener Setup-AP %d-mal gestartet", ap_starts);
    printf("  Verbindungsverlust: kein Neustart, kein offener AP, Station versucht es weiter\n");

    /* 2. The link comes back: services are told again, nothing else. */
    link_up = 1; wifi_config_monitor_callback(NULL);
    CHECK(ready_calls == 2, "Wiederverbindung meldet on_wifi_ready nicht");
    printf("  Wiederverbindung: on_wifi_ready erneut\n");

    /* 3. Booting with credentials into a network that is not there. */
    restarts = ap_starts = 0; ctx.first_time = 1; link_up = 0; opmode = STATION_MODE;
    for (int i = 0; i < 3; i++) wifi_config_monitor_callback(NULL);
    CHECK(ap_starts == 0, "Start ohne erreichbares Netz: offener AP %d-mal", ap_starts);
    CHECK(restarts == 0, "Start ohne erreichbares Netz: %d Neustart(s)", restarts);
    printf("  Start mit Zugangsdaten, Netz weg: kein offener AP\n");

    /* 4. No credentials (first setup, or after the BOOT long press): AP. */
    configured = 0; ctx.first_time = 1; opmode = STATION_MODE;
    wifi_config_monitor_callback(NULL);
    CHECK(ap_starts >= 1, "ohne Zugangsdaten kein Setup-AP");
    printf("  ohne Zugangsdaten: Setup-AP startet\n");

    /* 5. Ethernet-only only by POST. */
    CHECK(route(HTTP_GET,  "/eth-only") != ENDPOINT_ETH_ONLY, "GET /eth-only schaltet WLAN ab");
    CHECK(route(HTTP_POST, "/eth-only") == ENDPOINT_ETH_ONLY, "POST /eth-only nicht erkannt");
    CHECK(route(HTTP_POST, "/settings") == ENDPOINT_SETTINGS_UPDATE, "POST /settings nicht erkannt");
    CHECK(route(HTTP_GET,  "/settings") == ENDPOINT_SETTINGS, "GET /settings nicht erkannt");
    printf("  /eth-only nur per POST\n");

    /* 6. AP up (not commissioned yet), then disabled: the monitor stops it. */
    configured = 0; link_up = 0; opmode = 3; s_ap_disabled = 0; ap_starts = 0;
    s_ap_disabled = 1;
    wifi_config_monitor_callback(NULL);
    wifi_config_monitor_callback(NULL);
    CHECK(opmode == STATION_MODE && ap_starts == 0, "AP nach wifi_config_disable_ap() weiter offen (opmode %d, %d Starts)", opmode, ap_starts);
    printf("  spaet abgeschalteter AP: vom Monitor beendet\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_wifimon.c")
out.write_text(HARNESS.replace("__DEFS__", defs).replace("__HDR__", hdr).replace("__CUT__", cuts))
print("erzeugt:", out.name)
