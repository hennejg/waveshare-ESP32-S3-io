#!/usr/bin/env python3
"""Builds a host test for the WiFi setup portal's pages (wifi_config.c).

The settings page, the settings POST and the NVS helpers under them are cut
out of wifi_config.c verbatim, the form parser is form_urlencoded.c as it is,
and the page templates are content/index.html.h. Sockets, NVS and the reboot
are recorded instead of done.

What it pins down, found by a review:
  - a scanned SSID went into the page as markup: a neighbour's access point
    named <svg/onload=...> ran script on the page the WiFi password is typed
    into. SSIDs are HTML text now, the longest one whole;
  - POST /settings with Content-Length: 0 handed a NULL body to the form
    parser, which dereferenced it;
  - a failed NVS write still answered "Credentials saved" and rebooted, into
    the old or half-written credentials;
  - an SSID of 32 bytes was cut to 31 when connecting, and an empty or
    over-long SSID was stored and confirmed -- the board never connected,
    with the AP off for good;
  - the read loop printed every request it received, the WiFi password in
    the form included, with printf -- past any ESP log level.
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host wifiportal
"""
import pathlib, re
from cutter import Source

COMP = "components/esp32-wifi-bootstrap"
src  = Source.at(COMP + "/src/wifi_config.c")
form = Source.at(COMP + "/src/form_urlencoded.c")
# url_unescape() is written with nested functions, a GCC extension the host
# compiler lacks; it is not what this test is about, so it is swapped for a
# plain decoder. form_params_parse() and the rest are the file's own.
unesc = form.func("char *url_unescape(const char *buffer, size_t size) {")
form_text = form.text.replace(unesc, r'''char *url_unescape(const char *b, size_t n) {
        char *r = malloc(n + 1); size_t j = 0;
        for (size_t i = 0; i < n; i++) {
                unsigned v;
                if (b[i] == '%' && i + 2 < n && sscanf(b + i + 1, "%2x", &v) == 1) { r[j++] = (char)v; i += 2; }
                else r[j++] = b[i] == '+' ? ' ' : b[i];
        }
        r[j] = 0; return r;
}
''')
new  = "static void html_escape(" in src.text

# Log lines whose arguments carry request data: the format string is left
# out, only what is printed into it counts.
leaks = []
for m in re.finditer(r"\b(INFO|DEBUG|ERROR)\((\"(?:[^\"\\]|\\.)*\")(.*?)\);", src.text):
    if re.search(r"\b(data|body|password|password_param)\b|->body|->value", m.group(3)):
        leaks.append(m.group(0))

cuts = (src.defines("INFO", "ERROR")
        + src.type("} endpoint_t;")
        + src.type("} wifi_config_context_t;")
        + "static wifi_config_context_t *context = NULL;\n"
        + src.type("} client_t;")
        + src.func("static void client_send(client_t *client, const char *payload, size_t payload_size) {")
        + src.func("static void client_send_chunk(client_t *client, const char *payload) {")
        + src.func("static void client_send_redirect(client_t *client, int code, const char *redirect_url) {")
        + src.type("} wifi_network_info_t;")
        + "wifi_network_info_t *wifi_networks = NULL;\nSemaphoreHandle_t wifi_networks_mutex;\n"
        + src.func("static void sysparam_init(void) {" if not new else "static esp_err_t sysparam_init(void) {")
        + src.func("static void sysparam_set_string(const char *key, const char *value) {" if not new
                   else "static esp_err_t sysparam_set_string(const char *key, const char *value) {")
        + (src.span("static void html_escape(", "#define SSID_HTML_MAX (32 * 6 + 1)") if new else "")
        + src.func("static void wifi_config_server_on_settings(client_t *client) {")
        + (src.func("static esp_err_t store_credentials(const char *ssid, const char *password) {") if new else "")
        + src.func("static void wifi_config_server_on_settings_update(client_t *client) {")
        + src.func("static void sysparam_get_string(const char *key, char **value) {")
        + src.func("static int wifi_config_station_connect() {")
        + (src.func("bool wifi_config_reset_requested(void) {") + src.func("esp_err_t wifi_config_reset() {")
           if "wifi_config_reset_requested" in src.text else ""))
reset_test = "wifi_config_reset_requested" in src.text

HARNESS = r"""
/* GENERATED by gen_wifiportal_test.py -- do not edit; edit wifi_config.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>
#include <unistd.h>

__FORM__

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
static const char *esp_err_to_name(esp_err_t e) { return e ? "ESP_FAIL" : "ESP_OK"; }
#define DEBUG(...)
typedef void *TimerHandle_t;
typedef void *TaskHandle_t;
typedef void *SemaphoreHandle_t;
#define portTICK_PERIOD_MS 1
#define pdMS_TO_TICKS(x) (x)
static int xSemaphoreTake(SemaphoreHandle_t s, int t) { (void)s; (void)t; return 1; }
static void xSemaphoreGive(SemaphoreHandle_t s) { (void)s; }
static void vTaskDelay(int t) { (void)t; }
typedef enum { WIFI_CONFIG_CONNECTED = 1 } wifi_config_event_t;
typedef struct { int method; void *data; } http_parser;
static bool (*s_eth_available_fn)(void) = NULL;

/* What went out on the socket. */
static char sent[16384]; static size_t sent_len;
static void capture(const void *b, size_t n)
{ if (sent_len + n < sizeof sent) { memcpy(sent + sent_len, b, n); sent_len += n; sent[sent_len] = 0; } }
static int lwip_write(int fd, const void *b, size_t n) { (void)fd; capture(b, n); return (int)n; }
#define write(fd, b, n) lwip_write(fd, b, n)
static int restarts;
static void esp_restart(void) { restarts++; }

/* NVS: two strings; nvs_fail_at = n makes the n-th set fail. */
typedef int nvs_handle_t;
enum { NVS_READWRITE = 1 };
static nvs_handle_t wifi_cfg_handle;
static char nv_ssid[128] = "AltesNetz", nv_pw[128] = "AltesPasswort";
static int nvs_sets, nvs_fail_at;
static esp_err_t nvs_flash_init(void) { return ESP_OK; }
static esp_err_t nvs_open(const char *ns, int m, nvs_handle_t *h) { (void)ns; (void)m; *h = 1; return ESP_OK; }
static esp_err_t nvs_set_str(nvs_handle_t h, const char *k, const char *v)
{
    (void)h;
    if (++nvs_sets == nvs_fail_at) return ESP_FAIL;
    snprintf(strcmp(k, "wifi_ssid") ? nv_pw : nv_ssid, 128, "%s", v);
    return ESP_OK;
}
static esp_err_t nvs_commit(nvs_handle_t h) { (void)h; return ESP_OK; }
static int nv_ssid_missing;
static esp_err_t nvs_get_str(nvs_handle_t h, const char *k, char *v, size_t *n)
{
    (void)h; const char *s = strcmp(k, "wifi_ssid") ? nv_pw : nv_ssid;
    if (s == nv_ssid && nv_ssid_missing) return 0x1102;
    if (v) memcpy(v, s, strlen(s) + 1);
    *n = strlen(s) + 1; return ESP_OK;
}

/* The station config the driver is given. */
typedef union { struct { uint8_t ssid[32]; uint8_t password[64]; } sta; } wifi_config_t;
static wifi_config_t station;
static void sdk_wifi_station_set_config(wifi_config_t *c) { station = *c; }
static void sdk_wifi_station_connect(void) {}
static void sdk_wifi_station_set_auto_connect(bool on) { (void)on; }

#include "index.html.h"

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static void reset(void) { sent_len = 0; sent[0] = 0; restarts = 0; nvs_sets = 0; nvs_fail_at = 0; }

static void post(const char *body)
{
    client_t c; memset(&c, 0, sizeof c);
    c.body = body ? (uint8_t *)strdup(body) : NULL;
    reset();
    wifi_config_server_on_settings_update(&c);
    free(c.body);
}

int main(void)
{
    static wifi_config_context_t ctx;
    context = &ctx;
    printf("WLAN-Setup-Portal\n");

    /* 1. Scanned SSIDs on the settings page. */
    static wifi_network_info_t a = { .ssid = "<svg/onload=alert(1)>", .secure = true }, b;
    memset(b.ssid, '"', 32); b.ssid[32] = 0;
    a.next = &b; wifi_networks = &a;
    reset();
    client_t page; memset(&page, 0, sizeof page);
    wifi_config_server_on_settings(&page);
    CHECK(!strstr(sent, "<svg"), "SSID als HTML-Markup in der Seite");
    CHECK(strstr(sent, "&lt;svg/onload=alert(1)&gt;") != NULL, "SSID mit < > nicht als Text in der Seite");
    char q[32 * 6 + 1] = ""; for (int i = 0; i < 32; i++) strcat(q, "&quot;");
    CHECK(strstr(sent, q) != NULL, "SSID aus 32 Anfuehrungszeichen nicht vollstaendig escaped");
    if (!failures) printf("  gescannte SSIDs: als HTML-Text, auch 32 Sonderzeichen ganz\n");

    /* 2. Storing fails half-way: no "saved", no reboot, old network not
          paired with the new password. */
    int f0 = failures;
    for (int at = 1; at <= 3; at++) {
        snprintf(nv_ssid, sizeof nv_ssid, "AltesNetz"); snprintf(nv_pw, sizeof nv_pw, "AltesPasswort");
        client_t c; memset(&c, 0, sizeof c);
        c.body = (uint8_t *)strdup("ssid=NeuesNetz&password=NeuesPasswort");
        reset(); nvs_fail_at = at;
        wifi_config_server_on_settings_update(&c);
        free(c.body);
        CHECK(restarts == 0, "Schreibfehler beim %d. Wert: trotzdem Neustart", at);
        CHECK(!strstr(sent, "Credentials saved"), "Schreibfehler beim %d. Wert: \"Credentials saved\" gemeldet", at);
        CHECK(strncmp(sent, "HTTP/1.1 5", 10) == 0, "Schreibfehler beim %d. Wert: kein 5xx (%.20s)", at, sent);
        CHECK(!(strcmp(nv_ssid, "AltesNetz") == 0 && strcmp(nv_pw, "NeuesPasswort") == 0),
              "Schreibfehler beim %d. Wert: altes Netz mit neuem Passwort gespeichert", at);
    }
    if (failures == f0) printf("  Schreibfehler: 5xx, kein Neustart, keine halbe Kombination\n");

    /* 3. Stored: confirmation with the SSID as text, then the reboot. */
    f0 = failures;
    post("ssid=%3Cb%3EX&password=pw1");
    CHECK(restarts == 1, "Speichern: kein Neustart");
    CHECK(strcmp(nv_ssid, "<b>X") == 0 && strcmp(nv_pw, "pw1") == 0, "Speichern: NVS hat %s/%s", nv_ssid, nv_pw);
    CHECK(strstr(sent, "&lt;b&gt;X") && !strstr(sent, "<b>X"), "Bestaetigung: SSID als Markup");
    if (failures == f0) printf("  Speichern: Werte im NVS, SSID in der Bestaetigung als Text, Neustart\n");

    /* 3b. SSID lengths. */
    f0 = failures;
    snprintf(nv_ssid, sizeof nv_ssid, "AltesNetz");
    post("ssid=&password=pw1");
    CHECK(restarts == 0 && strcmp(nv_ssid, "AltesNetz") == 0, "leere SSID gespeichert");
    post("ssid=123456789012345678901234567890123&password=pw1");
    CHECK(restarts == 0 && strcmp(nv_ssid, "AltesNetz") == 0, "SSID mit 33 Bytes gespeichert");
    post("ssid=12345678901234567890123456789012&password=pw1");
    CHECK(restarts == 1, "SSID mit 32 Bytes abgelehnt");
    wifi_config_station_connect();
    CHECK(memcmp(station.sta.ssid, "12345678901234567890123456789012", 32) == 0,
          "SSID mit 32 Bytes beim Verbinden gekuerzt (%.32s)", (char *)station.sta.ssid);
    if (failures == f0) printf("  SSID: leer/33 Bytes abgelehnt, 32 Bytes gespeichert und ganz verwendet\n");

#if RESET_TEST
    /* 3c. When a set-up device may open the AP again. */
    f0 = failures;
    nv_ssid_missing = 1;
    CHECK(!wifi_config_reset_requested(), "nie gesetzte SSID gilt als Zuruecksetzen");
    nv_ssid_missing = 0; snprintf(nv_ssid, sizeof nv_ssid, "Netz");
    CHECK(!wifi_config_reset_requested(), "gespeicherte SSID gilt als Zuruecksetzen");
    wifi_config_reset();
    CHECK(wifi_config_reset_requested(), "nach wifi_config_reset() kein Zuruecksetzen erkannt");
    if (failures == f0) printf("  AP-Freigabe: nur nach BOOT-Zuruecksetzen, nicht bei nie gesetzter SSID\n");
#endif

    /* 4. Nothing printed from the request. */
    CHECK(LOG_LEAKS == 0, "%d Log-Zeile(n) geben Request-Daten aus:\n__LEAKS__", LOG_LEAKS);
    if (!LOG_LEAKS) printf("  Logs: keine Request-Daten, kein Passwort\n");

    /* 5. An empty POST, in a child: the old code crashed in the parser. */
    fflush(stdout);
    pid_t pid = fork();
    if (pid == 0) {
        post(NULL);
        _exit(restarts == 0 && strstr(sent, "HTTP/1.1 302") ? 0 : 2);
    }
    int st = 0; waitpid(pid, &st, 0);
    CHECK(WIFEXITED(st) && WEXITSTATUS(st) == 0, "POST ohne Body: %s",
          WIFEXITED(st) ? "falsche Antwort oder Neustart" : "Absturz");
    if (WIFEXITED(st) && WEXITSTATUS(st) == 0) printf("  POST ohne Body: Weiterleitung auf /settings\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
leak_txt = "".join("    %s\\n" % l.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") for l in leaks)
