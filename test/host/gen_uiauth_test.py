#!/usr/bin/env python3
"""Builds a node test for the Basic auth header the web UIs send.

The header expression of authHeaders() and, where present, basicAuth() are
taken from www/index.html and apps/matter/www/index.html as they are.

What it pins down, found by a review: the header was btoa(':' + pw), and
btoa() takes Latin-1 -- a password with "ä" went out as the byte 0xE4 where
the device, which stores the UTF-8 bytes, expects C3 A4, and one with "€"
made btoa() throw. Either way the UI could not log in with a password it
had just set.
OLD=1 takes both files from git (OLDREV, default HEAD).

  make -C test/host uiauth
"""
import json, pathlib, re
from cutter import show

files = ["www/index.html", "apps/matter/www/index.html"]
cases = []
for f in files:
    html = show(f)
    m = re.search(r"function basicAuth\(pw\) \{.*?\n    \}\n", html, re.S)
    helper = m.group(0) if m else ""
    expr = re.search(r"'Authorization': (.*?) \};", html[html.index("function authHeaders"):]).group(1)
    cases.append({"file": f, "src": helper + "\nreturn (authPassword) => " + expr + ";"})

JS = r"""
// GENERATED by gen_uiauth_test.py -- do not edit; edit the index.html files.
const cases = __CASES__;
let failures = 0;
console.log("Basic-Auth der Weboberflaechen");
for (const c of cases) {
  const header = new Function(c.src)();
  for (const pw of ["ascii-pass", "Größe-ä", "1000€", "🔒x"]) {
    let got;
    try { got = header(pw); } catch (e) { got = "Ausnahme: " + e.message; }
    const want = "Basic " + Buffer.from(":" + pw, "utf8").toString("base64");
    if (got !== want) { failures++; console.log(`  FEHLER: ${c.file}: ${JSON.stringify(pw)} -> ${got}`); }
  }
}
if (!failures) console.log("  Passwoerter mit Umlaut, Euro und Emoji: als UTF-8 gesendet (beide UIs)");
console.log(failures ? "FEHLER" : "alles in Ordnung");
process.exit(failures ? 1 : 0);
"""
out = pathlib.Path(__file__).with_name("test_uiauth.js")
out.write_text(JS.replace("__CASES__", json.dumps(cases)))
print("erzeugt:", out.name)
