#!/usr/bin/env python3
"""Builds a host test for MQTT command payloads parsed in place (led.c,
buzzer.c).

led_on_mqtt_message() and buzzer_on_mqtt_message() are cut out verbatim
with their step parsers, types and limits; ESP-IDF's cJSON parses, the
queue and the LED driver are stubs. Built with ASan: every payload sits at
the very end of a buffer of exactly its length, with no NUL after it, the
way an MQTT event hands it over.

What it pins down, found by a review: both handlers copied the payload
into a 1 KiB stack buffer on the MQTT task only to NUL-terminate it. They
now pass the length to cJSON_ParseWithLength(). The test makes sure that
nothing reads past the payload -- neither the JSON parse nor the "#RRGGBB"
shortcut -- and that the size limits still hold. It guards a refactor, so
OLD=1 (OLDREV, default HEAD) passes as well: the old copy was correct,
only wasteful.

  make -C test/host payload
"""
import pathlib
from cutter import Source

led = Source.at("components/board/led.c")
buz = Source.at("components/board/buzzer.c")


def limit(src, name, old):
    """The new limit, or the old stack buffer size under OLD=1."""
    try:
        return src.defines(name)
    except SystemExit:
        return "#define %s %d\n" % (name, old)


led_cut = (limit(led, "LED_PAYLOAD_MAX", 1024) + led.defines("SEQ_MAX", "DUR_MAX_MS")
           + led.type("} led_step_t;") + led.type("} led_seq_t;")
           + led.func("static uint8_t hex_digit(char c)")
           + led.func("static bool parse_hex(const char *s, uint8_t *r, uint8_t *g, uint8_t *b)")
           + led.func("static bool parse_step(cJSON *obj, led_step_t *s)")
           + led.func("void led_on_mqtt_message("))
buz_cut = (limit(buz, "BUZZER_PAYLOAD_MAX", 1024)
           + buz.defines("SEQ_MAX", "FREQ_MIN", "FREQ_MAX", "DUR_MIN_MS", "DUR_MAX_MS")
           + buz.type("} bstep_t;") + buz.type("} bseq_t;")
           + buz.func("static bool parse_bstep(cJSON *obj, bstep_t *s)")
           + buz.func("void buzzer_on_mqtt_message("))

HARNESS = r"""
/* GENERATED by gen_payload_test.py -- do not edit; edit led.c / buzzer.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cJSON.h"

#define CONFIG_APP_MQTT_ENABLE 1
#define ESP_LOGW(tag, ...) snprintf(NULL, 0, __VA_ARGS__)
typedef int QueueHandle_t;

static int  queued, queued_count, applied;
static uint8_t ar, ag, ab;
static void hw_apply(uint8_t r, uint8_t g, uint8_t b) { applied++; ar = r; ag = g; ab = b; }
static bool app_mqtt_is_connected(void) { return false; }
static void publish_color(void) {}

#define xQueueOverwrite(q, seq) ((void)(q), queued++, queued_count = (seq)->count)

/* led.c */
static bool          s_status_mode;
static QueueHandle_t s_queue;
__LED__
#undef SEQ_MAX
#undef DUR_MAX_MS
#define s_queue s_bqueue
static QueueHandle_t s_bqueue;
__BUZ__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

/* The payload at the very end of an exact-size heap block: one byte past
   it is an ASan error. */
static void send(void (*h)(const char *, size_t, const char *, size_t),
                 const char *topic, const char *text, size_t dlen)
{
    char *p = malloc(dlen ? dlen : 1);
    memcpy(p, text, dlen);
    queued = 0; queued_count = 0; applied = 0;
    h(topic, strlen(topic), p, dlen);
    free(p);
}
#define SEND(h, t, s) send(h, t, s, strlen(s))

int main(void)
{
    printf("MQTT-Befehle ohne Kopie geparst\n");
    (void)s_status_mode; (void)s_queue; (void)s_bqueue;

    SEND(led_on_mqtt_message, "led/set", "#102030");
    CHECK(applied == 1 && ar == 0x10 && ag == 0x20 && ab == 0x30, "LED #102030 ohne NUL");
    SEND(led_on_mqtt_message, "led/set", "#1020");
    CHECK(applied == 0, "LED #1020 (zu kurz) angenommen");
    SEND(led_on_mqtt_message, "led/set", "{\"color\":\"#102030\",\"duration\":500}");
    CHECK(queued == 1 && queued_count == 1, "LED-JSON ohne NUL: %d/%d", queued, queued_count);
    SEND(led_on_mqtt_message, "led/set", "[{\"color\":\"#102030\",\"duration\":5},{\"color\":\"#000000\",\"duration\":5}]");
    CHECK(queued == 1 && queued_count == 2, "LED-Folge: %d/%d", queued, queued_count);
    /* Only dlen counts: the bytes after it are another payload's. */
    send(led_on_mqtt_message, "led/set", "{\"color\":\"#102030\",\"duration\":5}]}", 32);
    CHECK(queued == 1 && queued_count == 1, "LED-JSON mit Folgebytes: %d/%d", queued, queued_count);
    SEND(led_on_mqtt_message, "led/set", "{\"color\":\"#1020");
    CHECK(queued == 0, "abgeschnittenes LED-JSON angenommen");

    SEND(buzzer_on_mqtt_message, "buzzer/beep", "{\"freq\":440,\"duration\":200}");
    CHECK(queued == 1 && queued_count == 1, "Summer-JSON ohne NUL: %d/%d", queued, queued_count);
    send(buzzer_on_mqtt_message, "buzzer/beep", "{\"freq\":440,\"duration\":200}garbage", 27);
    CHECK(queued == 1 && queued_count == 1, "Summer-JSON mit Folgebytes: %d/%d", queued, queued_count);
    SEND(buzzer_on_mqtt_message, "buzzer/beep", "{\"freq\":440,");
    CHECK(queued == 0, "abgeschnittenes Summer-JSON angenommen");

    /* The limits: a payload of the limit's size is ignored, one byte less parses. */
    size_t big = LED_PAYLOAD_MAX;
    char *pad = malloc(big + 1);
    memset(pad, ' ', big);
    const char *step = "{\"color\":\"#102030\",\"duration\":5}";
    memcpy(pad, step, strlen(step));
    pad[big] = '\0';
    send(led_on_mqtt_message, "led/set", pad, big);
    CHECK(queued == 0, "LED: %zu Byte angenommen", big);
    send(led_on_mqtt_message, "led/set", pad, big - 1);
    CHECK(queued == 1, "LED: %zu Byte abgelehnt", big - 1);
    memset(pad, ' ', big);
    step = "{\"freq\":440,\"duration\":200}";
    memcpy(pad, step, strlen(step));
    send(buzzer_on_mqtt_message, "buzzer/beep", pad, BUZZER_PAYLOAD_MAX);
    CHECK(queued == 0, "Summer: %d Byte angenommen", BUZZER_PAYLOAD_MAX);
    send(buzzer_on_mqtt_message, "buzzer/beep", pad, BUZZER_PAYLOAD_MAX - 1);
    CHECK(queued == 1, "Summer: %d Byte abgelehnt", BUZZER_PAYLOAD_MAX - 1);
    free(pad);
    SEND(led_on_mqtt_message, "led/set", "");
    CHECK(queued == 0 && applied == 0, "leere LED-Payload angenommen");

    if (!failures) printf("  nichts wird hinter der Payload gelesen, die Grenzen gelten\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_payload.c")
out.write_text(HARNESS.replace("__LED__", led_cut).replace("__BUZ__", buz_cut))
print("erzeugt:", out.name)
