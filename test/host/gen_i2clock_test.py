#!/usr/bin/env python3
"""Builds a host test for who holds the shared I2C bus (dout.c, rtc.c).

i2c_transmit_safe() is cut out of dout.c, reg_write() and reg_read() out of
rtc.c, verbatim; the I2C driver is a recorder that notes whether the bus
lock is held.

What it pins down, found by a review: the driver serialises transfers, but
not i2c_master_bus_reset(). The output expander's recovery reset the bus
with no lock against the RTC, so a reset from the relay path could cut into
an RTC transfer under way on the web server's or SNTP's task. Now every
transfer, and the reset with the transfer it repeats, runs under
i2c_bus_lock().
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host i2clock
"""
import pathlib
from cutter import Source

dout = Source.at("components/board/dout.c")
rtc  = Source.at("components/board/rtc.c")

HARNESS = r"""
/* GENERATED by gen_i2clock_test.py -- do not edit; edit dout.c / rtc.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_ERR_INVALID_STATE 0x103
#define ESP_ERR_INVALID_SIZE  0x104
#define TAG "t"
#define ESP_LOGW(...) ((void)0)
#define I2C_TIMEOUT_MS 50
typedef void *i2c_master_bus_handle_t;
typedef void *i2c_master_dev_handle_t;
static int bus, dev_do, dev_rtc;
static i2c_master_bus_handle_t s_bus = &bus;

static int held, unlocked_ops, stuck_once;
static void i2c_bus_lock(void)   { held++; }
static void i2c_bus_unlock(void) { held--; }
static esp_err_t i2c_master_transmit(i2c_master_dev_handle_t d, const uint8_t *b, size_t n, int to)
{ (void)d; (void)b; (void)n; (void)to; if (!held) unlocked_ops++;
  if (stuck_once) { stuck_once = 0; return ESP_ERR_INVALID_STATE; } return ESP_OK; }
static esp_err_t i2c_master_transmit_receive(i2c_master_dev_handle_t d, const uint8_t *w, size_t wn,
                                             uint8_t *r, size_t rn, int to)
{ (void)d; (void)w; (void)wn; (void)r; (void)rn; (void)to; if (!held) unlocked_ops++; return ESP_OK; }
static int resets_unlocked, resets;
static esp_err_t i2c_master_bus_reset(i2c_master_bus_handle_t b) { (void)b; resets++; if (!held) resets_unlocked++; return ESP_OK; }

/* dout.c's s_dev and rtc.c's s_dev are two variables in two files. */
#define s_dev s_dev_do
static i2c_master_dev_handle_t s_dev_do = &dev_do;
__DOUT__
#undef s_dev
#define s_dev s_dev_rtc
static i2c_master_dev_handle_t s_dev_rtc = &dev_rtc;
__RTC__
#undef s_dev

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("I2C-Bus-Sperre\n");

    uint8_t b[2] = {1, 0}, r[8];
    stuck_once = 1;
    i2c_transmit_safe(b, sizeof b);
    CHECK(resets == 1, "kein Bus-Reset bei haengendem Bus");
    CHECK(resets_unlocked == 0, "Bus-Reset ohne Bus-Sperre");
    CHECK(unlocked_ops == 0, "Ausgangs-Transfer ohne Bus-Sperre (%d)", unlocked_ops);

    unlocked_ops = 0;
    reg_write(4, r, 7);
    reg_read(3, r, 8);
    CHECK(unlocked_ops == 0, "RTC-Transfer ohne Bus-Sperre (%d)", unlocked_ops);
    CHECK(held == 0, "Sperre nicht freigegeben (%d)", held);
    if (!failures) printf("  Reset und jeder Transfer laufen unter der gemeinsamen Sperre\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
dcut = dout.func("static esp_err_t i2c_transmit_safe(const uint8_t *buf, size_t len)")
rcut = (rtc.func("static esp_err_t reg_write(uint8_t reg, const uint8_t *data, size_t len)")
        + rtc.func("static esp_err_t reg_read(uint8_t reg, uint8_t *data, size_t len)"))
out = pathlib.Path(__file__).with_name("test_i2clock.c")
out.write_text(HARNESS.replace("__DOUT__", dcut).replace("__RTC__", rcut))
print("erzeugt:", out.name)
