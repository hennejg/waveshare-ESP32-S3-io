#!/usr/bin/env python3
"""Builds a host test for channel numbers handed to the I/O bindings
(bindings.c).

The channel checks and the input/output bindings are cut out of bindings.c
verbatim; the board's I/O is a stub that records which channel was driven.
Real QuickJS.

What it pins down, found by a review: JS_ToInt32 wraps modulo 2^32, so
output(4294967296).on() drove DO1 instead of throwing, and 7.9 was taken
as 7. Now the number is checked as the double it arrives as, like pad_arg().
OLD=1 cuts bindings.c from git (OLDREV, default HEAD).

  make -C test/host chan
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/bindings.c")
if os.environ.get("OLD") == "1":
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/scripting/bindings.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout
cuts  = src.func("static int do_count(JSContext *ctx)") + src.func("static int di_count(JSContext *ctx)")
if "static int chan_arg(" in src.text:
    cuts += src.func("static int chan_arg(JSContext *ctx, JSValue v, int count, const char *what, int32_t *ch)")
for f in ("js_di_get", "js_dout_set", "js_dout_toggle", "js_dout_get"):
    cuts += src.func("static JSValue %s(JSContext *ctx, JSValue this_val, int argc, JSValue *argv)" % f)

HARNESS = r"""
/* GENERATED by gen_chan_test.py -- do not edit; edit bindings.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "quickjs.h"
typedef int esp_err_t;
#define ESP_OK 0
#define ESP_ERR_INVALID_STATE 0x103
typedef struct {
    bool (*di_get)(uint8_t); esp_err_t (*dout_set)(uint8_t, bool); esp_err_t (*dout_toggle)(uint8_t);
    bool (*dout_get)(uint8_t); int di_count, do_count;
} scripting_io_t;
static int driven = -1, driven_n;
static bool      di_get(uint8_t c)            { (void)c; return false; }
static esp_err_t dout_set(uint8_t c, bool on) { (void)on; driven = c; driven_n++; return ESP_OK; }
static esp_err_t dout_toggle(uint8_t c)       { driven = c; driven_n++; return ESP_OK; }
static bool      dout_get(uint8_t c)          { (void)c; return false; }
static const scripting_io_t s_io = { di_get, dout_set, dout_toggle, dout_get, 11, 11 };
static const scripting_io_t *scripting_io_of(JSContext *ctx) { (void)ctx; return &s_io; }

__CUT__

int main(void)
{
    JSRuntime *rt = JS_NewRuntime(); JSContext *ctx = JS_NewContext(rt);
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "_dout_set",    JS_NewCFunction(ctx, js_dout_set, "_dout_set", 2));
    JS_SetPropertyStr(ctx, g, "_dout_toggle", JS_NewCFunction(ctx, js_dout_toggle, "_dout_toggle", 1));
    JS_SetPropertyStr(ctx, g, "_dout_get",    JS_NewCFunction(ctx, js_dout_get, "_dout_get", 1));
    JS_SetPropertyStr(ctx, g, "_di_get",      JS_NewCFunction(ctx, js_di_get, "_di_get", 1));
    JS_FreeValue(ctx, g);
    int failures = 0;
    printf("Kanalnummern an die I/O-Bindings\n");
    static const char *bad[] = { "_dout_set(4294967296, true)", "_dout_toggle(4294967297)", "_dout_set(7.9, true)",
                                 "_dout_get(-4294967295)", "_di_get(4294967296)", "_dout_set(11, true)", "_dout_set(NaN, true)" };
    for (size_t i = 0; i < sizeof bad / sizeof bad[0]; i++) {
        driven = -1; driven_n = 0;
        JSValue r = JS_Eval(ctx, bad[i], strlen(bad[i]), "<t>", JS_EVAL_TYPE_GLOBAL);
        bool threw = JS_IsException(r);
        if (threw) { JSValue e = JS_GetException(ctx); JS_FreeValue(ctx, e); }
        JS_FreeValue(ctx, r);
        if (!threw || driven_n) { failures++; printf("  FEHLER: %s %s%s\n", bad[i], threw ? "warf" : "warf nicht", driven_n ? (driven >= 0 ? ", Ausgang geschaltet" : "") : ""); if (driven_n) printf("          -> Kanal %d geschaltet\n", driven); }
    }
    driven_n = 0;
    JSValue r = JS_Eval(ctx, "_dout_set(10, true)", 19, "<t>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(r) || driven != 10) { failures++; printf("  FEHLER: gueltiger Kanal 10 nicht geschaltet\n"); }
    JS_FreeValue(ctx, r);
    if (!failures) printf("  7 ungueltige Kanalnummern abgewiesen, keine geschaltet; Kanal 10 geht\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    JS_FreeContext(ctx); JS_FreeRuntime(rt);
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_chan.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
