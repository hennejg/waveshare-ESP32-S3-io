#!/usr/bin/env python3
"""Builds a host test for deferred rule timers after a time-budget interrupt
(scripting.c).

Cut out of scripting.c verbatim: the timer table, run_timer(), the overflow
ring, drain_overflow() and recover_interrupt(). QuickJS with the firmware's
patches and the real dsl.js.

What it pins down, found by an outside review: drain_overflow() ran several
deferred timers in a row and the recovery came only after the loop. The
budget cut the first callback short, a noLoop rule kept _firing, and the
second callback skipped it -- one run instead of two.
OLD=1 cuts scripting.c as it was at OLDREV (default HEAD).

  make -C test/host drain
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/scripting.c")
if os.environ.get("OLD") == "1":
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/scripting/scripting.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

cuts  = src.span("#define MAX_TIMERS", "static uint32_t     s_next_timer_id = 1;")
cuts += src.func("static timer_slot_t *timer_find(uint32_t id)")
cuts += src.span("#define TIMER_OVERFLOW_SLOTS", "static volatile uint8_t  s_of_head, s_of_tail;")
cuts += src.span("static bool    s_interrupted;", "static bool    s_interrupted;")
if "#define RESUME_TRIES" in src.text:
    cuts += src.defines("RESUME_TRIES")
cuts += src.func("static void recover_interrupt(JSContext *ctx)")
cuts += src.func("static void run_timer(JSContext *ctx, uint32_t id)")
cuts += src.func("static void drain_overflow(JSContext *ctx)")

HARNESS = r"""
/* GENERATED by gen_drain_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include "quickjs.h"

#define TAG "t"
#define ESP_LOGW(tag, ...) do { printf("    log: "); printf(__VA_ARGS__); printf("\n"); } while (0)
#define ESP_LOGE ESP_LOGW
typedef void *esp_timer_handle_t;
static void esp_timer_delete(esp_timer_handle_t h) { (void)h; }
#define vTaskDelay(t) ((void)(t))
typedef int BaseType_t;
#define pdTRUE 1
#define pdFALSE 0
typedef struct { uint64_t seq; } scripting_evt_t;
typedef void *QueueHandle_t;
static QueueHandle_t s_queue;
static BaseType_t xQueuePeek(QueueHandle_t q, scripting_evt_t *e, int t) { (void)q; (void)e; (void)t; return pdFALSE; }
static inline bool evt_seq_after(uint64_t a, uint64_t b) { return a > b; }

/* The budget: 30 ms of wall time per entry into JS. */
static struct timespec deadline;
static void budget_start(void)
{
    clock_gettime(CLOCK_MONOTONIC, &deadline);
    deadline.tv_nsec += 30 * 1000000L;
    if (deadline.tv_nsec >= 1000000000L) { deadline.tv_sec++; deadline.tv_nsec -= 1000000000L; }
}

__CUT__

static int js_interrupt(JSRuntime *rt, void *op)
{
    (void)rt; (void)op;
    struct timespec now; clock_gettime(CLOCK_MONOTONIC, &now);
    if (now.tv_sec < deadline.tv_sec || (now.tv_sec == deadline.tv_sec && now.tv_nsec <= deadline.tv_nsec)) return 0;
    s_interrupted = true;
    return 1;
}
static JSValue js_nop(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_UNDEFINED; }
static JSValue js_now(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)t; (void)c; (void)v; return JS_NewFloat64(ctx, 1e12); }
static JSValue js_false(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_FALSE; }

/* A timer whose callback is fn, deferred into the overflow ring. */
static void defer(JSContext *ctx, const char *fn_src)
{
    JSValue fn = JS_Eval(ctx, fn_src, strlen(fn_src), "<cb>", JS_EVAL_TYPE_GLOBAL);
    for (int i = 0; i < MAX_TIMERS; i++) if (!s_timers[i].used) {
        s_timers[i].used = true; s_timers[i].id = s_next_timer_id++; s_timers[i].fn = fn;
        s_overflow[s_of_head] = s_timers[i].id;
        s_overflow_seq[s_of_head] = s_timers[i].id;
        s_of_head = (uint8_t)((s_of_head + 1u) % TIMER_OVERFLOW_SLOTS);
        return;
    }
    exit(2);
}

static char *slurp(const char *path)
{
    FILE *f = fopen(path, "rb"); if (!f) { perror(path); exit(2); }
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    char *b = malloc((size_t)n + 1); if (fread(b, 1, (size_t)n, f) != (size_t)n) exit(2); b[n] = 0; fclose(f);
    return b;
}

int main(int argc, char **argv)
{
    const char *dsl = slurp(argc > 1 ? argv[1] : "../../components/scripting/dsl.js");
    JSRuntime *rt = JS_NewRuntime();
    JSContext *ctx = JS_NewContext(rt);
    JS_SetInterruptHandler(rt, js_interrupt, NULL);
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "print",   JS_NewCFunction(ctx, js_nop, "print", 1));
    JS_SetPropertyStr(ctx, g, "_now",    JS_NewCFunction(ctx, js_now, "_now", 0));
    JS_SetPropertyStr(ctx, g, "_di_get", JS_NewCFunction(ctx, js_false, "_di_get", 1));
    JS_FreeValue(ctx, g);
    budget_start();
    const char *rules =
        "var T = { n: 0 };"
        "rule('n').when(input(0).isOn()).noLoop().then(function () {"
        "  T.n++; if (T.n == 1) for (;;) {}"      /* the first run overruns the budget */
        "});";
    const char *src[2] = { dsl, rules };
    for (int k = 0; k < 2; k++) {
        budget_start();
        JSValue r = JS_Eval(ctx, src[k], strlen(src[k]), "<load>", JS_EVAL_TYPE_GLOBAL);
        if (JS_IsException(r)) { printf("laedt nicht\n"); return 2; }
        JS_FreeValue(ctx, r);
    }

    printf("  zwei aufgestaute Timer, der erste ueberzieht das Budget:\n");
    defer(ctx, "(function () { _on_input(0, true); })");
    defer(ctx, "(function () { _on_input(0, false); _on_input(0, true); })");
    drain_overflow(ctx);
    recover_interrupt(ctx);          /* the loop's, after drain_overflow() */

    JSValue v = JS_Eval(ctx, "T.n", 3, "<n>", JS_EVAL_TYPE_GLOBAL);
    int32_t n = -1; JS_ToInt32(ctx, &n, v); JS_FreeValue(ctx, v);
    printf("  noLoop-Regel: %d Ausfuehrungen (erwartet 2)\n", n);
    int failures = n != 2;
    if (failures) printf("  FEHLER: der zweite Timer hat die Regel uebersprungen\n");
    for (int i = 0; i < MAX_TIMERS; i++) if (s_timers[i].used) JS_FreeValue(ctx, s_timers[i].fn);
    JS_FreeContext(ctx); JS_FreeRuntime(rt);
    printf(failures ? "drain: %d FEHLER\n" : "drain: alles OK\n", failures);
    return failures;
}
"""
out = pathlib.Path(__file__).with_name("test_drain.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
