#!/usr/bin/env python3
"""Builds a host test for how long one client can hold the WiFi setup
portal's HTTP server (wifi_config.c).

serve_client() is cut out of wifi_config.c verbatim (with OLD=1, the
per-connection loop of the old http_task). Socket reads, the tick count and
the HTTP parser are scripted.

What it pins down, found by a review: the portal serves one client at a
time, and SO_RCVTIMEO only bounds each read. A client sending a byte every
few seconds, or anything the parser could not read (a TLS hello on port 80),
kept the setup page from everyone else for as long as it liked. Now the
connection has a deadline, and a parse error ends it.
OLD=1 cuts wifi_config.c from git (OLDREV, default HEAD).

  make -C test/host portalconn
"""
import pathlib
from cutter import Source

src = Source.at("components/esp32-wifi-bootstrap/src/wifi_config.c")
if "static void serve_client(int fd) {" in src.text:
    cut = src.defines("WIFI_CONFIG_CLIENT_DEADLINE_MS") + src.func("static void serve_client(int fd) {")
else:
    body = src.span("                const struct timeval client_to = { 5, 0 };", "                client_free(client);")
    cut = "static void serve_client(int fd) {\n        char data[256];\n" + body + "}\n"

HARNESS = r"""
/* GENERATED by gen_portalconn_test.py -- do not edit; edit wifi_config.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>
#include <sys/time.h>

#define INFO(...) ((void)0)
typedef uint32_t TickType_t;
#define pdMS_TO_TICKS(x) ((TickType_t)(x) / 10)
#define SOL_SOCKET 0
#define SO_RCVTIMEO 0
static int setsockopt(int fd, int l, int o, const void *v, int n) { (void)fd; (void)l; (void)o; (void)v; (void)n; return 0; }
enum { HPE_OK = 0, HPE_INVALID_METHOD = 1 };
typedef struct { int err; } http_parser;
#define HTTP_PARSER_ERRNO(p) ((p)->err)
static const char *http_errno_name(int e) { (void)e; return "?"; }
typedef struct { int dummy; } http_parser_settings;
static http_parser_settings wifi_config_http_parser_settings;
typedef struct { int fd; bool disconnected; http_parser parser; } client_t;
static client_t *client_new(void) { return calloc(1, sizeof(client_t)); }
static void client_free(client_t *c) { free(c); }
static bool handle_get_request(client_t *c, const char *d, int n) { (void)c; (void)d; (void)n; return false; }
static size_t http_parser_execute(http_parser *p, const http_parser_settings *s, const char *d, size_t n)
{ (void)s; if ((unsigned char)d[0] == 0x16) { p->err = HPE_INVALID_METHOD; return 0; } return n; }

/* The client: each read takes `gap` ms and returns one byte, forever. */
static TickType_t ticks; static int reads, gap_ms; static const char *script_byte = "G";
static TickType_t xTaskGetTickCount(void) { return ticks; }
static int lwip_read(int fd, void *b, size_t n)
{
    (void)fd; (void)n;
    if (++reads > 1000) return -1;            /* the test's own limit */
    ticks += (TickType_t)(gap_ms / 10);
    memcpy(b, script_byte, 1);
    return 1;
}
static void lwip_close(int fd) { (void)fd; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Setup-Portal: eine Verbindung\n");

    ticks = 0; reads = 0; gap_ms = 4000; script_byte = "G";
    serve_client(3);
    CHECK(ticks * 10 <= 15000, "Langsamsender (1 Byte / 4 s) haelt das Portal %u s fest", (unsigned)(ticks / 100));

    ticks = 0; reads = 0; gap_ms = 10; script_byte = "\x16";
    serve_client(3);
    CHECK(reads == 1, "TLS-Hallo auf Port 80: %d Lesevorgaenge statt Abbruch nach dem ersten", reads);

    if (!failures) printf("  Langsamsender nach der Frist getrennt, Unlesbares sofort\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_portalconn.c")
out.write_text(HARNESS.replace("__CUT__", cut))
print("erzeugt:", out.name)
