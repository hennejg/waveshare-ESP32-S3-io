#!/usr/bin/env python3
"""Builds a host test for the NMEA 2000 heartbeat (can_server.c).

n2k_make_id() and n2k_tx_heartbeat() are cut out of can_server.c verbatim;
the CAN send functions are stubs that record what would go on the bus.

What it pins down, found by a review and checked against canboat
(pgn-generated-data.h: 126993 Heartbeat, PACKET_SINGLE, field 1
DURATION_UFIX16_MS): the heartbeat is one 8-byte frame whose first field is
the transmit interval in milliseconds. It went out as a 9-byte fast-packet
with the interval in 0.01 s.
OLD=1 cuts can_server.c from git (OLDREV, default HEAD).

  make -C test/host n2khb
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("apps/full/main/can_server.c")
cuts  = src.defines("HB_PERIOD_MS", "N2K_PGN_HEARTBEAT", "N2K_ADDR_GLOBAL")
cuts += src.func("static uint32_t n2k_make_id(uint32_t pgn, uint8_t pri, uint8_t src, uint8_t dst)")
cuts += src.func("static void n2k_tx_heartbeat(void)")

HARNESS = r"""
/* GENERATED by gen_n2khb_test.py -- do not edit; edit can_server.c. */
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static uint8_t s_hb_seq, s_addr = 42;
static int frames, fp_msgs;
static uint32_t last_id; static uint8_t last[16], last_len;
static void n2k_send_frame(uint32_t id, const uint8_t *d, uint8_t dlc)
{ frames++; last_id = id; last_len = dlc; memcpy(last, d, dlc); }
static void n2k_send_fp(uint32_t pgn, uint8_t pri, uint8_t dst, const uint8_t *d, uint16_t len)
{ (void)pgn; (void)pri; (void)dst; fp_msgs++; last_len = (uint8_t)len; memcpy(last, d, len > 16 ? 16 : len); }

__CUT__

int main(void)
{
    int failures = 0;
    printf("NMEA-2000-Heartbeat (PGN 126993)\n");
    n2k_tx_heartbeat();
    n2k_tx_heartbeat();
    if (fp_msgs) { failures++; printf("  FEHLER: als Fast-Packet gesendet (%u Bytes)\n", last_len); }
    if (frames != 2 || last_len != 8) { failures++; printf("  FEHLER: %d Einzelframes, Laenge %u statt 8\n", frames, last_len); }
    else {
        uint32_t pgn = (last_id >> 8) & 0x3FFFF, pri = (last_id >> 26) & 7, src = last_id & 0xFF;
        unsigned ms = last[0] | last[1] << 8;
        if (pgn != 126993 || pri != 7 || src != s_addr) { failures++; printf("  FEHLER: PGN %u Prio %u Quelle %u\n", pgn, pri, src); }
        if (ms != HB_PERIOD_MS) { failures++; printf("  FEHLER: Intervall-Feld %u statt %u ms\n", ms, HB_PERIOD_MS); }
        if (last[2] != 1) { failures++; printf("  FEHLER: Sequenzzaehler %u statt 1\n", last[2]); }
        if (!failures) printf("  ein 8-Byte-Frame, PGN %u, Prio %u, Intervall %u ms, Sequenz zaehlt\n", pgn, pri, ms);
    }
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_n2khb.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
