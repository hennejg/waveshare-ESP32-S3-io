#!/usr/bin/env python3
"""Builds a host test for what the poll table says about an RS-485 read
(mb_tcp_master.c).

read_rtu() is cut out of mb_tcp_master.c verbatim, with the exception codes
from mb_request.h and mb_gateway.h; the bus master is a stub that answers
with whatever the test asks for.

What it pins down, found by a review: 0x0A comes from the local bus master
when it could not even send (mb_gateway.c, transact()), but the entry's
error said "device says exception 0x0A" -- pointing at a device that was
never asked. A device's own exception is still reported as one.
OLD=1 cuts mb_tcp_master.c from git (OLDREV, default HEAD).

  make -C test/host rtuerr
"""
import pathlib
from cutter import Source

src = Source.at("apps/full/main/mb_tcp_master.c")
req = Source.at("apps/full/main/mb_request.h")
gw  = Source.at("apps/full/main/mb_gateway.h")
defines = req.defines("MB_EXC_NONE", "MB_EXC_ILLEGAL_ADDR", "MB_EXC_GW_PATH", "MB_EXC_GW_TARGET") + gw.defines("MB_GW_BUS_BUSY")
cuts = src.func("static bool read_rtu(const mbm_poll_t *e, uint16_t regs, double *value,")

HARNESS = r"""
/* GENERATED by gen_rtuerr_test.py -- do not edit; edit mb_tcp_master.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
__DEFINES__
typedef struct { uint8_t unit_id, fc; uint16_t reg; } mbm_poll_t;
static uint8_t answer;
static bool mb_gateway_is_running(void) { return true; }
static uint8_t mb_gateway_read_regs(uint8_t uid, uint8_t fc, uint16_t addr, uint16_t n, uint16_t *r)
{ (void)uid; (void)fc; (void)addr; (void)n; (void)r; return answer; }
static void mb_put16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)(v >> 8); p[1] = (uint8_t)v; }
static bool decode_scaled(const mbm_poll_t *e, const uint8_t *w, double *v, char *err, size_t n)
{ (void)e; (void)w; (void)err; (void)n; *v = 1; return true; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("Fehlertext einer RS-485-Abfrage\n");
    mbm_poll_t e = { .unit_id = 12, .fc = 4, .reg = 70 };
    double v; char err[48];

    answer = MB_EXC_GW_PATH; err[0] = 0;
    CHECK(!read_rtu(&e, 1, &v, err, sizeof err), "0x0A als Erfolg");
    CHECK(!strstr(err, "device"), "0x0A des eigenen Busmasters dem Geraet zugeschrieben: \"%s\"", err);

    answer = MB_EXC_ILLEGAL_ADDR; err[0] = 0;
    CHECK(!read_rtu(&e, 1, &v, err, sizeof err) && strstr(err, "device says exception 0x02"),
          "Exception des Geraets nicht als solche gemeldet: \"%s\"", err);

    answer = MB_EXC_GW_TARGET; err[0] = 0;
    CHECK(!read_rtu(&e, 1, &v, err, sizeof err) && strstr(err, "no answer"), "keine Antwort: \"%s\"", err);
    if (!failures) printf("  0x0A heisst Busmaster-Fehler, Geraete-Exceptions bleiben Geraete-Exceptions\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_rtuerr.c")
out.write_text(HARNESS.replace("__DEFINES__", defines).replace("__CUT__", cuts))
print("erzeugt:", out.name)
