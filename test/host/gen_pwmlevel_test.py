#!/usr/bin/env python3
"""Builds a host test for a header pad's PWM level as Matter remembers it
(apps/matter/main/matter.cpp).

Cut out verbatim: level_to_duty(), duty_to_level() and aux_attr_update(),
compiled as C++ against stand-ins for the esp-matter types.

What it pins down, found by a review: the level a controller wrote was
remembered before the pad was asked to take it. A refused level stayed
remembered, and the next "on" switched to it -- level 64 (25.2 %), a
refused 192, then off and on gave 75.6 %. Now it is remembered only once
the pad took it; a level written while the pad is off is kept for the next
"on" as before.
OLD=1 cuts matter.cpp from git (OLDREV, default HEAD).

  make -C test/host pwmlevel
"""
import pathlib
from cutter import Source

src = Source.at("apps/matter/main/matter.cpp")
cuts = (src.func("static uint16_t level_to_duty(uint8_t level)")
        + src.func("static uint8_t duty_to_level(uint16_t duty_pm)")
        + src.func("static esp_err_t aux_attr_update(int a, uint32_t cluster_id, uint32_t attribute_id,"))

HARNESS = r"""
// GENERATED by gen_pwmlevel_test.py -- do not edit; edit matter.cpp.
#include <cstdint>
#include <cstdio>
#include <limits>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define ESP_ERR_INVALID_STATE 0x103
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGW(...) ((void)0)
#define AUX_PAD_COUNT 3
#define AUX_PWM_DUTY_MAX 1000u
typedef enum { AUX_MODE_STANDARD, AUX_MODE_INPUT, AUX_MODE_OUTPUT, AUX_MODE_PWM, AUX_MODE_ANALOG } aux_mode_t;
namespace OnOff { constexpr uint32_t Id = 6; namespace Attributes { namespace OnOff { constexpr uint32_t Id = 0; } } }
namespace LevelControl { constexpr uint32_t Id = 8; namespace Attributes { namespace CurrentLevel { constexpr uint32_t Id = 0; } } }
enum { ESP_MATTER_VAL_TYPE_BOOLEAN = 1, ESP_MATTER_VAL_TYPE_NULLABLE_UINT8 = 2 };
struct esp_matter_attr_val_t { int type; union { bool b; uint8_t u8; } val; };
namespace chip { namespace app { template <typename T> struct NumericAttributeTraits {
    static bool IsNullValue(T v) { return v == std::numeric_limits<T>::max(); } }; } }

static aux_mode_t s_aux_ep_mode[AUX_PAD_COUNT] = { AUX_MODE_PWM, AUX_MODE_STANDARD, AUX_MODE_STANDARD };
static bool       s_pwm_on[AUX_PAD_COUNT];
static uint8_t    s_pwm_level[AUX_PAD_COUNT];
static aux_mode_t aux_io_mode(uint8_t a) { return s_aux_ep_mode[a]; }
static esp_err_t  aux_io_out_set(uint8_t a, bool on) { (void)a; (void)on; return ESP_OK; }
static bool fail_pwm; static uint16_t duty;
static esp_err_t  aux_io_pwm_set(uint8_t a, uint32_t f, uint16_t d)
{ (void)a; (void)f; if (fail_pwm) return ESP_FAIL; duty = d; return ESP_OK; }

__CUT__

static esp_err_t level(uint8_t l)
{ esp_matter_attr_val_t v{}; v.type = ESP_MATTER_VAL_TYPE_NULLABLE_UINT8; v.val.u8 = l;
  return aux_attr_update(0, LevelControl::Id, LevelControl::Attributes::CurrentLevel::Id, &v); }
static esp_err_t onoff(bool on)
{ esp_matter_attr_val_t v{}; v.type = ESP_MATTER_VAL_TYPE_BOOLEAN; v.val.b = on;
  return aux_attr_update(0, OnOff::Id, OnOff::Attributes::OnOff::Id, &v); }

int main()
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; std::printf("  FEHLER: "); std::printf(__VA_ARGS__); std::printf("\n"); } } while (0)
    std::printf("PWM-Pad: gemerkter Matter-Level\n");
    s_pwm_level[0] = 254;
    CHECK(onoff(true) == ESP_OK && duty == 1000, "einschalten: duty %u", duty);
    CHECK(level(64) == ESP_OK && duty == 252, "Level 64: duty %u statt 252", duty);
    fail_pwm = true;
    CHECK(level(192) != ESP_OK, "abgelehnter Level 192 meldet ok");
    fail_pwm = false;
    CHECK(onoff(false) == ESP_OK && onoff(true) == ESP_OK && duty == 252,
          "nach abgelehntem 192: aus/an gibt duty %u statt 252 (25,2 %%)", duty);
    CHECK(onoff(false) == ESP_OK && level(128) == ESP_OK && onoff(true) == ESP_OK && duty == level_to_duty(128),
          "Level im ausgeschalteten Zustand nicht fuer das naechste An gemerkt (duty %u)", duty);
    if (!failures) std::printf("  ein abgelehnter Level bleibt nicht haengen; aus-Level wird gemerkt\n");
    std::printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_pwmlevel.cpp")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
