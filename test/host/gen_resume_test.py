#!/usr/bin/env python3
"""Builds a host test for what a time-budget interrupt costs the other rules
(scripting.c, dsl.js).

Cut out of scripting.c verbatim: the timer table, run_timer() and
recover_interrupt(). QuickJS with the firmware's patches and the real
dsl.js; timers run on a fake clock, each with a budget of its own and the
recovery after it, as in the firmware's loop.

What it pins down, found by an outside review:
  - the engine takes an event off the queue and walks the rules in one
    _fire_matching() pass; a rule that ran over the budget cut the whole
    pass short, and the rules after it never saw the event -- an output a
    later rule was to switch on that edge stayed as it was;
  - a heldFor() timer whose check was cut short had already cleared its
    timer and fired nothing; with the conditions steady and no further
    event, the rule never fired.
OLD=1 takes scripting.c and dsl.js from git (OLDREV, default HEAD).

  make -C test/host resume
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/scripting.c")
dsl  = ROOT / "components/scripting/dsl.js"
here = pathlib.Path(__file__).parent
if os.environ.get("OLD") == "1":
    rev = os.environ.get("OLDREV", "HEAD")
    show = lambda rel: subprocess.run(["git", "show", rev + ":" + rel], cwd=ROOT,
                                      capture_output=True, text=True, check=True).stdout
    src.text = show("components/scripting/scripting.c")
    dsl = here / "test_resume_old_dsl.js"
    dsl.write_text(show("components/scripting/dsl.js"))

cuts  = src.span("#define MAX_TIMERS", "static uint32_t     s_next_timer_id = 1;")
cuts += src.func("static timer_slot_t *timer_find(uint32_t id)")
cuts += src.span("static bool    s_interrupted;", "static bool    s_interrupted;")
if "#define RESUME_TRIES" in src.text:
    cuts += src.defines("RESUME_TRIES")
cuts += src.func("static void recover_interrupt(JSContext *ctx)")
cuts += src.func("static void run_timer(JSContext *ctx, uint32_t id)")

HARNESS = r"""
/* GENERATED by gen_resume_test.py -- do not edit; edit scripting.c / dsl.js. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include "quickjs.h"

#define TAG "t"
static int logs;
#define ESP_LOGW(tag, ...) do { logs++; } while (0)
#define ESP_LOGE(tag, ...) do { printf("    log: "); printf(__VA_ARGS__); printf("\n"); } while (0)
typedef void *esp_timer_handle_t;
static void esp_timer_delete(esp_timer_handle_t h) { (void)h; }
#define vTaskDelay(t) ((void)(t))

/* The budget: 30 ms of wall time per entry into JS. */
static struct timespec deadline;
static void budget_start(void)
{
    clock_gettime(CLOCK_MONOTONIC, &deadline);
    deadline.tv_nsec += 30 * 1000000L;
    if (deadline.tv_nsec >= 1000000000L) { deadline.tv_sec++; deadline.tv_nsec -= 1000000000L; }
}

__CUT__

static int js_interrupt(JSRuntime *rt, void *op)
{
    (void)rt; (void)op;
    struct timespec now; clock_gettime(CLOCK_MONOTONIC, &now);
    if (now.tv_sec < deadline.tv_sec || (now.tv_sec == deadline.tv_sec && now.tv_nsec <= deadline.tv_nsec)) return 0;
    s_interrupted = true;
    return 1;
}

/* Timers on a fake clock: the slot table is the firmware's, the due times
   stand in for esp_timer. */
static int64_t fake_now = 1000000, due[MAX_TIMERS];
static JSValue js_set_timer(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{
    (void)t; (void)c;
    double ms; JS_ToFloat64(ctx, &ms, v[0]);
    for (int i = 0; i < MAX_TIMERS; i++) if (!s_timers[i].used) {
        s_timers[i].used = true; s_timers[i].id = s_next_timer_id++;
        s_timers[i].fn = JS_DupValue(ctx, v[1]);
        due[i] = fake_now + (int64_t)(ms < 0 ? 0 : ms);
        return JS_NewInt32(ctx, (int32_t)s_timers[i].id);
    }
    return JS_NewInt32(ctx, -1);
}
static JSValue js_clear_timer(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{
    (void)t; (void)c;
    int32_t id; JS_ToInt32(ctx, &id, v[0]);
    timer_slot_t *s = timer_find((uint32_t)id);
    if (s) { JS_FreeValue(ctx, s->fn); s->used = false; }
    return JS_UNDEFINED;
}
static JSValue js_nop(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_UNDEFINED; }
static JSValue js_now(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)t; (void)c; (void)v; return JS_NewFloat64(ctx, (double)fake_now); }
static JSValue js_false(JSContext *ctx, JSValueConst t, int c, JSValueConst *v)
{ (void)ctx; (void)t; (void)c; (void)v; return JS_FALSE; }

/* One event the way the firmware's loop delivers it. */
static void event(JSContext *ctx, const char *js)
{
    budget_start();
    JSValue r = JS_Eval(ctx, js, strlen(js), "<event>", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(r)) JS_FreeValue(ctx, JS_GetException(ctx));
    JS_FreeValue(ctx, r);
    recover_interrupt(ctx);
}
static void run_until(JSContext *ctx, int64_t end)
{
    for (int guard = 0; guard < 1000; guard++) {
        int best = -1;
        for (int i = 0; i < MAX_TIMERS; i++)
            if (s_timers[i].used && (best < 0 || due[i] < due[best])) best = i;
        if (best < 0 || due[best] > end) break;
        if (due[best] > fake_now) fake_now = due[best];
        budget_start();
        run_timer(ctx, s_timers[best].id);
        recover_interrupt(ctx);
    }
    fake_now = end;
}
static int num(JSContext *ctx, const char *expr)
{
    JSValue r = JS_Eval(ctx, expr, strlen(expr), "<expr>", JS_EVAL_TYPE_GLOBAL);
    int32_t d = -1; JS_ToInt32(ctx, &d, r); JS_FreeValue(ctx, r); return d;
}
static double ms_since(struct timespec a)
{
    struct timespec b; clock_gettime(CLOCK_MONOTONIC, &b);
    return (b.tv_sec - a.tv_sec) * 1e3 + (b.tv_nsec - a.tv_nsec) / 1e6;
}
static char *slurp(const char *path)
{
    FILE *f = fopen(path, "rb"); if (!f) { perror(path); exit(2); }
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    char *b = malloc((size_t)n + 1); if (fread(b, 1, (size_t)n, f) != (size_t)n) exit(2); b[n] = 0; fclose(f);
    return b;
}

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    char *dsl = slurp("__DSL__");
    JSRuntime *rt = JS_NewRuntime();
    JSContext *ctx = JS_NewContext(rt);
    JS_SetInterruptHandler(rt, js_interrupt, NULL);
    JSValue g = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, g, "print",        JS_NewCFunction(ctx, js_nop, "print", 1));
    JS_SetPropertyStr(ctx, g, "_now",         JS_NewCFunction(ctx, js_now, "_now", 0));
    JS_SetPropertyStr(ctx, g, "_di_get",      JS_NewCFunction(ctx, js_false, "_di_get", 1));
    JS_SetPropertyStr(ctx, g, "_set_timer",   JS_NewCFunction(ctx, js_set_timer, "_set_timer", 2));
    JS_SetPropertyStr(ctx, g, "_clear_timer", JS_NewCFunction(ctx, js_clear_timer, "_clear_timer", 1));
    JS_FreeValue(ctx, g);
    const char *rules =
        "var T = { a: 0, b: 0, c: 0, spinA: 1, o: 0, i1: 0, i2: 0, o2: 0, spinI: 1,"
        "          m: 0, s: 0, z: 0, spinS: 1, h: 0, slowH: 0, f: fact(0) };"
        "function spin() { for (;;) {} }"
        /* 1. Three rules on one edge, the first runs over. */
        "rule('a').when(input(0).isOn()).then(function(){ T.a++; if (T.spinA) spin(); });"
        "rule('b').when(input(0).isOn()).then(function(){ T.b++; });"
        "rule('c').when(input(0).isOn()).then(function(){ T.c++; });"
        /* 2. Nested: an outer rule's fact change runs an inner pass, whose
              first rule runs over. */
        "rule('outer').when(input(2).isOn()).then(function(){ T.o++; T.f.set(1); });"
        "rule('inner1').when(T.f.is(1)).then(function(){ T.i1++; if (T.spinI) spin(); });"
        "rule('inner2').when(T.f.is(1)).then(function(){ T.i2++; });"
        "rule('outer2').when(input(2).isOn()).then(function(){ T.o2++; });"
        /* 3. mqtt().once(): later rules on the same message still see it armed. */
        "rule('m1').when(mqtt('x').once()).then(function(){ if (T.spinA) spin(); });"
        "rule('m2').when(mqtt('x').once()).then(function(){ T.m++; });"
        /* 4. Every rule on the edge runs over: bounded. */
        "for (var k = 0; k < 6; k++) rule('s' + k).when(input(4).isOn()).then(function(){ T.s++; if (T.spinS) spin(); });"
        "rule('z').when(input(4).isOn()).then(function(){ T.z++; });"
        /* 5. heldFor() whose check at the end of the period runs over once. */
        "rule('h').when(input(1).isOn(), function(){ if (T.slowH) { T.slowH = 0; spin(); } return true; })"
        "  .heldFor(1000).then(function(){ T.h++; });";
    const char *src[2] = { dsl, rules };
    for (int k = 0; k < 2; k++) {
        budget_start();
        JSValue r = JS_Eval(ctx, src[k], strlen(src[k]), "<load>", JS_EVAL_TYPE_GLOBAL);
        if (JS_IsException(r)) { printf("laedt nicht\n"); return 2; }
        JS_FreeValue(ctx, r);
    }

    printf("Zeitbudget-Abbruch und die uebrigen Regeln\n");
    event(ctx, "_on_input(0, true)");
    CHECK(num(ctx, "T.a") == 1, "a lief %d mal", num(ctx, "T.a"));
    CHECK(num(ctx, "T.b") == 1 && num(ctx, "T.c") == 1,
          "spaetere Regeln auf derselben Flanke: b=%d c=%d (erwartet 1/1)", num(ctx, "T.b"), num(ctx, "T.c"));
    printf("  eine Regel ueberzieht: die Regeln nach ihr bekommen das Ereignis (b=%d c=%d)\n", num(ctx, "T.b"), num(ctx, "T.c"));

    event(ctx, "_on_input(2, true)");
    CHECK(num(ctx, "T.i2") == 1, "innerer Durchlauf nicht fortgesetzt: inner2=%d", num(ctx, "T.i2"));
    CHECK(num(ctx, "T.o2") == 1, "aeusserer Durchlauf nicht fortgesetzt: outer2=%d", num(ctx, "T.o2"));
    CHECK(num(ctx, "T.o") == 1 && num(ctx, "T.i1") == 1, "outer/inner1 doppelt gelaufen");
    printf("  verschachtelt: innerer und aeusserer Durchlauf laufen weiter (inner2=%d outer2=%d)\n",
           num(ctx, "T.i2"), num(ctx, "T.o2"));

    event(ctx, "_on_mqtt('x', '1')");
    CHECK(num(ctx, "T.m") == 1, "mqtt().once() der spaeteren Regel: %d (erwartet 1)", num(ctx, "T.m"));
    event(ctx, "_on_input(0, false)");
    event(ctx, "T.spinA = 0");
    event(ctx, "_on_input(0, true)");
    CHECK(num(ctx, "T.m") == 1, "mqtt().once() danach ohne Nachricht erneut gefeuert");
    CHECK(num(ctx, "T.b") == 2 && num(ctx, "T.a") == 2, "zweite Flanke: a=%d b=%d", num(ctx, "T.a"), num(ctx, "T.b"));
    printf("  mqtt().once(): die spaetere Regel sieht die Nachricht, danach nicht mehr\n");

    struct timespec t0; clock_gettime(CLOCK_MONOTONIC, &t0);
    event(ctx, "_on_input(4, true)");
    double ms = ms_since(t0);
    CHECK(ms < 400, "alle Regeln ueberziehen: %.0f ms blockiert", ms);
    int s = num(ctx, "T.s");
    CHECK(s >= 2, "nach dem ersten Abbruch keine weitere Regel versucht (s=%d)", s);
    event(ctx, "T.spinS = 0");
    event(ctx, "_on_input(4, false)");
    event(ctx, "_on_input(4, true)");
    CHECK(num(ctx, "T.z") >= 1, "die Engine laeuft danach nicht normal weiter (z=%d)", num(ctx, "T.z"));
    printf("  jede Regel ueberzieht: %d versucht, %.0f ms blockiert, danach normal\n", s, ms);

    event(ctx, "_on_input(1, true)");
    event(ctx, "T.slowH = 1");
    run_until(ctx, fake_now + 1000);      /* the check at the end runs over  */
    run_until(ctx, fake_now + 1000);      /* set again: fires one period on  */
    CHECK(num(ctx, "T.h") == 1, "heldFor() nach abgebrochener Pruefung: %d Ausfuehrungen (erwartet 1)", num(ctx, "T.h"));
    run_until(ctx, fake_now + 5000);
    CHECK(num(ctx, "T.h") == 1, "heldFor() feuert mehrfach: %d", num(ctx, "T.h"));
    printf("  heldFor(): abgebrochene Pruefung wird neu angesetzt und feuert einmal\n");

    for (int i = 0; i < MAX_TIMERS; i++) if (s_timers[i].used) JS_FreeValue(ctx, s_timers[i].fn);
    JS_FreeContext(ctx); JS_FreeRuntime(rt);
    free(dsl);
    printf(failures ? "resume: %d FEHLER\n" : "resume: alles OK\n", failures);
    return failures ? 1 : 0;
}
"""
out = here / "test_resume.c"
out.write_text(HARNESS.replace("__CUT__", cuts).replace("__DSL__", str(dsl)))
print("erzeugt:", out.name)
