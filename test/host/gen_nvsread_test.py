#!/usr/bin/env python3
"""Builds a host test for reading the stored rule script (web_server.c,
rules_nvs_read()) against an NVS that changes between two calls.

Cut out of web_server.c verbatim: rules_nvs_read() and its keys. The NVS is
a model with NVS's answers: a buffer too small gets INVALID_LENGTH and the
size needed in len.

What it pins down, found by an outside review: a script saved between the
size query and the read (a save still pending after a 202, and a GET) grew
past the buffer; NVS answered INVALID_LENGTH with the new size in len, and
buf[len] = 0 wrote past the end of the heap buffer. AddressSanitizer catches
it. Also: a save that moves the script from the old string key to the blob
in between must not make the reader take the device for empty.
OLD=1 cuts web_server.c as it was at OLDREV (default HEAD).

  make -C test/host nvsread
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "apps/full/main/web_server.c")
if os.environ.get("OLD") == "1":
    src.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":apps/full/main/web_server.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

cuts  = src.defines("RULES_NVS_NS", "RULES_NVS_BLOB", "RULES_NVS_KEY")
cuts += src.func("esp_err_t rules_nvs_read(char **out)")

HARNESS = r"""
/* GENERATED by gen_nvsread_test.py -- do not edit; edit web_server.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef int esp_err_t;
#define ESP_OK                     0
#define ESP_ERR_NO_MEM             0x101
#define ESP_ERR_INVALID_STATE      0x103
#define ESP_ERR_INVALID_SIZE       0x104
#define ESP_ERR_NVS_NOT_FOUND      0x1102
#define ESP_ERR_NVS_INVALID_LENGTH 0x110c
typedef uint32_t nvs_handle_t;
typedef enum { NVS_READONLY, NVS_READWRITE } nvs_open_mode_t;

/* The flash: the blob and the old string key, NULL when absent. */
static char *blob, *str;
static int calls;                       /* get calls so far */
static int change_at;                   /* before this call, change() runs */
static void (*change)(void);
static void maybe_change(void) { if (++calls == change_at && change) change(); }

static esp_err_t nvs_open(const char *ns, nvs_open_mode_t m, nvs_handle_t *h) { (void)ns; (void)m; *h = 1; return ESP_OK; }
static void nvs_close(nvs_handle_t h) { (void)h; }
static esp_err_t nvs_get_blob(nvs_handle_t h, const char *key, void *out, size_t *len)
{
    (void)h; (void)key; maybe_change();
    if (!blob) return ESP_ERR_NVS_NOT_FOUND;
    size_t n = strlen(blob);
    if (!out) { *len = n; return ESP_OK; }
    if (*len < n) { *len = n; return ESP_ERR_NVS_INVALID_LENGTH; }
    memcpy(out, blob, n); *len = n; return ESP_OK;
}
static esp_err_t nvs_get_str(nvs_handle_t h, const char *key, char *out, size_t *len)
{
    (void)h; (void)key; maybe_change();
    if (!str) return ESP_ERR_NVS_NOT_FOUND;
    size_t n = strlen(str) + 1;
    if (!out) { *len = n; return ESP_OK; }
    if (*len < n) { *len = n; return ESP_ERR_NVS_INVALID_LENGTH; }
    memcpy(out, str, n); *len = n; return ESP_OK;
}

__CUT__

static char *rep(char c, size_t n) { char *s = malloc(n + 1); memset(s, c, n); s[n] = 0; return s; }
static char *big;
static void grow(void)    { blob = big; }
static void migrate(void) { blob = big; str = NULL; }
static void erase(void)   { blob = NULL; }

static int failures;
static void run(const char *what, char *b, char *s, int at, void (*fn)(void),
                esp_err_t want_err, const char *want)
{
    blob = b; str = s; calls = 0; change_at = at; change = fn;
    char *out = NULL;
    esp_err_t err = rules_nvs_read(&out);
    bool ok = err == want_err && (want ? out && strcmp(out, want) == 0 : !out);
    printf("  %-48s err=0x%x  %zu Bytes  %s\n", what, err, out ? strlen(out) : 0, ok ? "ok" : "FEHLER");
    failures += !ok;
    free(out);
}

int main(void)
{
    char *small = rep('a', 100), *old = rep('o', 200);
    big = rep('b', 3000);
    run("Blob, unveraendert",                               small, NULL, 0, NULL, ESP_OK, small);
    run("alter String, unveraendert",                       NULL, old, 0, NULL, ESP_OK, old);
    run("nichts gespeichert",                               NULL, NULL, 0, NULL, ESP_ERR_NVS_NOT_FOUND, NULL);
    run("Blob waechst zwischen Groesse und Lesen",          small, NULL, 2, grow, ESP_OK, big);
    run("String -> Blob zwischen Groesse und Lesen",        NULL, old, 3, migrate, ESP_OK, big);
    run("Blob geloescht zwischen Groesse und Lesen",        small, NULL, 2, erase, ESP_ERR_NVS_NOT_FOUND, NULL);
    printf(failures ? "nvsread: %d FEHLER\n" : "nvsread: alles OK\n", failures);
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_nvsread.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
