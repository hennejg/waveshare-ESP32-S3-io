#!/usr/bin/env python3
"""Builds a host test for the rule engine's input resync (scripting.c).

The sequence helpers are cut out of scripting.c verbatim; the scripting task's
loop is modelled in its real order -- resync dropped channels first, then
take the next event from the queue -- with a queue, a pin and the engine's
shadow of the input.

The numbering is the engine's one event counter, 64 bits wide and taken
under a lock together with the queueing (evt_send).

What it pins down: an input change dropped because the queue was full is
resynced from the live pin, and an older event still in the queue behind it
must not put the shadow back on a level the pin left. Before the sequence
numbers it did: HIGH queued, LOW dropped, resync delivered LOW, the queued
HIGH followed -- shadow HIGH, pin LOW, a heldFor() on it fired.

  make -C test/host resync
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source(ROOT / "components/scripting/scripting.c")
cuts = src.span("static SemaphoreHandle_t s_send_lock;", "    return seq <= s_input_mark[ch & 31];\n}")

HARNESS = r"""
/* GENERATED by gen_resync_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>

/* FreeRTOS, as far as the cut code needs it: a lock and a queue of 16
   whose usable capacity qcap the test narrows. */
typedef int BaseType_t;
#define pdTRUE  1
#define pdFALSE 0
#define portMAX_DELAY 0
typedef int *SemaphoreHandle_t;
static int lock_held;
static void xSemaphoreTake(SemaphoreHandle_t l, int t) { (void)l; (void)t; lock_held++; }
static void xSemaphoreGive(SemaphoreHandle_t l)        { (void)l; lock_held--; }
typedef struct {
    int      type;
    uint64_t seq;
    union { struct { uint8_t channel; bool state; } input; };
} scripting_evt_t;
static scripting_evt_t q[16];
static int qh, qt, qcap = 16;
typedef void *QueueHandle_t;
static BaseType_t xQueueSend(QueueHandle_t h, const scripting_evt_t *e, int t)
{ (void)h; (void)t; if ((qt - qh) >= qcap) return pdFALSE; q[(qt++) % 16] = *e; return pdTRUE; }
static BaseType_t xQueueReceive(QueueHandle_t h, scripting_evt_t *e, int t)
{ (void)h; (void)t; if (qh == qt) return pdFALSE; *e = q[(qh++) % 16]; return pdTRUE; }

__CUT__

/* --- the world around them ----------------------------------------------- */
static uint32_t lost;
static bool     pin[32];      /* the live level di_get() reads   */
static bool     seen[32];     /* the engine's _di_seen shadow    */
static unsigned delivered;

/* scripting_on_input_change(): number and queue, or remember as lost. */
static void produce(uint8_t ch, bool st)
{
    scripting_evt_t e = { .type = 0, .input = { ch, st } };
    if (evt_send(&e) != pdTRUE) lost |= 1u << ch;
}

/* One pass of scripting_task(): resync, then one event. */
static void pass(void)
{
    uint32_t l = lost; lost = 0;
    for (uint8_t ch = 0; l; ch++, l >>= 1) {
        if (!(l & 1)) continue;
        input_mark_resync(ch);
        if (seen[ch] != pin[ch]) { seen[ch] = pin[ch]; delivered++; }   /* _resync_input */
    }
    scripting_evt_t e;
    if (xQueueReceive(s_queue, &e, 0) != pdTRUE) return;
    if (input_event_stale(e.input.channel, e.seq)) return;
    seen[e.input.channel] = e.input.state; delivered++;                 /* _on_input */
}

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    printf("Resync verlorener Eingangsereignisse\n");
    (void)evt_seq_after;

    /* 1. The reported case: HIGH queued, queue full, LOW dropped. */
    qcap = 1;
    pin[3] = true;  produce(3, true);           /* queued                  */
    pin[3] = false; produce(3, false);          /* queue full: dropped     */
    qcap = 16;
    for (int i = 0; i < 4; i++) pass();
    CHECK(seen[3] == false, "Schatten HIGH, Pin LOW");
    printf("  aelteres HIGH ueberschreibt das resynchronisierte LOW nicht\n");

    /* 2. A change after the resync still arrives. */
    pin[3] = true; produce(3, true);
    pass();
    CHECK(seen[3] == true, "Aenderung nach dem Resync verloren");
    printf("  Aenderung nach dem Resync kommt an\n");

    /* 3. Other channels are not affected by one channel's mark. */
    qcap = 2;
    pin[5] = true;  produce(5, true);
    pin[3] = false; produce(3, false);
    pin[3] = true;  produce(3, true);           /* dropped                 */
    qcap = 16;
    for (int i = 0; i < 4; i++) pass();
    CHECK(seen[5] == true, "Kanal 5 durch Resync von Kanal 3 verloren");
    CHECK(seen[3] == true, "Kanal 3 nicht auf dem Live-Pegel");
    printf("  die Marke eines Kanals beruehrt andere Kanaele nicht\n");

    /* 4. Long uptime: a channel never resynced, the counter past 2^31 and
          past 2^32. At 32 bits with a signed difference, event 2^31 against
          the mark 0 counted as stale, and so did every later one. */
    unsigned before = delivered;
    s_evt_seq = 0x7FFFFFFDu;
    for (int i = 0; i < 6; i++) { pin[9] = (i & 1) == 0; produce(9, pin[9]); pass(); }
    s_evt_seq = 0xFFFFFFFDu;
    for (int i = 0; i < 6; i++) { pin[9] = (i & 1) == 0; produce(9, pin[9]); pass(); }
    CHECK(delivered - before == 12, "lange Laufzeit: %u von 12 Ereignissen angekommen", delivered - before);
    printf("  Zaehler ueber 2^31 und 2^32: alle Ereignisse eines nie resynchronisierten Kanals kommen an\n");

    /* 5. The resync marks still work up there. */
    qcap = 1;
    pin[7] = true;  produce(7, true);
    pin[7] = false; produce(7, false);          /* dropped */
    qcap = 16;
    for (int i = 0; i < 4; i++) pass();
    CHECK(seen[7] == false, "nach 2^32: Schatten HIGH, Pin LOW");
    pin[7] = true; produce(7, true); pass();
    CHECK(seen[7] == true, "nach 2^32: spaetere Aenderung verloren");
    CHECK(lock_held == 0, "Sperre nicht freigegeben");
    printf("  Resync nach 2^32\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_resync.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
