#!/usr/bin/env python3
"""Builds a host test for the Modbus master's name cache and connection pick.

Same approach as gen_master_test.py: dns_slot(), resolve(), dns_recheck(),
dns_flush() and conn_get() are cut out of mb_tcp_master.c verbatim; the
resolver, the clock and the sockets are stubs the test drives.

What it pins down is what the cache exists for: the one polling task must
not pay the resolver's timeout once per entry, nor once per failed connect
while DNS is down, and a name that does not resolve must not cost another
entry its connection.

  make -C test/host dns
"""
import pathlib
from cutter import Source, kconfig_default

ROOT   = pathlib.Path(__file__).resolve().parents[2]
src    = Source(ROOT / "components/modbus/mb_tcp_master.c")

HARNESS = r'''
/* GENERATED by gen_dns_test.py -- do not edit; edit mb_tcp_master.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <netdb.h>
#include <arpa/inet.h>
#include <netinet/in.h>
#include "app_config.h"

#define TAG "mb_master"
#define ESP_LOGI(...)   ((void)0)
__DEFINES__

/* The real parser: what is under test is what resolve() does with its answer. */
static int real_inet_aton(const char *s, struct in_addr *a) { return inet_aton(s, a); }

/* --- the world the cut-out functions see ------------------------------- */
static int64_t  fake_now = 1000;
static int64_t  now_ms(void) { return fake_now; }

static unsigned lookups;          /* getaddrinfo calls                         */
static uint32_t dns_answer;       /* network order; 0 = no answer              */
static int64_t  dns_cost_ms;      /* how long a lookup blocks                  */
static struct sockaddr_in dns_sa;
static struct addrinfo    dns_ai;

static int fake_getaddrinfo(const char *h, const char *s, const struct addrinfo *hints,
                            struct addrinfo **res)
{
    (void)h; (void)s; (void)hints;
    lookups++;
    fake_now += dns_cost_ms;
    if (!dns_answer) { *res = NULL; return EAI_NONAME; }
    memset(&dns_sa, 0, sizeof dns_sa);
    dns_sa.sin_family = AF_INET;
    dns_sa.sin_addr.s_addr = dns_answer;
    memset(&dns_ai, 0, sizeof dns_ai);
    dns_ai.ai_family = AF_INET;
    dns_ai.ai_addr = (struct sockaddr *)&dns_sa;
    *res = &dns_ai;
    return 0;
}
static void fake_freeaddrinfo(struct addrinfo *ai) { (void)ai; }

#define getaddrinfo  fake_getaddrinfo
#define freeaddrinfo fake_freeaddrinfo
#define inet_aton    real_inet_aton

__TYPES__

static conn_t   s_conns[CONN_CACHE];
static unsigned conn_closes, dials, closes_before_dial;
static int      dial_result = 10;   /* fd to hand out, or -1 */
static uint32_t dialled_addr;

static void conn_close(conn_t *c) { c->fd = -1; c->host[0] = '\0'; conn_closes++; }
static int dial(uint32_t addr_be, uint16_t port, char *err, size_t err_len)
{
    (void)port;
    dials++;
    closes_before_dial = conn_closes;
    dialled_addr = addr_be;
    if (dial_result < 0) { snprintf(err, err_len, "no answer"); return -1; }
    return dial_result++;
}

/* --- cut from mb_tcp_master.c ------------------------------------------ */
__CUT__
/* ----------------------------------------------------------------------- */

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); \
                                       printf(__VA_ARGS__); printf("\n"); } } while (0)

static void reset(void)
{
    dns_flush();
    for (int i = 0; i < CONN_CACHE; i++) { memset(&s_conns[i], 0, sizeof s_conns[i]); s_conns[i].fd = -1; }
    lookups = 0; dials = 0; conn_closes = 0; dial_result = 10;
    dns_answer = htonl(0xC0000202); dns_cost_ms = 0;
}

static bool get(const char *host, char *err)
{
    bool fresh;
    return conn_get(host, 502, &fresh, err, 48) != NULL;
}

int main(void)
{
    printf("Namensaufloesung des Modbus-TCP-Masters\n");
    char err[48];
    uint32_t a;

    /* 1. A literal address never reaches the resolver; 0.0.0.0 is refused
          before anything is dialled. */
    reset();
    CHECK(resolve("192.0.2.9", &a, err, sizeof err) && a == htonl(0xC0000209),
          "Literal nicht uebernommen");
    CHECK(!resolve("0.0.0.0", &a, err, sizeof err), "0.0.0.0 angenommen");
    CHECK(!resolve("0", &a, err, sizeof err), "\"0\" angenommen");
    CHECK(!get("0.0.0.0", err) && dials == 0, "0.0.0.0 wurde gewaehlt");
    CHECK(lookups == 0, "Literal ging an den Resolver (%u)", lookups);
    printf("  Literale ohne Resolver, 0.0.0.0 abgewiesen\n");

    /* 2. Eight entries naming one host cost one lookup. */
    reset();
    for (int i = 0; i < 8; i++) resolve("meter.local", &a, err, sizeof err);
    CHECK(lookups == 1, "8 Eintraege, %u Abfragen", lookups);
    printf("  acht Eintraege, ein Name: eine Abfrage\n");

    /* 3. DNS down from the start: one lookup per DNS_RETRY_MS, however many
          entries ask. */
    reset();
    dns_answer = 0; dns_cost_ms = 5000;
    for (int i = 0; i < 8; i++)
        CHECK(!resolve("meter.local", &a, err, sizeof err), "ohne Antwort aufgeloest");
    CHECK(lookups == 1, "DNS aus: %u Abfragen statt 1", lookups);
    fake_now += DNS_RETRY_MS;
    resolve("meter.local", &a, err, sizeof err);
    CHECK(lookups == 2, "nach DNS_RETRY_MS nicht neu gefragt (%u)", lookups);
    printf("  DNS aus: eine Abfrage je %d ms\n", DNS_RETRY_MS);

    /* 4. The case the review found: address cached, then DNS and device both
          down. A failed connect may ask once more; a failed lookup must not
          be followed by another on the next failed connect. */
    reset();
    CHECK(get("meter.local", err), "erste Verbindung fehlgeschlagen");
    s_conns[0].fd = -1; s_conns[0].host[0] = '\0';      /* device went away */
    dns_answer = 0; dns_cost_ms = 5000; dial_result = -1;
    lookups = 0;
    for (int i = 0; i < 8; i++) get("meter.local", err);
    CHECK(lookups == 1, "DNS und Geraet aus: %u Abfragen in einem Durchlauf", lookups);
    CHECK(dials == 1 + 8, "alte Adresse nicht weiter versucht (%u Verbindungsversuche)", dials);
    printf("  DNS und Geraet aus: eine Abfrage, alte Adresse weiter benutzt\n");

    /* 5. With DNS working, a failed connect re-resolves once. */
    reset();
    get("meter.local", err);
    s_conns[0].fd = -1; s_conns[0].host[0] = '\0';
    dial_result = -1; lookups = 0;
    get("meter.local", err);                 /* fails, schedules a recheck */
    get("meter.local", err);                 /* rechecks */
    CHECK(lookups == 1, "nach Verbindungsfehler %u Abfragen statt 1", lookups);
    printf("  Verbindungsfehler bei laufendem DNS: einmal neu aufgeloest\n");

    /* 6. After DNS_TTL_MS the name is asked again; an open connection stays,
          even when the answer differs, and a new one uses the new address. */
    reset();
    get("meter.local", err);
    unsigned before = conn_closes; lookups = 0;
    fake_now += DNS_TTL_MS;
    dns_answer = htonl(0xC0000203);
    CHECK(get("meter.local", err), "zwischengespeicherte Verbindung verloren");
    CHECK(lookups == 1, "nach DNS_TTL_MS nicht neu gefragt (%u)", lookups);
    CHECK(conn_closes == before, "offene Verbindung wegen neuer Adresse geschlossen");
    s_conns[0].fd = -1; s_conns[0].host[0] = '\0';
    get("meter.local", err);
    CHECK(dialled_addr == htonl(0xC0000203), "neue Adresse nicht benutzt");
    printf("  nach %d ms neu gefragt, offene Verbindung bleibt, neue nutzt neue Adresse\n",
           DNS_TTL_MS);

    /* 7. A name that does not resolve costs nobody a connection. */
    reset();
    get("192.0.2.11", err); get("192.0.2.12", err); get("192.0.2.13", err);
    unsigned closes = conn_closes;
    dns_answer = 0;
    CHECK(!get("dead.local", err), "unaufloesbarer Name verbunden");
    CHECK(conn_closes == closes, "unaufloesbarer Name hat eine Verbindung gekostet");
    printf("  unaufloesbarer Name: keine Verbindung verdraengt\n");

    /* 8. Eviction closes before it dials, so the cache never holds more than
          its share of sockets. */
    dns_answer = htonl(0xC0000204);
    CHECK(get("other.local", err), "Verdraengung fehlgeschlagen");
    CHECK(closes_before_dial == closes + 1, "erst gewaehlt, dann geschlossen");
    printf("  Verdraengung: erst schliessen, dann waehlen\n");

    /* 9. A reload forgets every answer. */
    reset();
    resolve("meter.local", &a, err, sizeof err);
    dns_flush(); lookups = 0;
    resolve("meter.local", &a, err, sizeof err);
    CHECK(lookups == 1, "nach dem Leeren nicht neu gefragt");
    printf("  Leeren beim Neuladen\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
'''

cuts = "".join(src.func(sig) for sig in (
    "static dns_entry_t *dns_slot(const char *host)",
    "static bool resolve(const char *host, uint32_t *addr_be, char *err, size_t err_len)",
    "static void dns_recheck(const char *host)",
    "static void dns_flush(void)",
    "static conn_t *conn_get(const char *host, uint16_t port, bool *fresh,",
))
decl = src.span("/* One slot per entry is enough", "static dns_entry_t s_dns[APP_CFG_MBM_COUNT];")
defines = ("#define CONFIG_MB_TCP_MASTER 1\n" +
           kconfig_default("components/modbus/Kconfig", "MB_TCP_MASTER_CONNS") +
           src.defines("CONN_CACHE", "DNS_TTL_MS", "DNS_RETRY_MS"))
out = pathlib.Path(__file__).with_name("test_mb_dns.c")
out.write_text(HARNESS.replace("__DEFINES__", defines)
                      .replace("__TYPES__", src.type("} conn_t;") + src.type("} dns_entry_t;"))
                      .replace("__CUT__", decl + "\n\n" + cuts))
print("erzeugt:", out.name)
