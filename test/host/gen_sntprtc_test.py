#!/usr/bin/env python3
"""Builds a host test for where the SNTP sync writes the RTC (sntp_sync.c).

on_time_synced() is cut out of sntp_sync.c verbatim, with what it calls;
rtc_dev_set() is a recorder that knows whether it runs on lwIP's task, and
esp_timer runs its callback when the test says so.

What it pins down, found by a review: the SNTP sync callback runs on lwIP's
task and wrote the PCF85063 from there -- an I2C transfer of up to 50 ms,
longer while the output expander holds the bus for a recovery, with every
socket on the board stalled meanwhile. Now the callback only schedules the
write on the esp_timer task; a second sync while one is pending adds none.
OLD=1 cuts sntp_sync.c from git (OLDREV, default HEAD).

  make -C test/host sntprtc
"""
import pathlib
from cutter import Source

src = Source.at("components/board/sntp_sync.c")
new = "static void write_rtc(void *arg)" in src.text
cuts = "static SemaphoreHandle_t s_lock;\n"
if new:
    cuts += src.span("static esp_timer_handle_t s_rtc_timer;", "static esp_timer_handle_t s_rtc_timer;")
    cuts += src.func("static void write_rtc(void *arg)")
cuts += src.func("static void on_time_synced(struct timeval *tv)")
cuts += src.func("void sntp_sync_init(void)")

HARNESS = r"""
/* GENERATED by gen_sntprtc_test.py -- do not edit; edit sntp_sync.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <time.h>
#include <sys/time.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_ERR_INVALID_STATE 0x103
#define TAG "t"
#define ESP_LOGI(...) ((void)0)
static int warnings;
#define ESP_LOGW(...) (warnings++)
#define CONFIG_APP_SCRIPTING_ENABLE 1
typedef void *SemaphoreHandle_t;
static int sem;
static SemaphoreHandle_t xSemaphoreCreateMutex(void) { return &sem; }

typedef struct { void (*callback)(void *); const char *name; } esp_timer_create_args_t;
typedef struct { void (*cb)(void *); bool armed; } timer_t_;
typedef timer_t_ *esp_timer_handle_t;
static timer_t_ the_timer;
static esp_err_t esp_timer_create(const esp_timer_create_args_t *a, esp_timer_handle_t *h)
{ the_timer.cb = a->callback; *h = &the_timer; return ESP_OK; }
static esp_err_t esp_timer_start_once(esp_timer_handle_t t, uint64_t us)
{ (void)us; if (t->armed) return ESP_ERR_INVALID_STATE; t->armed = true; return ESP_OK; }

static bool on_lwip;
static int rtc_writes, rtc_writes_on_lwip, time_syncs;
static esp_err_t rtc_dev_set(const struct tm *t) { (void)t; rtc_writes++; if (on_lwip) rtc_writes_on_lwip++; return ESP_OK; }
static void scripting_on_time_sync(void) { time_syncs++; }

__CUT__

static void run_timer(void)          /* the esp_timer task gets its turn */
{
    if (the_timer.armed) { the_timer.armed = false; the_timer.cb(NULL); }
}

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("RTC-Schreiben nach SNTP-Sync\n");

    sntp_sync_init();
    struct timeval tv = { .tv_sec = 1800000000 };
    on_lwip = true; on_time_synced(&tv); on_time_synced(&tv); on_lwip = false;
    CHECK(rtc_writes_on_lwip == 0, "RTC auf dem lwIP-Task geschrieben (%d mal)", rtc_writes_on_lwip);
    CHECK(time_syncs == 2, "Regel-Engine nicht benachrichtigt (%d)", time_syncs);
    run_timer();
    CHECK(rtc_writes == 1, "RTC nicht genau einmal geschrieben (%d)", rtc_writes);
    CHECK(warnings == 0, "Warnung fuer einen schon geplanten Schreibvorgang (%d)", warnings);

    on_lwip = true; on_time_synced(&tv); on_lwip = false;
    run_timer();
    CHECK(rtc_writes == 2, "zweiter Sync schreibt die RTC nicht (%d)", rtc_writes);
    if (!failures) printf("  der Sync-Callback plant das Schreiben nur, es laeuft auf dem esp_timer-Task\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_sntprtc.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
