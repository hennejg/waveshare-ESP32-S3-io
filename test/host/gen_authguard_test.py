#!/usr/bin/env python3
"""Builds a host test for the web servers' access guard (both apps).

Two parts, both from the real sources:

  - Every handler in s_handlers of apps/full and apps/matter must open with
    "if (!check_auth(req)) return send_denied(req);" -- except the setup flow
    (/api/auth/*) and the static files. Checked here, on the text; the
    findings are compiled into the test so it fails like any other. Found by
    a review: the matter app's POST /api/reboot had no guard at all, and
    GET /api/version and GET /api/time answered anyone.
  - cross_site() cut out of each web_server.c, against requests the way
    browsers and curl send them.

OLD=1 takes both files from git (OLDREV, default HEAD).

  make -C test/host authguard
"""
import os, pathlib, re, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
APPS = {"full": "apps/full/main/web_server.c", "matter": "apps/matter/main/web_server.c"}
OPEN = re.compile(r'^/api/auth/|^/\*$')
GUARD = "if (!check_auth(req)) return send_denied(req);"

findings, cuts, calls = [], "", ""
for app, rel in APPS.items():
    s = Source(ROOT / rel)
    if os.environ.get("OLD") == "1":
        s.text = subprocess.run(["git", "show", "%s:%s" % (os.environ.get("OLDREV", "HEAD"), rel)],
                                cwd=ROOT, check=True, capture_output=True, text=True).stdout
    table = s.span("static const httpd_uri_t s_handlers[] = {", "};")
    rows = re.findall(r'\.uri\s*=\s*"([^"]+)",\s*\.method\s*=\s*(\w+),\s*\.handler\s*=\s*(\w+)', table)
    if len(rows) < 10: raise SystemExit("%s: handler table not understood" % rel)
    for uri, method, fn in rows:
        if OPEN.search(uri): continue
        body = s.func("static esp_err_t %s(httpd_req_t *req)" % fn)
        body = body[body.index("{") + 1:]
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        body = re.sub(r"//[^\n]*", "", body)
        first = body.strip().split("\n", 1)[0].strip()
        if first != GUARD:
            findings.append("%s: %s %s (%s) beginnt nicht mit check_auth" % (app, method.replace("HTTP_", ""), uri, fn))
    if "static bool cross_site(httpd_req_t *req)" in s.text:
        cuts += "#define cross_site cross_site_%s\n" % app
        cuts += s.func("static bool cross_site(httpd_req_t *req)")
        cuts += "#undef cross_site\n"
        calls += "    check_cross(\"%s\", cross_site_%s);\n" % (app, app)
    else:
        calls += "    failures++; printf(\"  FEHLER: %s: keine Pruefung auf Cross-Site-Anfragen\\n\");\n" % app

HARNESS = r"""
/* GENERATED by gen_authguard_test.py -- do not edit; edit web_server.c. */
#include <stdbool.h>
#include <stdio.h>
#include <string.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_ERR_NOT_FOUND 0x105
#define ESP_ERR_HTTPD_RESULT_TRUNC 0xb006
typedef struct { const char *hdr[3][2]; } httpd_req_t;
static esp_err_t httpd_req_get_hdr_value_str(httpd_req_t *r, const char *f, char *v, size_t n)
{
    for (int i = 0; i < 3; i++) {
        if (!r->hdr[i][0] || strcmp(r->hdr[i][0], f)) continue;
        size_t l = strlen(r->hdr[i][1]);
        snprintf(v, n, "%s", r->hdr[i][1]);
        return l >= n ? ESP_ERR_HTTPD_RESULT_TRUNC : ESP_OK;
    }
    return ESP_ERR_NOT_FOUND;
}

__CUT__

static int failures;
static const char *findings[] = { __FINDINGS__ NULL };

static void check_cross(const char *app, bool (*cs)(httpd_req_t *))
{
    struct { const char *what; httpd_req_t r; bool cross; } c[] = {
        { "curl, keine Browser-Header",            {{{ "Host", "192.168.1.230" }}}, false },
        { "eigene Seite (same-origin)",            {{{ "Sec-Fetch-Site", "same-origin" }, { "Origin", "http://192.168.1.230" }, { "Host", "192.168.1.230" }}}, false },
        { "URL eingetippt (none)",                 {{{ "Sec-Fetch-Site", "none" }, { "Host", "192.168.1.230" }}}, false },
        { "fremde Seite (cross-site)",             {{{ "Sec-Fetch-Site", "cross-site" }, { "Origin", "http://evil.example" }, { "Host", "192.168.1.230" }}}, true },
        { "anderer Port, gleiche IP (same-site)",  {{{ "Sec-Fetch-Site", "same-site" }, { "Host", "192.168.1.230" }}}, true },
        { "alter Browser, fremder Origin",         {{{ "Origin", "http://evil.example" }, { "Host", "192.168.1.230" }}}, true },
        { "alter Browser, eigener Origin",         {{{ "Origin", "http://192.168.1.230" }, { "Host", "192.168.1.230" }}}, false },
        { "Origin null (Sandbox, file:)",          {{{ "Origin", "null" }, { "Host", "192.168.1.230" }}}, true },
        { "Origin mit Praefix der Geraete-IP",     {{{ "Origin", "http://192.168.1.230.evil.example" }, { "Host", "192.168.1.230" }}}, true },
    };
    for (size_t i = 0; i < sizeof c / sizeof c[0]; i++) {
        bool got = cs(&c[i].r);
        if (got != c[i].cross) { failures++; printf("  FEHLER: %s: %s als %s eingestuft\n", app, c[i].what, got ? "fremd" : "eigen"); }
    }
    printf("  %s: %zu Anfragearten richtig eingestuft\n", app, sizeof c / sizeof c[0]);
}

int main(void)
{
    printf("Zugriffsschutz der Web-API\n");
    for (const char **f = findings; *f; f++) { failures++; printf("  FEHLER: %s\n", *f); }
    if (!findings[0]) printf("  jeder Handler ausser Setup und statischen Dateien prueft zuerst das Passwort\n");
__CALLS__
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
lits = "".join('"%s", ' % f.replace('"', '\\"') for f in findings)
out = pathlib.Path(__file__).with_name("test_authguard.c")
out.write_text(HARNESS.replace("__CUT__", cuts).replace("__FINDINGS__", lits).replace("__CALLS__", calls))
print("erzeugt:", out.name)
