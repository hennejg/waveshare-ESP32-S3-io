#!/usr/bin/env python3
"""Builds a host test for numbers from MQTT LED and buzzer commands (led.c,
buzzer.c).

parse_step() is cut out of led.c and parse_bstep() out of buzzer.c verbatim,
with their types and limits; ESP-IDF's cJSON parses the commands. Built with
UBSan as a hard error.

What it pins down, found by a review: both cast the JSON double straight to
uint32_t before any range check. A negative or huge duration or frequency --
{"duration":-5}, {"freq":1e12} -- is undefined behaviour in C, not a refused
or clamped value. Now the double is checked or clamped first.
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host jsoncast
"""
import pathlib
from cutter import Source

led = Source.at("components/board/led.c")
buz = Source.at("components/board/buzzer.c")

led_cut = (led.defines("DUR_MAX_MS") + led.type("} led_step_t;")
           + led.func("static int hex_digit(char c)" if "static int hex_digit(char c)" in led.text
                      else "static uint8_t hex_digit(char c)")
           + led.func("static bool parse_hex(const char *s, uint8_t *r, uint8_t *g, uint8_t *b)")
           + led.func("static bool parse_step(cJSON *obj, led_step_t *s)"))
buz_cut = (buz.defines("FREQ_MIN", "FREQ_MAX", "DUR_MIN_MS", "DUR_MAX_MS") + buz.type("} bstep_t;")
           + buz.func("static bool parse_bstep(cJSON *obj, bstep_t *s)"))

HARNESS = r"""
/* GENERATED by gen_jsoncast_test.py -- do not edit; edit led.c / buzzer.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "cJSON.h"

__LED__
#undef DUR_MAX_MS
__BUZ__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static bool led_step(const char *json, led_step_t *s)
{
    cJSON *o = cJSON_Parse(json);
    memset(s, 0, sizeof *s);
    bool ok = parse_step(o, s);
    cJSON_Delete(o);
    return ok;
}

static bool buz_step(const char *json, bstep_t *s)
{
    cJSON *o = cJSON_Parse(json);
    memset(s, 0, sizeof *s);
    bool ok = parse_bstep(o, s);
    cJSON_Delete(o);
    return ok;
}

int main(void)
{
    printf("Zahlen aus LED- und Summer-Befehlen\n");
    led_step_t l;
    CHECK(led_step("{\"color\":\"#102030\",\"duration\":500}", &l) && l.duration_ms == 500, "LED 500 ms");
    CHECK(!led_step("{\"color\":\"#102030\",\"duration\":-5}", &l), "LED -5 ms angenommen");
    CHECK(!led_step("{\"color\":\"#102030\",\"duration\":1e20}", &l), "LED 1e20 ms angenommen");
    CHECK(!led_step("{\"color\":\"#102030\",\"duration\":0.5}", &l), "LED 0,5 ms angenommen");

    bstep_t b;
    CHECK(buz_step("{\"freq\":440,\"duration\":200}", &b) && b.freq_hz == 440 && b.dur_ms == 200, "Summer 440 Hz/200 ms");
    CHECK(buz_step("{\"duration\":-5}", &b) && b.dur_ms == DUR_MIN_MS, "Summer -5 ms: %u", (unsigned)b.dur_ms);
    CHECK(buz_step("{\"duration\":1e20}", &b) && b.dur_ms == DUR_MAX_MS, "Summer 1e20 ms: %u", (unsigned)b.dur_ms);
    CHECK(buz_step("{\"freq\":-3,\"duration\":10}", &b) && b.freq_hz == 0, "Summer -3 Hz: %u", (unsigned)b.freq_hz);
    CHECK(buz_step("{\"freq\":0.5,\"duration\":10}", &b) && b.freq_hz == 0, "Summer 0,5 Hz: %u", (unsigned)b.freq_hz);
    CHECK(buz_step("{\"freq\":50,\"duration\":10}", &b) && b.freq_hz == FREQ_MIN, "Summer 50 Hz: %u", (unsigned)b.freq_hz);
    CHECK(buz_step("{\"freq\":1e12,\"duration\":10}", &b) && b.freq_hz == FREQ_MAX, "Summer 1e12 Hz: %u", (unsigned)b.freq_hz);
    if (!failures) printf("  negative und riesige Werte werden vor der Umwandlung abgelehnt oder begrenzt\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_jsoncast.c")
out.write_text(HARNESS.replace("__LED__", led_cut).replace("__BUZ__", buz_cut))
print("erzeugt:", out.name)
