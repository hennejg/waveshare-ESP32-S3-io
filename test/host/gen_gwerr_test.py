#!/usr/bin/env python3
"""Builds a host test for what the RS-485 gateway reports when a transaction
fails (mb_gateway.c).

transact(), the request handlers and mb_gateway_handle() are cut out of
mb_gateway.c verbatim; the esp-modbus master and the segment lock are stubs.

What it pins down, found by a review:
  - a garbled answer (bad CRC, wrong address, wrong length; esp-modbus says
    ESP_ERR_INVALID_RESPONSE) went out as 0x0A "gateway path unavailable",
    which clients read as a routing fault and stop retrying. It is 0x0B now,
    like a device that stayed silent;
  - a segment that never came free went out as 0x06 to the poll table too,
    which then reported "device says exception 0x06" and backed the device
    off though it never said anything. The poll table now gets a code of its
    own; on the wire it stays 0x06.
OLD=1 cuts mb_gateway.c from git (OLDREV, default HEAD).

  make -C test/host gwerr
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("components/modbus/mb_gateway.c")
hdr  = Source.at("components/modbus/mb_gateway.h")
busy = hdr.defines("MB_GW_BUS_BUSY") if "MB_GW_BUS_BUSY" in hdr.text else "#define MB_GW_BUS_BUSY 0x06  /* old: no code of its own */\n"
cuts = src.text[src.text.index("static uint8_t transact("):]

HARNESS = r"""
/* GENERATED by gen_gwerr_test.py -- do not edit; edit mb_gateway.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "esp_err.h"
#include "mb_pdu.h"
#define ESP_ERR_TIMEOUT          0x107
#define ESP_ERR_INVALID_RESPONSE 0x108
#define TAG "t"
#define PRIu32 "u"
#define ESP_LOGW(...) ((void)0)
#define ESP_LOGD(...) ((void)0)
#define pdTRUE 1
#define pdMS_TO_TICKS(x) (x)
__BUSY__
typedef void *SemaphoreHandle_t;
typedef struct { uint8_t slave_addr, command; uint16_t reg_start, reg_size; } mb_param_request_t;
static int  lock_free = 1;
static int  xSemaphoreTake(SemaphoreHandle_t s, int t) { (void)s; (void)t; return lock_free; }
static void xSemaphoreGive(SemaphoreHandle_t s) { (void)s; }
static esp_err_t next_err; static uint8_t next_exc;
static esp_err_t mbc_master_send_request(void *m, mb_param_request_t *r, void *d) { (void)m; (void)r; (void)d; return next_err; }
static esp_err_t mbc_master_get_last_exception(void *m, uint8_t *e) { (void)m; *e = next_exc; return ESP_OK; }
static void *s_master = (void *)1;
static SemaphoreHandle_t s_bus;
static uint32_t s_bus_wait_ms = 4000;

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

int main(void)
{
    printf("Fehlercodes des RS-485-Gateways\n");
    mb_request_t rq = { .fc = MB_FC_READ_HOLDING, .addr = 0, .count = 2 };
    uint8_t resp[8]; uint16_t len; uint16_t regs[2];

    next_err = ESP_ERR_INVALID_RESPONSE; next_exc = 0;
    uint8_t w = mb_gateway_handle(11, &rq, resp, &len);
    CHECK(w == MB_EXC_GW_TARGET, "verstuemmelte Antwort: 0x%02X auf der Leitung statt 0x0B", w);
    printf("  verstuemmelte Antwort: 0x%02X\n", w);

    next_err = ESP_ERR_TIMEOUT;
    w = mb_gateway_handle(11, &rq, resp, &len);
    CHECK(w == MB_EXC_GW_TARGET, "keine Antwort: 0x%02X statt 0x0B", w);

    next_err = ESP_FAIL; next_exc = MB_EXC_ILLEGAL_ADDR;
    w = mb_gateway_handle(11, &rq, resp, &len);
    CHECK(w == MB_EXC_ILLEGAL_ADDR, "Ausnahme des Geraets nicht durchgereicht: 0x%02X", w);

    next_err = ESP_ERR_INVALID_STATE; next_exc = 0;
    w = mb_gateway_handle(11, &rq, resp, &len);
    CHECK(w == MB_EXC_GW_PATH, "Gateway nicht bereit: 0x%02X statt 0x0A", w);

    lock_free = 0;
    w = mb_gateway_handle(11, &rq, resp, &len);
    CHECK(w == MB_EXC_DEVICE_BUSY, "Bus belegt: 0x%02X auf der Leitung statt 0x06", w);
    uint8_t p = mb_gateway_read_regs(11, MB_FC_READ_HOLDING, 0, 2, regs);
    CHECK(p != MB_EXC_DEVICE_BUSY && p == MB_GW_BUS_BUSY, "Bus belegt: Poll-Tabelle bekommt 0x%02X wie eine Ausnahme des Geraets", p);
    printf("  Bus belegt: Leitung 0x%02X, Poll-Tabelle 0x%02X\n", w, p);

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_gwerr.c")
out.write_text(HARNESS.replace("__BUSY__", busy).replace("__CUT__", cuts))
print("erzeugt:", out.name)
