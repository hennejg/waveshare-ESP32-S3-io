#!/usr/bin/env python3
"""Builds a host test for the header pads' status getters against a mode
change (components/board/aux_io.c).

Cut out verbatim: the pad state and the getters aux_io_mode(),
aux_io_out_get(), aux_io_pwm_actual_hz() and aux_io_status(). The lock is
a pthread mutex; a writer thread changes a pad's mode under it the way
aux_io_apply() does -- the old mode left first (an output switched off),
the new one entered after -- while readers ask for the pad's status.

What it pins down, found by an outside review: the getters read s_mode
and s_out without the lock, so a status query beside a mode change could
pair the mode with a state from the middle of the change -- an output
reported off that was on before and after, because leave() had already
cleared it while the mode was still "output".
OLD=1 cuts aux_io.c from git (OLDREV, default HEAD); the old status is
put together as web_server.c did, from aux_io_mode() and aux_io_out_get().

  make -C test/host auxlock
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
old  = os.environ.get("OLD") == "1"
aux  = Source(ROOT / "components/board/aux_io.c")
if old:
    aux.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":components/board/aux_io.c"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout

cuts  = aux.defines("PWM_MODE", "PWM_TIMER")
cuts += aux.span("static SemaphoreHandle_t s_mux;", "static bool                      s_an_valid;")
cuts += aux.func("bool aux_io_out_get(uint8_t a, bool *on)\n{")
cuts += aux.func("aux_mode_t aux_io_mode(uint8_t a)\n{")
cuts += aux.func("uint32_t aux_io_pwm_actual_hz(uint8_t a)\n{")
if not old:
    cuts += aux.func("void aux_io_status(uint8_t a, aux_status_t *st)\n{")

HARNESS = r"""
/* GENERATED by gen_auxlock_test.py -- do not edit; edit aux_io.c. */
#include <pthread.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "esp_err.h"
#include "aux_io.h"
__OLD__
typedef pthread_mutex_t *SemaphoreHandle_t;
#define portMAX_DELAY 0
#define xSemaphoreTake(m, t) pthread_mutex_lock(m)
#define xSemaphoreGive(m)    pthread_mutex_unlock(m)
typedef void *adc_oneshot_unit_handle_t;
typedef void *adc_cali_handle_t;
#define LEDC_LOW_SPEED_MODE 0
#define LEDC_TIMER_1 1
typedef int ledc_timer_t;
static uint32_t ledc_get_freq(int mode, ledc_timer_t t) { (void)mode; (void)t; return 1000; }

__CUT__

static pthread_mutex_t lock = PTHREAD_MUTEX_INITIALIZER;
static int stop;

/* aux_io_apply() switching pad 0 between output (on) and PWM, as enter()
   and leave() do: under the lock, the old mode left first, the new one
   entered after. */
static void *writer(void *arg)
{
    (void)arg;
    for (int i = 0; i < 20000; i++) {
        pthread_mutex_lock(&lock);
        if (s_mode[0] == AUX_MODE_OUTPUT) {
            s_out[0] = false;                                   /* leave(): off first */
            for (volatile int k = 0; k < 200; k++) {}
            s_freq[0] = 1000; s_mode[0] = AUX_MODE_PWM;         /* enter(PWM)        */
        } else {
            s_freq[0] = 0;                                      /* leave(PWM)        */
            for (volatile int k = 0; k < 200; k++) {}
            s_mode[0] = AUX_MODE_OUTPUT; s_out[0] = true;       /* enter(): on       */
        }
        pthread_mutex_unlock(&lock);
    }
    __atomic_store_n(&stop, 1, __ATOMIC_RELAXED);
    return NULL;
}

static long reads, torn;
static void *reader(void *arg)
{
    (void)arg;
    while (!__atomic_load_n(&stop, __ATOMIC_RELAXED)) {
#ifdef OLD_CODE
        aux_mode_t m = aux_io_mode(0);                          /* as web_server.c did */
        bool on = false, out = (m == AUX_MODE_OUTPUT) && aux_io_out_get(0, &on);
        if (out && !on) __atomic_fetch_add(&torn, 1, __ATOMIC_RELAXED);
#else
        aux_status_t st;
        aux_io_status(0, &st);
        if (st.mode == AUX_MODE_OUTPUT && !st.out) __atomic_fetch_add(&torn, 1, __ATOMIC_RELAXED);
        if (st.mode == AUX_MODE_PWM && st.freq_hz != 1000) __atomic_fetch_add(&torn, 1, __ATOMIC_RELAXED);
        bool on = false;
        if (aux_io_out_get(0, &on) && !on) __atomic_fetch_add(&torn, 1, __ATOMIC_RELAXED);
#endif
        __atomic_fetch_add(&reads, 1, __ATOMIC_RELAXED);
    }
    return NULL;
}

int main(void)
{
    printf("AUX-Statusabfragen waehrend eines Moduswechsels\n");
    s_mux = &lock;
    s_mode[0] = AUX_MODE_OUTPUT; s_out[0] = true;
    pthread_t w, r[2];
    pthread_create(&r[0], NULL, reader, NULL);
    pthread_create(&r[1], NULL, reader, NULL);
    pthread_create(&w, NULL, writer, NULL);
    pthread_join(w, NULL); pthread_join(r[0], NULL); pthread_join(r[1], NULL);
    (void)aux_io_pwm_actual_hz(0);
    printf("  %ld Abfragen, %ld mit Zwischenstand (Ausgang \"aus\" mitten im Wechsel)\n", reads, torn);
    int failures = torn != 0;
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures;
}
"""
out = pathlib.Path(__file__).with_name("test_auxlock.c")
out.write_text(HARNESS.replace("__CUT__", cuts).replace("__OLD__", "#define OLD_CODE 1" if old else ""))
print("erzeugt:", out.name)
