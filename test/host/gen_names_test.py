#!/usr/bin/env python3
"""Builds a host test for the I/O names as MQTT topic fragments (app_config.c).

The checks are cut out of app_config.c verbatim. What they pin down, both
found by an outside review:
  - an output called "set" published its state on output/set, the bulk
    command every output listens to: with the broker's echo DO1 on switched
    all eight on;
  - DO1 called "2" next to an unnamed DO2: both subscribed output/2/set and
    the handler only ever switched DO1.
And a stored configuration from before the check is cleaned up on load.
Later review: a name cut at 20 bytes inside a UTF-8 character was stored,
and made a topic the broker closes the connection over -- names must be
UTF-8 (refused on save, dropped on load).

  make -C test/host names
"""
import pathlib
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
src  = Source.at("components/board/app_config.c")
cuts = src.span("#define IO_SPACE_MAX", "    io_space_normalize(&out);\n}")

HARNESS = r"""
/* GENERATED by gen_names_test.py -- do not edit; edit app_config.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define APP_CFG_DI_COUNT     11
#define APP_CFG_DO_COUNT      8
#define APP_CFG_IO_NAME_MAX  20
typedef struct { bool invert; char name[APP_CFG_IO_NAME_MAX + 1]; } di_config_t;
typedef struct { di_config_t di[APP_CFG_DI_COUNT], dout[APP_CFG_DO_COUNT], aux_out[3]; } app_config_t;
#define ESP_LOGW(tag, ...) do { printf("    log: "); printf(__VA_ARGS__); printf("\n"); } while (0)
#define TAG "t"
static size_t strlcpy_(char *d, const char *s, size_t n)
{ size_t l = strlen(s); if (n) { size_t k = l < n - 1 ? l : n - 1; memcpy(d, s, k); d[k] = 0; } return l; }
#define strlcpy strlcpy_

__CUT__

static int failures;
static void expect(const char *label, app_config_t *c, bool want)
{
    const char *err = "";
    bool ok = app_config_io_names_ok(c, &err);
    printf("  %-44s %s%s%s\n", label, ok ? "ok" : "abgelehnt", ok ? "" : ": ", ok ? "" : err);
    if (ok != want) { failures++; printf("  FEHLER: erwartet %s\n", want ? "ok" : "abgelehnt"); }
}

int main(void)
{
    app_config_t c;
#define FRESH() memset(&c, 0, sizeof c)
    FRESH();                                         expect("alles unbenannt", &c, true);
    FRESH(); strcpy(c.dout[0].name, "set");          expect("DO1 'set'", &c, false);
    FRESH(); strcpy(c.dout[0].name, "read");         expect("DO1 'read'", &c, false);
    FRESH(); strcpy(c.aux_out[1].name, "set");       expect("Pad-Ausgang 'set'", &c, false);
    FRESH(); strcpy(c.di[3].name, "read");           expect("DI4 'read'", &c, false);
    FRESH(); strcpy(c.di[3].name, "set");            expect("DI4 'set' (kein Eingangsbefehl)", &c, true);
    FRESH(); strcpy(c.dout[0].name, "2");            expect("DO1 '2', DO2 unbenannt", &c, false);
    FRESH(); strcpy(c.dout[0].name, "2"); strcpy(c.dout[1].name, "x");
                                                     expect("DO1 '2', DO2 'x'", &c, true);
    FRESH(); strcpy(c.dout[2].name, "9");            expect("DO3 '9', Pad 9 unbenannt", &c, false);
    FRESH(); strcpy(c.di[0].name, "11");             expect("DI1 '11', Pad-Eingang 11 unbenannt", &c, false);
    FRESH(); strcpy(c.di[0].name, "a"); strcpy(c.di[1].name, "a");
                                                     expect("DI1 und DI2 'a'", &c, false);
    FRESH(); strcpy(c.di[0].name, "a"); strcpy(c.dout[0].name, "a");
                                                     expect("DI1 und DO1 'a' (andere Topics)", &c, true);
    FRESH(); strcpy(c.dout[0].name, "a+b");          expect("DO1 'a+b'", &c, false);
    FRESH(); strcpy(c.dout[0].name, "#");            expect("DO1 '#'", &c, false);
    FRESH(); strcpy(c.dout[0].name, "a/b");          expect("DO1 'a/b'", &c, false);
    FRESH(); strcpy(c.di[0].name, "Gr\xc3\xb6\xc3\x9f" "e"); expect("DI1 mit Umlaut (UTF-8)", &c, true);
    FRESH(); strcpy(c.di[0].name, "Wohnzimmer\xc3");  expect("DI1 endet mitten im Zeichen", &c, false);
    FRESH(); strcpy(c.di[0].name, "\xc0\xaf");       expect("DI1 ueberlange Kodierung", &c, false);

    printf("  Bereinigung beim Laden:\n");
    FRESH(); strcpy(c.dout[0].name, "set"); strcpy(c.dout[1].name, "1"); strcpy(c.dout[4].name, "pump");
    io_names_normalize(&c);
    expect("DO1 'set', DO2 '1' -> bereinigt", &c, true);
    if (c.dout[0].name[0] || c.dout[1].name[0] || strcmp(c.dout[4].name, "pump"))
        { failures++; printf("  FEHLER: DO1 '%s', DO2 '%s', DO5 '%s'\n", c.dout[0].name, c.dout[1].name, c.dout[4].name); }
    FRESH(); strcpy(c.dout[0].name, "2");
    io_names_normalize(&c);
    expect("DO1 '2' -> bereinigt", &c, true);
    FRESH(); strcpy(c.dout[3].name, "ab\xc3");
    io_names_normalize(&c);
    expect("DO4 kaputtes UTF-8 -> bereinigt", &c, true);

    printf(failures ? "names: %d FEHLER\n" : "names: alles OK\n", failures);
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_names.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
