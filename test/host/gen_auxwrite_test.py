#!/usr/bin/env python3
"""Builds a host test for Modbus writes to several header pads at once
(apps/full/main/mb_server.c, components/board/aux_io.c).

Cut out verbatim: local_write_coils(), plan_pwm(), local_write_holding()
and the register layout from mb_server.c; the pad state and the pad
accessors from aux_io.c. The LEDC and GPIO calls are stubs; the pad
driver's lock is a counter whose release can run "the HTTP task" -- a
configuration save that changes a pad's mode -- the way another task
would get the lock in between.

What it pins down, found by an outside review: an FC 15 to coils 9-11 or
an FC 16 to the PWM registers checked every pad first and then set them
one by one, each call taking the lock on its own. A mode changed between
two of them switched the first pads, refused the next, and answered with
an exception -- although a refused request is meant to have changed
nothing.
OLD=1 cuts both files from git (OLDREV, default HEAD).

  make -C test/host auxwrite
"""
import os, pathlib, subprocess
from cutter import Source

ROOT = pathlib.Path(__file__).resolve().parents[2]
old  = os.environ.get("OLD") == "1"
def source(rel):
    s = Source(ROOT / rel)
    if old:
        s.text = subprocess.run(["git", "show", os.environ.get("OLDREV", "HEAD") + ":" + rel],
                                cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return s
mb  = source("apps/full/main/mb_server.c")
aux = source("components/board/aux_io.c")

cuts  = aux.span("static SemaphoreHandle_t s_mux;", "static bool              s_out_inv[AUX_PAD_COUNT];")
for sig in ("esp_err_t aux_io_out_set(uint8_t a, bool on)\n{",
            "bool aux_io_out_get(uint8_t a, bool *on)\n{",
            "esp_err_t aux_io_pwm_set(uint8_t a, uint32_t freq_hz, uint16_t duty_pm)\n{",
            "bool aux_io_pwm_info(uint8_t a, uint32_t *freq_hz, uint16_t *duty_pm, uint8_t *bits)\n{"):
    cuts += aux.func(sig)
if not old:
    cuts += aux.func("esp_err_t aux_io_out_set_many(uint8_t mask, uint8_t on)\n{")
    cuts += aux.func("esp_err_t aux_io_pwm_write(const aux_pwm_write_t w[AUX_PAD_COUNT])\n{")
mbcuts  = mb.defines("MB_NUM_DO", "MB_NUM_COILS", "MB_HR_BASE", "MB_HR_PER_PAD", "MB_NUM_HOLDING")
mbcuts += mb.type("} mb_cmd_t;")
mbcuts += "__MBSTATE__\n"
mbcuts += mb.func("static uint8_t local_write_coils(uint16_t addr, uint16_t count, const uint8_t *bits)")
if old:
    mbcuts += mb.span("typedef struct { bool touched, has_duty", "} pwm_req_t;")
mbcuts += mb.func("static uint8_t plan_pwm(")
mbcuts += mb.func("static uint8_t local_write_holding(uint16_t addr, uint16_t count, const uint8_t *regs_be)")

HARNESS = r"""
/* GENERATED by gen_auxwrite_test.py -- do not edit; edit the firmware. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "esp_err.h"
#include "mb_pdu.h"
#include "aux_io.h"

#define APP_CFG_DI_AUX_COUNT 3
#define TAG "t"
#define ESP_LOGW(t, ...) ((void)(t))
#define portMAX_DELAY 0
#define MB_PARAM_COIL 0
#define MB_PARAM_HOLDING 1
uint16_t mb_be16(const uint8_t *p) { return (uint16_t)((p[0] << 8) | p[1]); }

/* The pad driver's lock. Released, it may let "the HTTP task" in: a
   configuration save that puts pad apply_pad into input mode, once, at the
   apply_at-th release during a request. */
typedef int *SemaphoreHandle_t;
static int held, gives, apply_at = -1, apply_pad;
static void http_save(void);
static void xSemaphoreTake(SemaphoreHandle_t m, int t) { (void)m; (void)t; held++; }
static void xSemaphoreGive(SemaphoreHandle_t m)
{ (void)m; held--; if (++gives == apply_at) http_save(); }

/* The rest of the pad driver: stubs that record. */
static int dirty_n, pwm_calls, pwm_fail_pad = -1;
static void mark_dirty(uint8_t a) { (void)a; dirty_n++; }
static void out_drive(uint8_t a) { (void)a; }
static esp_err_t pwm_set(uint8_t a, uint32_t freq, uint16_t duty, bool fresh);

__AUX__

static esp_err_t pwm_set(uint8_t a, uint32_t freq, uint16_t duty, bool fresh)
{
    (void)fresh; pwm_calls++;
    if (a == pwm_fail_pad) return ESP_FAIL;
    s_freq[a] = freq; s_duty[a] = duty;
    return ESP_OK;
}
static void http_save(void) { s_mode[apply_pad] = AUX_MODE_INPUT; s_out[apply_pad] = false; }

/* mb_server.c's surroundings. */
static bool s_local_ready = true;
typedef void *QueueHandle_t;
static QueueHandle_t s_cmd_q;
static int uxQueueSpacesAvailable(QueueHandle_t q) { (void)q; return 8; }
#define CMD_LOCK()   ((void)0)
#define CMD_UNLOCK() ((void)0)
static int activity;
static void scripting_on_modbus_activity(void) { activity++; }

__MB__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static void reset(aux_mode_t m)
{
    for (int a = 0; a < 3; a++) { s_mode[a] = m; s_out[a] = false; s_freq[a] = 1000; s_duty[a] = 100; }
    s_mux = &held; held = 0; gives = 0; apply_at = -1; pwm_fail_pad = -1;
}

int main(void)
{
    printf("Modbus-Schreibzugriffe auf mehrere Pads\n");
    for (int k = 1; k <= 4; k++) {
        /* FC 15: coils 9-11 (addr 8..10) all on; a save puts pad 2 into
           input mode at the k-th release of the pad lock. */
        reset(AUX_MODE_OUTPUT);
        apply_at = k; apply_pad = 2;
        uint8_t bits = 0x07;
        uint8_t exc = local_write_coils(8, 3, &bits);
        int on = s_out[0] + s_out[1];
        if (exc == MB_EXC_NONE)
            CHECK(on == 2, "FC15 (Speichern nach Freigabe %d): ok, aber nur %d von 2 Pads gesetzt", k, on);
        else
            CHECK(on == 0, "FC15 (Speichern nach Freigabe %d): Ausnahme 0x%02X, aber %d Pads geschaltet", k, exc, on);
        CHECK(held == 0, "Sperre nicht freigegeben");
    }
    printf("  FC 15 an Spule 9-11: ganz oder gar nicht, wann immer die Konfiguration dazwischenkommt\n");

    for (int k = 1; k <= 5; k++) {
        /* FC 16: duty of pads 1 and 3 (regs 2 and 8); pad 3 leaves PWM at
           the k-th release. */
        reset(AUX_MODE_PWM);
        apply_at = k; apply_pad = 2;
        /* regs 2..8: pad 1 duty 50.0 % at 1000 Hz, pad 2 as it is, pad 3 duty 50.0 % */
        uint8_t regs[7 * 2] = { 0x01, 0xF4, 0x00, 0x00, 0x03, 0xE8,
                                0x00, 0x64, 0x00, 0x00, 0x03, 0xE8, 0x01, 0xF4 };
        uint8_t exc = local_write_holding(2, 7, regs);
        int ch = (s_duty[0] == 500) + (s_duty[2] == 500);
        if (exc == MB_EXC_NONE)
            CHECK(ch == 2, "FC16 (Speichern nach Freigabe %d): ok, aber nur %d von 2 Pads geaendert", k, ch);
        else
            CHECK(ch == 0, "FC16 (Speichern nach Freigabe %d): Ausnahme 0x%02X, aber %d Pads geaendert", k, exc, ch);
        CHECK(held == 0, "Sperre nicht freigegeben");
    }
    printf("  FC 16 an PWM-Register: ganz oder gar nicht\n");

    /* The LEDC driver refuses the second pad: the first is put back. */
    reset(AUX_MODE_PWM);
    pwm_fail_pad = 2;
    uint8_t regs[7 * 2] = { 0x01, 0xF4, 0x00, 0x00, 0x03, 0xE8,
                            0x00, 0x64, 0x00, 0x00, 0x03, 0xE8, 0x01, 0xF4 };
    uint8_t exc = local_write_holding(2, 7, regs);
    CHECK(exc == MB_EXC_DEVICE_FAILURE, "LEDC-Fehler: Ausnahme 0x%02X statt 0x04", exc);
    CHECK(s_duty[0] == 100, "LEDC-Fehler am zweiten Pad: erster Pad bleibt geaendert (%u)", s_duty[0]);
    printf("  LEDC verweigert ein Pad: die schon geaenderten werden zurueckgesetzt\n");

    /* Plain cases still work. */
    reset(AUX_MODE_OUTPUT);
    uint8_t b = 0x05;
    CHECK(local_write_coils(8, 3, &b) == MB_EXC_NONE && s_out[0] && !s_out[1] && s_out[2], "FC15 normal");
    reset(AUX_MODE_PWM); s_mode[1] = AUX_MODE_INPUT;
    CHECK(local_write_holding(2, 7, regs) == MB_EXC_ILLEGAL_VALUE && s_duty[0] == 100, "FC16 auf Nicht-PWM-Pad");
    reset(AUX_MODE_PWM);
    uint8_t fr[2 * 2] = { 0x00, 0x00, 0x07, 0xD0 };   /* regs 3,4: 2000 Hz in one step */
    CHECK(local_write_holding(3, 2, fr) == MB_EXC_NONE && s_freq[0] == 2000 && s_duty[0] == 100, "FC16 Frequenz");
    uint8_t lo[2] = { 0x0B, 0xB8 };                      /* reg 4 alone: low word 3000 */
    CHECK(local_write_holding(4, 1, lo) == MB_EXC_NONE && s_freq[0] == 3000, "FC16 nur Low-Word");
    uint8_t bad[2] = { 0x03, 0xE9 };                     /* duty 1001 */
    CHECK(local_write_holding(2, 1, bad) == MB_EXC_ILLEGAL_VALUE && s_duty[0] == 100, "Duty > 100 %%");
    printf("  Normalfaelle unveraendert\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_auxwrite.c")
MBSTATE = """static uint16_t s_hr_shadow[MB_NUM_HOLDING];
static uint8_t  s_do_shadow;
static uint8_t  s_do_pending[MB_NUM_COILS];
static uint8_t enqueue(const mb_cmd_t *cmd, const char *what) { (void)cmd; (void)what; return MB_EXC_NONE; }"""
out.write_text(HARNESS.replace("__AUX__", cuts).replace("__MB__", mbcuts).replace("__MBSTATE__", MBSTATE))
print("erzeugt:", out.name)
