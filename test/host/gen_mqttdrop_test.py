#!/usr/bin/env python3
"""Builds a host test for MQTT messages too long for the rule engine
(scripting.c).

scripting_on_mqtt_message() is cut out of scripting.c verbatim, with the
event type and its limits; evt_send() records what would reach the rules.

What it pins down, found by a review: a topic over 127 or a payload over
255 bytes was cut to fit and delivered. A cut topic can equal a shorter one
and fire that topic's rules; a cut payload is a different value -- half a
JSON object, a number missing digits. Now such a message is dropped, with a
warning, and one that fits arrives whole.
OLD=1 cuts scripting.c from git (OLDREV, default HEAD).

  make -C test/host mqttdrop
"""
import pathlib
from cutter import Source

src = Source.at("components/scripting/scripting.c")
defines = src.defines("MAX_TOPIC_LEN", "MAX_PAYLOAD_LEN")
types = src.type("EVT_ACTIVITY, EVT_TZ_CHANGE, EVT_ANALOG } evt_type_t;") + src.type("} scripting_evt_t;")
cuts = src.func("void scripting_on_mqtt_message(const char *topic, size_t tlen,")

HARNESS = r"""
/* GENERATED by gen_mqttdrop_test.py -- do not edit; edit scripting.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#define TAG "t"
#define ESP_LOGW(...) ((void)0)
#define pdTRUE 1
typedef void (*scripting_store_fn_t)(const char *);
typedef void *QueueHandle_t;
static int q;
static QueueHandle_t s_queue = &q;
__DEFINES__
__TYPES__
static int delivered;
static char got_topic[512], got_payload[1024];
static int evt_send(const scripting_evt_t *ev)
{ delivered++; strcpy(got_topic, ev->mqtt.topic); strcpy(got_payload, ev->mqtt.payload); return pdTRUE; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("MQTT-Nachrichten an der Laengengrenze der Regel-Engine\n");
    char topic[300], payload[600];

    /* The longest that fits arrives whole. */
    memset(topic, 't', MAX_TOPIC_LEN - 1); topic[MAX_TOPIC_LEN - 1] = 0;
    memset(payload, 'p', MAX_PAYLOAD_LEN - 1); payload[MAX_PAYLOAD_LEN - 1] = 0;
    delivered = 0;
    scripting_on_mqtt_message(topic, strlen(topic), payload, strlen(payload));
    CHECK(delivered == 1 && !strcmp(got_topic, topic) && !strcmp(got_payload, payload), "groesste passende Nachricht nicht ganz zugestellt");

    /* One byte over: cut, it would be a different topic. */
    memset(topic, 'a', MAX_TOPIC_LEN); topic[MAX_TOPIC_LEN] = 0;
    delivered = 0;
    scripting_on_mqtt_message(topic, strlen(topic), "1", 1);
    CHECK(delivered == 0, "Topic mit %zu Byte gekuerzt zugestellt (als %zu Byte)", strlen(topic), strlen(got_topic));

    memcpy(payload, "{\"v\":", 5); memset(payload + 5, '1', MAX_PAYLOAD_LEN); strcpy(payload + 5 + MAX_PAYLOAD_LEN, "}");
    delivered = 0;
    scripting_on_mqtt_message("rules/x", 7, payload, strlen(payload));
    CHECK(delivered == 0, "Payload mit %zu Byte gekuerzt zugestellt (als %zu Byte)", strlen(payload), strlen(got_payload));
    if (!failures) printf("  zu lange Nachrichten werden verworfen, passende kommen ganz an\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqttdrop.c")
out.write_text(HARNESS.replace("__DEFINES__", defines).replace("__TYPES__", types).replace("__CUT__", cuts))
print("erzeugt:", out.name)
