#!/usr/bin/env python3
"""Builds a host test for the poll table's values as Matter sensors
(apps/matter/main/mbm_value.c, matter_mbm.cpp) and the Modbus pieces the
Matter firmware relies on (components/board/web_common.c,
components/modbus/mb_gateway.c).

Cut out verbatim: mbm_matter_value(), row_is_sensor() and
matter_mbm_endpoints_differ(), web_mbm_config_parse() with its helpers, and
mb_gateway_set_forwarding() as built without CONFIG_MB_GATEWAY. cJSON is
ESP-IDF's own.

What it pins down, new with the RS-485 master in the Matter firmware:
  - a value reaches its Matter attribute in that attribute's unit, rounded,
    and a value the attribute cannot carry is not reported at all rather
    than clamped (a meter at the end of its range would read plausible);
  - the table refuses rows for network devices in a firmware without a
    Modbus TCP master, and stores the Matter type per row; an unknown type
    is a bad field, not "none";
  - only a change to the set of sensor endpoints asks for a reboot -- a
    changed register or scale does not, Modbus switched off or the board
    back to slave does;
  - without the gateway in the build a stored "gateway" never forwards.
OLD=1 cuts the files from git (OLDREV, default HEAD); before this change
mbm_value.c did not exist, so the generator stops there.

  make -C test/host mbmmatter
"""
import pathlib, subprocess, sys
from cutter import Source

try:
    val = Source.at("apps/matter/main/mbm_value.c")
except subprocess.CalledProcessError:
    sys.exit("FEHLER: mbm_value.c fehlt -- Modbus-Werte haben keinen Matter-Endpoint")
mm  = Source.at("apps/matter/main/matter_mbm.cpp")
wc  = Source.at("components/board/web_common.c")
wh  = Source.at("components/board/web_common.h")
cfg = Source.at("components/board/app_config.c")
gw  = Source.at("components/modbus/mb_gateway.c")

cuts = (cfg.func("bool app_config_utf8_ok(const char *s)")
        + wc.func("bool web_json_uint(const cJSON *v, uint32_t lo, uint32_t hi, uint32_t *out)")
        + wh.span("typedef struct { char field[40]; } web_cfg_err_t;", "typedef struct { char field[40]; } web_cfg_err_t;")
        + wc.func("void web_cfg_bad(web_cfg_err_t *bad, const char *where, const char *key)")
        + wc.func("bool web_cfg_uint(const cJSON *obj, const char *where, const char *key,")
        + wc.func("bool web_cfg_str(const cJSON *obj, const char *where, const char *key,")
        + wc.span("static const struct { const char *name; uint8_t type; } k_mbm_types[] = {", "};")
        + (wc.func("static bool mbm_type_value(const char *s, uint8_t *out)")
                + wc.func("static bool mbm_word(const cJSON *o, const char *where, const char *key,")
                if "static bool mbm_word(" in wc.text else wc.func("static void mbm_type_value(const char *s, uint8_t *out)"))
        + wc.span("static const char *const k_mbm_matter[MBM_MATTER_MAX + 1] = {", "};")
        + wc.func("const char *web_mbm_config_parse(const cJSON *mbm_j, app_config_t *cfg,")
        + val.func("bool mbm_matter_value(uint8_t kind, double v, int64_t *out)")
        + mm.func("bool row_is_sensor(const app_config_t *cfg, int i)")
        + mm.func("bool matter_mbm_endpoints_differ(const app_config_t *a, const app_config_t *b)")
        + gw.span("#if CONFIG_MB_GATEWAY\nvoid mb_gateway_set_forwarding(bool on)", "#endif"))

HARNESS = r"""
/* GENERATED by gen_mbmmatter_test.py -- do not edit; edit the firmware. */
#include <math.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include "cJSON.h"
#include "app_config.h"

/* CONFIG_MB_GATEWAY is not defined: the Matter firmware's build. */
static bool  s_forwarding;
static void *s_master = (void *)1;
static bool  forwarding(void) { return s_forwarding && s_master != NULL; }

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static int64_t conv(uint8_t k, double v, bool *ok) { int64_t o = -1; *ok = mbm_matter_value(k, v, &o); return o; }

static const char *parse(app_config_t *c, const char *json, web_cfg_err_t *bad)
{
    cJSON *a = cJSON_Parse(json);
    const char *why = web_mbm_config_parse(a, c, false, bad);
    cJSON_Delete(a);
    return why;
}

#define ROW(en, tr, matter) "{\"enable\":" #en ",\"name\":\"zaehler\",\"transport\":\"" tr "\",\"host\":\"10.0.0.5\"," \
                            "\"unit_id\":12,\"fc\":\"input\",\"reg\":70,\"type\":\"f32\",\"scale\":1,\"interval_ms\":1000," \
                            "\"matter\":\"" matter "\"}"

int main(void)
{
    bool ok;
    printf("Modbus-Werte als Matter-Sensoren\n");

    int f0 = failures;
    CHECK(conv(MBM_MATTER_TEMPERATURE, 21.456, &ok) == 2146 && ok, "21,456 degC -> %lld", (long long)conv(MBM_MATTER_TEMPERATURE, 21.456, &ok));
    CHECK(conv(MBM_MATTER_TEMPERATURE, -273.15, &ok) == -27315 && ok, "-273,15 degC nicht angenommen");
    conv(MBM_MATTER_TEMPERATURE, -273.2, &ok);   CHECK(!ok, "-273,2 degC angenommen");
    conv(MBM_MATTER_TEMPERATURE, 327.675, &ok);  CHECK(!ok, "327,675 degC (gerundet 32768) angenommen");
    CHECK(conv(MBM_MATTER_HUMIDITY, 55.5, &ok) == 5550 && ok, "55,5 %% -> falsch");
    conv(MBM_MATTER_HUMIDITY, 100.01, &ok);      CHECK(!ok, "100,01 %% angenommen");
    conv(MBM_MATTER_HUMIDITY, -1, &ok);          CHECK(!ok, "-1 %% angenommen");
    CHECK(conv(MBM_MATTER_PRESSURE, 1013.25, &ok) == 1013 && ok, "1013,25 hPa -> falsch");
    CHECK(conv(MBM_MATTER_FLOW, 12.34, &ok) == 123 && ok, "12,34 m3/h -> falsch");
    conv(MBM_MATTER_FLOW, -0.1, &ok);            CHECK(!ok, "-0,1 m3/h angenommen");
    CHECK(conv(MBM_MATTER_POWER, -1500.5, &ok) == -1500500 && ok, "-1500,5 W -> falsch");
    CHECK(conv(MBM_MATTER_ENERGY, 12345.678, &ok) == 12345678000LL && ok, "12345,678 kWh -> %lld", (long long)conv(MBM_MATTER_ENERGY, 12345.678, &ok));
    conv(MBM_MATTER_ENERGY, -0.001, &ok);        CHECK(!ok, "negative Energie angenommen");
    conv(MBM_MATTER_POWER, NAN, &ok);            CHECK(!ok, "NaN angenommen");
    conv(MBM_MATTER_POWER, 1e17, &ok);           CHECK(!ok, "1e17 W (ueber 2^62 mW) angenommen");
    conv(MBM_MATTER_NONE, 1, &ok);               CHECK(!ok, "Typ none ergibt einen Wert");
    conv(99, 1, &ok);                            CHECK(!ok, "unbekannter Typ ergibt einen Wert");
    if (failures == f0) printf("  Einheiten, Rundung und Grenzen der Matter-Attribute\n");

    f0 = failures;
    app_config_t c; memset(&c, 0, sizeof c);
    web_cfg_err_t bad = { "" };
    const char *why = parse(&c, "[" ROW(true, "rtu", "power") "]", &bad);
    CHECK(!why && !bad.field[0] && c.mbm[0].matter == MBM_MATTER_POWER && c.mbm[0].transport == MBM_TRANSPORT_RTU,
          "RS-485-Zeile mit power: %s %s matter=%u", why ? why : "-", bad.field, c.mbm[0].matter);
    why = parse(&c, "[" ROW(true, "tcp", "none") "]", &bad);
    CHECK(why && strstr(why, "RS-485"), "Netzwerk-Zeile angenommen: %s", why ? why : "-");
    why = parse(&c, "[" ROW(false, "tcp", "none") "]", &bad);
    CHECK(!why, "abgeschaltete Netzwerk-Zeile abgewiesen: %s", why ? why : "-");
    memset(&bad, 0, sizeof bad);
    why = parse(&c, "[" ROW(true, "rtu", "lux") "]", &bad);
    CHECK(!why && !strcmp(bad.field, "mbm.1.matter"), "unbekannter Typ: Feld '%s'", bad.field);
    memset(&bad, 0, sizeof bad);
    parse(&c, "[{\"enable\":false},{\"enable\":true,\"name\":\"t\",\"transport\":\"rtu\",\"matter\":\"temperature\"}]", &bad);
    CHECK(c.mbm[0].matter == MBM_MATTER_NONE && c.mbm[1].matter == MBM_MATTER_TEMPERATURE, "Typ je Zeile: %u %u",
          c.mbm[0].matter, c.mbm[1].matter);
    if (failures == f0) printf("  Tabelle: nur RS-485-Zeilen, Matter-Typ je Zeile, unbekannter Typ abgewiesen\n");

    f0 = failures;
    app_config_t a, b; memset(&a, 0, sizeof a);
    a.modbus.enable = 1; a.modbus.rs485_role = MB_ROLE_MASTER;
    a.mbm[0] = (mbm_poll_t){ .enable = 1, .transport = MBM_TRANSPORT_RTU, .matter = MBM_MATTER_ENERGY, .reg = 1, .scale = 1 };
    strcpy(a.mbm[0].name, "zaehler");
    b = a; b.mbm[0].reg = 2; b.mbm[0].scale = 0.001f;
    CHECK(!matter_mbm_endpoints_differ(&a, &b), "anderes Register verlangt einen Neustart");
    b = a; b.mbm[0].matter = MBM_MATTER_POWER;
    CHECK(matter_mbm_endpoints_differ(&a, &b), "anderer Matter-Typ ohne Neustart");
    b = a; b.mbm[0].enable = 0;
    CHECK(matter_mbm_endpoints_differ(&a, &b), "abgeschaltete Zeile ohne Neustart");
    b = a; b.modbus.rs485_role = MB_ROLE_SLAVE;
    CHECK(matter_mbm_endpoints_differ(&a, &b), "Rolle Slave ohne Neustart");
    b = a; b.modbus.enable = 0;
    CHECK(matter_mbm_endpoints_differ(&a, &b), "Modbus aus ohne Neustart");
    b = a; b.mbm[0].transport = MBM_TRANSPORT_TCP;
    CHECK(matter_mbm_endpoints_differ(&a, &b), "Netzwerk-Zeile behaelt ihren Endpunkt");
    if (failures == f0) printf("  Neustart nur, wenn sich die Sensor-Endpunkte aendern\n");

    mb_gateway_set_forwarding(true);
    CHECK(!forwarding(), "ohne CONFIG_MB_GATEWAY wird weitergeleitet");
    if (!forwarding()) printf("  ohne Gateway im Build leitet ein gespeichertes \"gateway\" nichts weiter\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mbmmatter.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
