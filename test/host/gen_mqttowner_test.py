#!/usr/bin/env python3
"""Builds a host test for MQTT subscriptions shared by several owners
(apps/full/main/app_mqtt.c).

Cut out verbatim: the subscription table, app_mqtt_subscribe_as(),
app_mqtt_unsubscribe_as() and the firmware modules' app_mqtt_subscribe() /
app_mqtt_unsubscribe(). The MQTT client is a recorder.

What it pins down, found by a review: a topic filter is one subscription at
the broker, whoever asked for it. A rule reading mqtt('output/set') shared
the bulk output command's subscription, and when that rule went the rule
engine's UNSUBSCRIBE took the command away until the next reconnect. Now a
filter is unsubscribed only once no owner wants it; a new connection starts
the record empty; a filter the full table could not record is never
unsubscribed blind.
OLD=1 cuts app_mqtt.c from git (OLDREV, default HEAD); before the fix the
owners did not exist, so the generator stops there.

  make -C test/host mqttowner
"""
import pathlib, sys
from cutter import Source

src = Source.at("apps/full/main/app_mqtt.c")
if "int app_mqtt_unsubscribe_as(unsigned owner, const char *topic)" not in src.text:
    sys.exit("FEHLER: app_mqtt_unsubscribe_as() fehlt -- ein UNSUBSCRIBE der Regeln trifft auch die Module")
hdr = Source.at("apps/full/main/app_mqtt.h")
cuts = (src.defines("TOPIC_MAXLEN")
        + hdr.defines("APP_MQTT_OWNER_FW", "APP_MQTT_OWNER_RULES")
        + src.func("static bool make_topic(const char *topic, char *buf, size_t buf_len)")
        + src.span("#define SUBS_MAX      64", "static bool              s_subs_full;")
        + src.func("static void subs_clear(void)")
        + src.func("static void subs_add(unsigned owner, const char *topic)")
        + src.func("static int subs_remove(unsigned owner, const char *topic)")
        + src.func("int app_mqtt_subscribe_as(unsigned owner, const char *topic, int qos)")
        + src.func("int app_mqtt_unsubscribe_as(unsigned owner, const char *topic)")
        + src.func("int app_mqtt_subscribe(const char *topic, int qos)")
        + src.func("int app_mqtt_unsubscribe(const char *topic)"))

HARNESS = r"""
/* GENERATED by gen_mqttowner_test.py -- do not edit; edit app_mqtt.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef int *SemaphoreHandle_t;
#define portMAX_DELAY 0
static void xSemaphoreTake(SemaphoreHandle_t m, int t) { (void)m; (void)t; }
static void xSemaphoreGive(SemaphoreHandle_t m) { (void)m; }
typedef struct { char mqtt_topic_prefix[64]; } app_config_t;
static app_config_t cfg = { "dev" };
static const app_config_t *app_config_get(void) { return &cfg; }
#define strlcpy test_strlcpy
static size_t test_strlcpy(char *d, const char *s, size_t n) { size_t l = strlen(s); if (n) { size_t c = l < n - 1 ? l : n - 1; memcpy(d, s, c); d[c] = 0; } return l; }

typedef int *esp_mqtt_client_handle_t;
static int client_obj; static esp_mqtt_client_handle_t s_client = &client_obj;
static char sent[64][200]; static int nsent;
static int esp_mqtt_client_subscribe(esp_mqtt_client_handle_t c, const char *t, int q)
{ (void)c; (void)q; if (nsent < 64) snprintf(sent[nsent++], 200, "SUB %s", t); return 1; }
static int esp_mqtt_client_unsubscribe(esp_mqtt_client_handle_t c, const char *t)
{ (void)c; if (nsent < 64) snprintf(sent[nsent++], 200, "UNSUB %s", t); return 1; }
static int mux_obj;

__CUT__

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
static bool did(const char *what) { for (int i = 0; i < nsent; i++) if (!strcmp(sent[i], what)) return true; return false; }

int main(void)
{
    printf("MQTT-Abonnements mit mehreren Besitzern\n");
    s_subs = calloc(SUBS_MAX, sizeof(*s_subs)); s_subs_mux = &mux_obj;

    app_mqtt_subscribe("output/set", 0);                                  /* dout */
    app_mqtt_subscribe_as(APP_MQTT_OWNER_RULES, "output/set", 0);          /* a rule reads it */
    app_mqtt_subscribe_as(APP_MQTT_OWNER_RULES, "sys/heartbeat", 0);
    nsent = 0;
    app_mqtt_unsubscribe_as(APP_MQTT_OWNER_RULES, "output/set");           /* the rule went */
    CHECK(!did("UNSUB dev/output/set"), "Regel entfernt: UNSUBSCRIBE fuer output/set, das dout noch braucht");
    app_mqtt_unsubscribe_as(APP_MQTT_OWNER_RULES, "sys/heartbeat");
    CHECK(did("UNSUB dev/sys/heartbeat"), "nur von den Regeln gelesenes Topic nicht abbestellt");
    nsent = 0;
    app_mqtt_unsubscribe("output/set");                                    /* the module as well */
    CHECK(did("UNSUB dev/output/set"), "ohne Besitzer nicht abbestellt");

    /* A new session: nothing recorded; modules subscribe again. */
    app_mqtt_subscribe_as(APP_MQTT_OWNER_RULES, "a/b", 0);
    subs_clear();
    app_mqtt_subscribe_as(APP_MQTT_OWNER_RULES, "a/b", 0);
    nsent = 0;
    app_mqtt_unsubscribe_as(APP_MQTT_OWNER_RULES, "a/b");
    CHECK(did("UNSUB dev/a/b"), "nach neuer Sitzung: Eintrag haengt fest");

    /* Table full: an unknown filter is not unsubscribed blind. */
    subs_clear();
    char t[32];
    for (int i = 0; i < SUBS_MAX + 2; i++) { snprintf(t, sizeof t, "fw/%d", i); app_mqtt_subscribe(t, 0); }
    nsent = 0;
    snprintf(t, sizeof t, "fw/%d", SUBS_MAX + 1);
    app_mqtt_unsubscribe_as(APP_MQTT_OWNER_RULES, t);
    CHECK(nsent == 0, "volle Tabelle: unbekannter Filter blind abbestellt");

    if (!failures) printf("  abbestellt erst ohne Besitzer; neue Sitzung leer; volle Tabelle bestellt nichts blind ab\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_mqttowner.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
