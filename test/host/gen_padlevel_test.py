#!/usr/bin/env python3
"""Builds a host test for a PWM header pad as a Matter Dimmable Plug-in Unit
(apps/matter/main/matter.cpp).

level_to_duty() and duty_to_level() are cut out verbatim with the duty
limit from aux_io.h.

What it pins down, new with the pads in the Matter firmware: a Matter level
(1..254) maps onto the whole duty range, 254 is 100 %, every level survives
the round trip to a duty cycle and back (otherwise a controller writing a
level would read back another one), and a duty cycle never yields a level
outside 1..254 -- 0 is no level in LevelControl's lighting feature.
OLD=1 cuts matter.cpp from git (OLDREV, default HEAD); before the pads had
endpoints the functions did not exist, so the generator stops there.

  make -C test/host padlevel
"""
import pathlib, sys
from cutter import Source

src = Source.at("apps/matter/main/matter.cpp")
if "static uint16_t level_to_duty(uint8_t level)" not in src.text:
    sys.exit("FEHLER: level_to_duty() fehlt -- PWM-Pads haben keinen Matter-Endpoint")
aux = Source.at("components/board/aux_io.h")
cuts = (aux.defines("AUX_PWM_DUTY_MAX")
        + src.func("static uint16_t level_to_duty(uint8_t level)")
        + src.func("static uint8_t duty_to_level(uint16_t duty_pm)"))

HARNESS = r"""
/* GENERATED by gen_padlevel_test.py -- do not edit; edit matter.cpp. */
#include <stdint.h>
#include <stdio.h>

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("PWM-Pad als dimmbarer Matter-Zwischenstecker\n");
    CHECK(level_to_duty(254) == AUX_PWM_DUTY_MAX, "Level 254 -> %u statt %u", level_to_duty(254), AUX_PWM_DUTY_MAX);
    CHECK(level_to_duty(127) == 500, "Level 127 -> %u statt 500", level_to_duty(127));
    CHECK(level_to_duty(1) > 0, "Level 1 -> Tastgrad 0");
    for (int l = 1; l <= 254; l++)
        CHECK(duty_to_level(level_to_duty((uint8_t)l)) == l, "Level %d -> %u -> %u", l,
              level_to_duty((uint8_t)l), duty_to_level(level_to_duty((uint8_t)l)));
    for (unsigned d = 0; d <= AUX_PWM_DUTY_MAX; d++) {
        uint8_t l = duty_to_level((uint16_t)d);
        CHECK(l >= 1 && l <= 254, "Tastgrad %u -> Level %u", d, l);
    }
    CHECK(duty_to_level(0xFFFF) == 254, "Tastgrad ueber 100 %% -> %u", duty_to_level(0xFFFF));
    if (!failures) printf("  Level 1..254 auf den ganzen Tastgrad, jedes Level kommt unveraendert zurueck\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_padlevel.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
