#!/usr/bin/env python3
"""Builds a host test for saving the configuration (POST /api/config,
apps/full/main/web_server.c).

api_config_post() and the helpers it uses are cut out verbatim; the
configuration type is app_config.h as it is, cJSON ESP-IDF's own. Storage,
the Modbus master, the outputs and the HTTP server are recorded.

What it pins down, found by a review:
  - a value out of range or of the wrong type was skipped and the page said
    "Saved" (register 70000 polled register 0, Modbus address 0 kept the old
    one) -- now a 400 naming the field; a disabled Modbus row's hidden
    boxes do not count;
  - names were cut at 20 bytes, also inside a UTF-8 character, which makes
    an MQTT topic the broker drops the connection over -- now refused, as is
    a name that is not UTF-8;
  - the page sends the Modbus table with every save, so renaming an input
    reloaded the master and dropped every meter connection -- now only a
    changed table does;
  - a changed output invert reached the relays only through the MQTT path,
    empty in a build without MQTT -- now always, and a failure is a 500;
  - a name the validator refused came back as 200 with a JSON error.
OLD=1 cuts web_server.c from git (OLDREV, default HEAD).

  make -C test/host cfgpost
"""
import pathlib
from cutter import Source

src = Source.at("apps/full/main/web_server.c")
new = "static bool cfg_uint(" in src.text
cuts = src.defines("BODY_MAX") + (Source.at("components/board/web_common.c").func("bool web_json_uint(const cJSON *v, uint32_t lo, uint32_t hi, uint32_t *out)")
                                          if "web_json_uint(" in src.text else src.func("static bool json_uint(const cJSON *v, uint32_t lo, uint32_t hi, uint32_t *out)"))
common = "web_cfg_uint(" in src.text   # helpers and poll table moved to web_common.c
if common:
    wc  = Source.at("components/board/web_common.c")
    cuts += (Source.at("components/board/web_common.h").span("typedef struct { char field[40]; } web_cfg_err_t;", "typedef struct { char field[40]; } web_cfg_err_t;")
             + wc.func("void web_cfg_bad(web_cfg_err_t *bad, const char *where, const char *key)")
             + wc.func("bool web_cfg_uint(const cJSON *obj, const char *where, const char *key,")
             + wc.func("bool web_cfg_str(const cJSON *obj, const char *where, const char *key,")
             + src.func("static void parse_invert_array(cJSON *arr, di_config_t *out, int max, const char *where, web_cfg_err_t *bad)")
             + wc.span("static const struct { const char *name; uint8_t type; } k_mbm_types[] = {", "};")
             + wc.func("static void mbm_type_value(const char *s, uint8_t *out)")
             + wc.span("static const char *const k_mbm_matter[MBM_MATTER_MAX + 1] = {", "};")
             + wc.func("const char *web_mbm_config_parse(const cJSON *mbm_j, app_config_t *cfg,"))
    if "web_can_config_parse(" in src.text:   # the CAN fields, shared with the Matter firmware
        cuts += wc.func("void web_can_config_parse(const cJSON *can_j, app_config_t *cfg, web_cfg_err_t *bad)")
elif new:
    cuts += (src.span("typedef struct { char field[40]; } cfg_err_t;", "typedef struct { char field[40]; } cfg_err_t;")
             + src.func("static void cfg_bad(cfg_err_t *bad, const char *where, const char *key)")
             + src.func("static bool cfg_uint(const cJSON *obj, const char *where, const char *key,")
             + src.func("static bool cfg_str(const cJSON *obj, const char *where, const char *key,")
             + src.func("static void parse_invert_array(cJSON *arr, di_config_t *out, int max, const char *where, cfg_err_t *bad)"))
else:
    cuts += src.func("static void parse_invert_array(cJSON *arr, di_config_t *out, int max)")
if not common:
    cuts += src.span("static const struct { const char *name; uint8_t type; } k_mbm_types[] = {", "};")
    cuts += src.func("static void mbm_type_value(const char *s, uint8_t *out)")
if new or common:
    cuts = Source.at("components/board/app_config.c").func("bool app_config_utf8_ok(const char *s)") + cuts
cuts += src.func("static esp_err_t api_config_post(httpd_req_t *req)")

HARNESS = r"""
/* GENERATED by gen_cfgpost_test.py -- do not edit; edit web_server.c. */
#include <math.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "cJSON.h"
#include "app_config.h"

#define TAG "t"
#define ESP_LOGI(...) ((void)0)
#define ESP_LOGW(...) ((void)0)
#define ESP_LOGE(...) ((void)0)
#define LED_MODE_IO 0
#define LED_MODE_STATUS 1
typedef struct { size_t content_len; } httpd_req_t;
enum { HTTPD_400_BAD_REQUEST = 400, HTTPD_500_INTERNAL_SERVER_ERROR = 500 };
static int status; static char resp[256]; static const char *req_body;
static bool check_auth(httpd_req_t *r) { (void)r; return true; }
static esp_err_t send_denied(httpd_req_t *r) { (void)r; status = 401; return ESP_OK; }
static esp_err_t httpd_resp_send_err(httpd_req_t *r, int code, const char *m) { (void)r; status = code; snprintf(resp, sizeof resp, "%s", m); return ESP_OK; }
static esp_err_t httpd_resp_set_type(httpd_req_t *r, const char *t) { (void)r; (void)t; return ESP_OK; }
static esp_err_t httpd_resp_sendstr(httpd_req_t *r, const char *s) { (void)r; status = 200; snprintf(resp, sizeof resp, "%s", s); return ESP_OK; }
static esp_err_t send_json(httpd_req_t *r, const char *st, const char *b) { (void)r; status = atoi(st); snprintf(resp, sizeof resp, "%s", b); return ESP_OK; }
static int recv_body(httpd_req_t *r, char *buf, size_t cap) { (void)r; snprintf(buf, cap + 1, "%s", req_body); return (int)strlen(buf); }
/* Since web_common.c the helpers carry a web_ prefix; the stubs serve both. */
#define web_check_auth check_auth
#define web_send_denied send_denied
#define web_send_json send_json
#define web_recv_body recv_body

static app_config_t stored;
static int updates, reloads, dout_applies; static esp_err_t dout_result;
const app_config_t *app_config_get(void) { return &stored; }
esp_err_t app_config_update(const app_config_t *c) { updates++; stored = *c; return ESP_OK; }
bool app_config_io_names_ok(const app_config_t *c, const char **err)
{ if (!strcmp(c->di[0].name, "dup")) { *err = "two inputs have the same name"; return false; } return true; }
static void mb_tcp_master_reload(void) { reloads++; }
static esp_err_t aux_io_apply(void) { return ESP_OK; }
static void app_time_apply_tz(void) {}
static void sntp_sync_apply(void) {}
static void di_publish_all(void) {}
static esp_err_t dout_publish_all(void) { dout_applies++; return dout_result; }
/* A build without MQTT: nothing happens here. */
static void dout_on_mqtt_connected(void) {}
static bool app_mqtt_is_connected(void) { return false; }
static void aux_io_on_mqtt_connected(void) {}

__CUT__

static void post(const char *json)
{
    httpd_req_t rq = { strlen(json) };
    req_body = json; status = 0; resp[0] = 0; updates = reloads = dout_applies = 0;
    api_config_post(&rq);
}

static int failures;
#define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)

#define ROW(en, reg) "{\"enable\":" #en ",\"name\":\"zaehler\",\"host\":\"10.0.0.5\",\"port\":502,\"unit_id\":1," \
                     "\"fc\":\"holding\",\"reg\":" #reg ",\"type\":\"u16\",\"scale\":1,\"interval_ms\":5000}"

int main(void)
{
    printf("Konfiguration speichern (POST /api/config)\n");
    post("{\"mbm\":[" ROW(true, 5) "]}");
    CHECK(status == 200 && stored.mbm[0].reg == 5, "Ausgangslage: Status %d %s", status, resp);

    /* 1. Modbus master only reloaded when its table changed. */
    int f0 = failures;
    post("{\"di\":[{\"name\":\"tuer\"}],\"mbm\":[" ROW(true, 5) "]}");
    CHECK(status == 200 && reloads == 0, "Umbenennen mit unveraenderter Tabelle: %d Reload(s)", reloads);
    post("{\"mbm\":[" ROW(true, 6) "]}");
    CHECK(status == 200 && reloads == 1, "geaenderte Tabelle: %d Reload(s)", reloads);
    if (failures == f0) printf("  Modbus-Master: Reload nur bei geaenderter Tabelle\n");

    /* 2. Bad values refuse the save. */
    f0 = failures;
    static const struct { const char *json; const char *what; } bad[] = {
        { "{\"mbm\":[" ROW(true, 70000) "]}",            "Register 70000" },
        { "{\"modbus\":{\"address\":0}}",                "Modbus-Adresse 0" },
        { "{\"can\":{\"tx_interval_ms\":70000}}",        "tx_interval_ms 70000" },
        { "{\"can\":{\"bitrate\":\"500000\"}}",          "Bitrate als String" },
        { "{\"di\":[{\"name\":\"Rolllade Wohnzimmer\xc3\xbc\"}]}", "Name mit 21 Bytes (20 Zeichen)" },
        { "{\"di\":[{\"name\":\"ab\xc3\"}]}",            "Name mit abgeschnittenem UTF-8" },
        { "{\"sntp\":{\"server\":\"" "0123456789012345678901234567890123456789012345678901234567890123456789" "\"}}", "NTP-Server zu lang" },
    };
    for (unsigned i = 0; i < sizeof bad / sizeof bad[0]; i++) {
        post(bad[i].json);
        CHECK(status == 400 && updates == 0, "%s: Status %d, %d Mal gespeichert (%s)", bad[i].what, status, updates, resp);
    }
    post("{\"mbm\":[" ROW(false, 70000) "]}");
    CHECK(status == 200, "deaktivierte Zeile mit Register 70000 blockiert das Speichern (%d %s)", status, resp);
    post("{\"modbus\":{\"address\":null},\"di\":[{\"name\":\"Gr\xc3\xb6\xc3\x9f" "e\"}]}");
    CHECK(status == 200 && !strcmp(stored.di[0].name, "Gr\xc3\xb6\xc3\x9f" "e"), "null-Feld oder gueltiger Umlaut-Name abgelehnt (%d %s)", status, resp);
    if (failures == f0) printf("  ungueltige Felder: 400 mit Feldname; null und deaktivierte Zeilen bleiben erlaubt\n");

    /* 3. Name the validator refuses: 400 in plain text. */
    post("{\"di\":[{\"name\":\"dup\"}]}");
    CHECK(status == 400 && updates == 0, "doppelter Name: Status %d (%s)", status, resp);

    /* 4. Output invert without MQTT. */
    f0 = failures;
    post("{\"dout\":[{\"invert\":true}]}");
    CHECK(status == 200 && dout_applies >= 1, "Invertierung ohne MQTT nicht an die Relais gegeben (%d)", dout_applies);
    dout_result = ESP_FAIL;
    post("{\"dout\":[{\"invert\":false}]}");
    dout_result = ESP_OK;
    CHECK(status == 500, "fehlgeschlagenes Uebernehmen der Ausgaenge: Status %d", status);
    if (failures == f0) printf("  Ausgangs-Invertierung: auch ohne MQTT uebernommen, Fehler als 500\n");

    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_cfgpost.c")
out.write_text(HARNESS.replace("__CUT__", cuts))
print("erzeugt:", out.name)
