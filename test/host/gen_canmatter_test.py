#!/usr/bin/env python3
"""Builds a host test for CAN in the Matter firmware
(components/can/can_server.c) and for outputs reported to Matter whoever
switched them (components/board/dout.c).

Cut out verbatim: command_seen(), basic_tx_heartbeat(), basic_handle_rx()
and dout_modify() as built with CONFIG_APP_MATTER_ENABLE.

What it pins down, new with CAN in the Matter firmware:
  - the CAN server reads its uplink state and reports control frames through
    hooks the firmware hands it: no hooks -- heartbeat 0x01, no call; with
    them, 0x03 while online, and a DO, LED or buzzer frame is reported once;
  - an output switched by anyone (CAN, Modbus, web, Matter) is handed to
    Matter as the mask of channels that moved, and a write the expander
    refused moves nothing and reports nothing. Before this only the web
    page told Matter, so a controller kept showing an output switched over
    Modbus in its old state.
OLD=1 cuts the files from git (OLDREV, default HEAD); there command_seen()
did not exist, so the generator stops there.

  make -C test/host canmatter
"""
import pathlib
from cutter import Source

can  = Source.at("components/can/can_server.c", "apps/full/main/can_server.c")
dout = Source.at("components/board/dout.c")
cuts = (can.func("static void command_seen(void)")
        + can.func("static void basic_tx_heartbeat(void)")
        + can.func("static void basic_handle_rx(const rx_msg_t *m)"))
dcut = dout.func("esp_err_t dout_modify(uint8_t set, uint8_t clear, uint8_t toggle)")

HARNESS = r"""
/* GENERATED by gen_canmatter_test.py -- do not edit; edit can_server.c or dout.c. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

typedef int esp_err_t;
#define ESP_OK 0
#define ESP_FAIL -1
#define TAG "t"
#define ESP_LOGW(...) ((void)0)
static const char *esp_err_to_name(esp_err_t e) { (void)e; return "?"; }
#define CONFIG_APP_MATTER_ENABLE 1

/* ---- CAN side */
typedef struct { uint32_t id; uint8_t ide; uint8_t dlc; uint8_t data[8]; } rx_msg_t;
typedef struct { bool (*online)(void); void (*on_command)(void); bool psram_stack; } can_server_hooks_t;
static can_server_hooks_t s_hooks;
static uint16_t s_base = 0x100;
static uint8_t  s_last_do;
static uint8_t  hb[8]; static int nhb;
static bool basic_send(uint16_t id, const uint8_t *d, uint8_t dlc)
{ if (id == s_base) { memcpy(hb, d, dlc); nhb++; } return true; }
static bool basic_tx_di(uint8_t b) { (void)b; return true; }
static void basic_tx_do(void) {}
static uint8_t do_cmds;
static void basic_apply_do(uint8_t op, uint8_t mask) { (void)op; (void)mask; do_cmds++; }
static void led_set_rgb(uint8_t r, uint8_t g, uint8_t b) { (void)r; (void)g; (void)b; }
static void buzzer_beep_once(uint32_t f, uint32_t d) { (void)f; (void)d; }
static bool di_get(int i) { (void)i; return false; }
static bool up; static bool is_up(void) { return up; }
static int commands; static void on_cmd(void) { commands++; }

/* ---- output side */
#define NUM_DO 8
static bool s_state[NUM_DO];
static volatile uint8_t s_port;
static bool fail_write;
static esp_err_t write_outputs(void) { return fail_write ? ESP_FAIL : ESP_OK; }
static void dout_lock(void) {}
static void dout_unlock(void) {}
static uint8_t reported; static int reports;
static void matter_do_changed(uint8_t mask) { reported = mask; reports++; }

__CUT__

int main(void)
{
    int failures = 0;
    #define CHECK(c, ...) do { if (!(c)) { failures++; printf("  FEHLER: "); printf(__VA_ARGS__); printf("\n"); } } while (0)
    printf("CAN-Hooks und Ausgaenge an Matter\n");

    basic_tx_heartbeat();
    CHECK(nhb == 1 && hb[0] == 0x01, "ohne Hooks: Heartbeat 0x%02x statt 0x01", hb[0]);
    rx_msg_t m = { .id = 0x102, .dlc = 2, .data = { 1, 0x01 } };
    basic_handle_rx(&m);
    CHECK(do_cmds == 1, "ohne Hooks: DO-Befehl nicht ausgefuehrt");

    s_hooks = (can_server_hooks_t){ .online = is_up, .on_command = on_cmd };
    up = false; basic_tx_heartbeat(); CHECK(hb[0] == 0x01, "offline: Heartbeat 0x%02x", hb[0]);
    up = true;  basic_tx_heartbeat(); CHECK(hb[0] == 0x03, "online: Heartbeat 0x%02x statt 0x03", hb[0]);
    basic_handle_rx(&m);
    rx_msg_t led = { .id = 0x103, .dlc = 3, .data = { 1, 2, 3 } };
    basic_handle_rx(&led);
    rx_msg_t bz  = { .id = 0x104, .dlc = 2, .data = { 0xD0, 0x07 } };
    basic_handle_rx(&bz);
    rx_msg_t req = { .id = 0x105, .dlc = 0 };
    basic_handle_rx(&req);
    CHECK(commands == 3, "on_command %d-mal statt 3 (DO, LED, Summer; Abfrage zaehlt nicht)", commands);

    dout_modify(0x05, 0, 0);
    CHECK(reports == 1 && reported == 0x05, "Ausgaenge 1+3 an: Matter bekam Maske 0x%02x (%d Meldungen)", reported, reports);
    dout_modify(0x04, 0x01, 0);
    CHECK(reports == 2 && reported == 0x01, "nur Ausgang 1 bewegt: Maske 0x%02x", reported);
    fail_write = true;
    dout_modify(0x80, 0, 0);
    CHECK(reported == 0 && s_port == 0x04, "abgelehnter Schreibzugriff: Maske 0x%02x, Port 0x%02x", reported, s_port);

    if (!failures) printf("  Heartbeat und Befehle ueber Hooks; jede bewegte Ausgangsmaske geht an Matter\n");
    printf("%s\n", failures ? "FEHLER" : "alles in Ordnung");
    return failures ? 1 : 0;
}
"""
out = pathlib.Path(__file__).with_name("test_canmatter.c")
out.write_text(HARNESS.replace("__CUT__", cuts + dcut))
print("erzeugt:", out.name)
